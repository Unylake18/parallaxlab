        acende(2, extra=pk.anim(0.65, s=1.0, k=-1.0), rt=0.65)                 # sync: o chip acende enquanto as caixas descem abaixo do chão (b14k)
        lxk = pk.prende(TC(r"\X", 0, 0, 30, "c"), "ex", 40, -12)
