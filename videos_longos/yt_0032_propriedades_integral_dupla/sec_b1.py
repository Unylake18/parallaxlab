        self.gat("total sete vírgula")
        T2 = L([("r1", r"\Ci{4}"), ("p", "+"), ("r2", r"\Ci{3{,}06}"), ("ap", r"\approx"), ("t", r"\Ci{7{,}06}"), ("u", r"\ \text{kg}")], 1120, 700, 48)
        gm(self, T1, T2, [("r1", "r1"), ("p", "p"), ("r2", "r2"), (["r1", "p", "r2"], "t")], rt=1.4, copia=True, nota="mapa 3b (B1-4: a soma vira 7,06)")
