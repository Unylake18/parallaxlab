        pf = parte(FG, FG._ix["f"] + FG._ix["e1"], "f =")
        self.pena(pf)
        vx = ja_escrita(parte(FG, FG._ix["x2"], "x²"))          # nasce do voo (não da caneta)
        self.play(TransformFromCopy(lx2.f, vx, path_arc=-0.6), run_time=1.0)
        self.gat("uma rampa que cresce na direção vertical")
        ly2 = pal.prende(TP(r"\Mg{y^2}", 0, 0, 36), "yq", 46, -10, "l")
        self.pena(ly2)
        pg = parte(FG, FG._ix["g"] + FG._ix["e2"], "g =")
        self.pena(pg)
        vy = ja_escrita(parte(FG, FG._ix["y2"], "y²"))
        self.play(TransformFromCopy(ly2.f, vy, path_arc=-0.6), run_time=1.0)
