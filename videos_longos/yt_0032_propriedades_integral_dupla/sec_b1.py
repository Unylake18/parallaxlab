            ch_ = chips[i].copy().set_stroke(CI, W(3), 1)
            self.play(Create(ch_), *outros, *extra, run_time=rt)
            self.remove(ch_)
            chips[i].set_stroke(CI, W(3), 1)
            self.add(chips[i])
            self.pena(tchips[i], passo=0.03)
