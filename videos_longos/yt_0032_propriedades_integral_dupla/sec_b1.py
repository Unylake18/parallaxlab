        self.play(LaggedStart(*[Create(l) for l in gr16], lag_ratio=0.03), run_time=1.0)
        self.gat("independentemente dos pontos")         # C1: um ponto por célula da grade 8×8, que pula duas vezes dentro da célula
        rng = np.random.default_rng(32)
        h8 = 2 / 8
