        b2 = borda_ch(v2, GEO, 2)
        d2 = lin_px([v2.px(0, 0), v2.px(2, 2)], BR, 2, dash=(10, 8), z=5)
        st = seta_px(v1.px(2.15, 1), v1.px(2.65, 1), GEO, 3, 14)
        self.play(Transform(cp, M2o), GrowFromPoint(st, PX(*v1.px(2.15, 1))), run_time=1.4)
        self.remove(cp)
        self.add(M2o)
        self.play(FadeIn(b2), Create(d2), run_time=0.5)
        ly1 = TC(r"\Mg{y^2}", *v2.px(1, 2.22), 34, "c")
        self.pena(ly1)
        self.gat("a região continua a")
        esp = leg("ESPELHO NA DIAGONAL", 560, 880, GEO, "center", 26)
        self.pena(esp)
        self.gat("então as duas integrais")
        q = TC(r"\iint \Am{x^2}=\iint \Mg{y^2}", 1240, 330, 44)
        self.pena(q)
        self.gat("como somam trinta e")
        N = L([("n", r"\Ci{\dfrac{32}{3}}")], 1240, 480, 52)
        self.escreve(N, voos=[(gl(chip, "n"), N._ix["n"])])
        self.some(chip, chip_l, rt=0.4)
        self.gat("cada uma vale dezesseis")
        N2 = L([("n", r"\Ci{\dfrac{32}{3}}"), ("eq", "="), ("a", r"\Am{\dfrac{16}{3}}"), ("p", "+"), ("b", r"\Mg{\dfrac{16}{3}}")], 1240, 480, 52)
