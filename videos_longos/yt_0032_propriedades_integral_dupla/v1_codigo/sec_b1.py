"""yt_0032 · B1 · somar e multiplicar (alvos 04 a 07). 3D: b12 (rampas empilhadas) e b14 (k e camadas)."""
from lib32 import *


class PB1(B32):
    CANTO = False

    def corpo(self):
        # ── B1-1 · as regras do jogo (alvo 04) ──
        self.an("B1-1")
        poe_canto(self, "SOMAR E MULTIPLICAR")
        self.grade_on(CH, rt=0)
        mapa = img_chapa(arr_dens(64), CH)
        gr4 = grade_ch(4, CH, mixh(BG_, GEO, .6), 2, z=3)
        bord = borda_ch(CH, GEO, 3)
        sx, sy, lx, ly = eixos_chapa(CH)
        self.play(FadeIn(mapa), FadeIn(bord), GrowFromPoint(sx, CH.P(0, 0)), GrowFromPoint(sy, CH.P(0, 0)), run_time=1.0)
        self.pena(lx, ly)
        self.play(LaggedStart(*[Create(l) for l in gr4], lag_ratio=0.1), run_time=0.8)
        self.gat("duas funções éfe e")
        f1 = TC(r"\f,\ \g\ \text{integráveis em }B", 1120, 300, 44)
        self.pena(f1)
        self.gat("numa mesma região b")
        bB = TP(r"B", *CH.px(1.75, 1.8), 40)
        self.pena(bB)
        self.gat("uma constante cá")
        f2 = TC(r"k\ \text{constante}", 1120, 380, 44)
        self.pena(f2)
        self.gat("um número fixo")
        l1 = leg("UM NÚMERO FIXO", 1120, 425, GEO, "left", 26)
        self.pena(l1)
        self.gat("convergem para um único")
        l4 = leg("LIMITE DAS SOMAS DE RIEMANN", 1120, 800, CI, "left", 26)
        self.pena(l4)
        self.gat("esse valor é escrito")
        I = L([("ii", r"\iint_B"), ("f", r"\f(\X,\Y)"), ("d", r"\,\dX\,\dY")], 1120, 580, 64)
        self.pena(I)
        self.gat("integral dupla sobre b")
        self.sublinha(VGroup(*[I[0][i] for i in I._ix["ii"][:-1]]), 0.6)
        self.gat("sobre b de éfe")
        self.sublinha(I[0][I._ix["ii"][-1]], 0.6)
        self.gat("dê xis dê ípsilon a")
        self.sublinha(gl(I, "d"), 0.6)
        self.gat("a letra b indica")
        l2 = leg("B: A REGIÃO", 1120, 700, GEO, "left", 26)
        self.pena(l2)
        self.gat("e o dê xis dê ípsilon representa")
        l3 = leg("dx dy: ÁREA DE CADA RETANGUINHO", 1120, 740, GEO, "left", 26)
        self.pena(l3)
        self.marca("04")

        # ── B1-2 · somar funções (alvo 05), 3D b12 ──
        self.an("B1-2")
        col = [f1, f2, l1, l2, l3, l4, I, bB]
        self.some(*col, rt=0.4)
        pal = Palco3D(self, "b12", CAM_RAMPA, cam0=CAM_TOPO, s=0.0, cresceA=0.0, pousoB=0.0)
        entra3d(self, pal, saem=[mapa, gr4, bord, sx, sy, lx, ly], rt_x=0.6, rt_cam=5.0)      # pouso lento: a chapa vira palco 3D
        ex = pal.prende(TC(r"\X", 0, 0, 30, "c"), "ex")
        ez = pal.prende(TC(r"\Ci{z}", 0, 0, 30, "c"), "ez")
        self.pena(ez)
        self.gat("uma rampa que cresce na direção horizontal")
        self.pena(ex)
        self.gat("uma rampa que cresce na direção vertical")
        ey = pal.prende(TC(r"\Y", 0, 0, 30, "c"), "ey")
        self.pena(ey)
        self.gat("mesma grade para as")
        m1 = leg("MESMA GRADE, MESMOS PONTOS", 1120, 250, GEO, "left", 26)
        self.pena(m1)
        self.gat("primeiro levantamos as caixinhas")
        self.play(*pal.anim(2.0, cresceA=1.0), run_time=2.0)
        lx2 = pal.prende(TP(r"\Am{x^2}", 0, 0, 36), "xq", 40, 30, "l")
        self.pena(lx2)
        self.gat("depois colocamos em cima")
        self.play(*pal.anim(2.6, rate=linear, pousoB=1.0), run_time=2.6)
        ly2 = pal.prende(TP(r"\Mg{y^2}", 0, 0, 36), "yq", 46, -10, "l")
        self.pena(ly2)
        self.gat("em cada célula a")
        m2 = leg("CAIXA EM CIMA DE CAIXA", 1120, 395, GEO, "left", 26)
        self.pena(m2)
        self.gat("então a soma de riemann")
        PS = [("S", r"\sum"), ("lp", "("), ("f", r"\f"), ("p", "+"), ("g", r"\g"), ("rp", ")"), ("d", r"\,\Delta A")]
        A = L(PS, 1120, 340, 40)
        self.pena(A)
        self.gat("é exatamente a soma")
        Bq = L(PS + [("eq", "="), ("S1", r"\sum"), ("f1", r"\f"), ("d1", r"\,\Delta A"), ("p2", "+"), ("S2", r"\sum"), ("g2", r"\g"), ("d2", r"\,\Delta A")],
               1120, 340, 40)
        gm(self, A, Bq, [(k, k) for k, _ in PS] + [("S", "S1"), ("f", "f1"), ("d", "d1"), ("p", "p2"), ("S", "S2"), ("g", "g2"), ("d", "d2")],
           rt=1.6, copia=True, nota="mapa 1")
        self.remove(A)
        self.gat("e passando ao limite")
        lim = TC(r"\Downarrow\ \text{limite}", 1120, 480, 34)
        self.pena(lim)
        self.gat("a igualdade continua valendo")
        Ii = TC(r"\iint_B(\f+\g)=\iint_B\f+\iint_B\g", 1120, 580, 48)
        self.pena(Ii)
        self.gat("também é integrável")
        m3 = leg("E f + g É INTEGRÁVEL", 1120, 650, CI, "left", 26)
        self.pena(m3)
        self.marca("05")

        # ── B1-3 · uma conta de graça (alvo 06), 2D: espelho na diagonal ──
        self.an("B1-3")
        self.limpa(rt=0.5)
        v1, v2 = Vw(160, 780, 200), Vw(720, 780, 200)
        self.grade_on(v1, rt=0)
        n = 160
        M1 = faixas(v1, lambda X: X * X, n, "#1A1534", E1, 4.0, "x")
        b1 = borda_ch(v1, GEO, 2)
        d1 = lin_px([v1.px(0, 0), v1.px(2, 2)], BR, 2, dash=(10, 8), z=5)
        lx1 = TC(r"\Am{x^2}", *v1.px(1, 2.22), 34, "c")
        self.play(FadeIn(M1), FadeIn(b1), run_time=0.8)
        self.play(Create(d1), run_time=0.6)
        self.pena(lx1)
        self.gat("a chapa com densidade")
        chip_l = leg("MASSA DE x² + y²", 1240, 770, GEO, "left", 26)
        chip = L([("n", r"\Ci{\tfrac{32}{3}}"), ("u", r"\ \text{kg}")], 1240, 830, 44)
        self.pena(chip_l)
        self.gat("deu trinta e dois")
        self.pena(chip)
        self.gat("agora espelha a rampa")
        cp = M1.copy().set_z_index(2)
        self.add(cp)
        self.play(Rotate(cp, PI, axis=np.array([1, 1, 0]) / math.sqrt(2), about_point=v1.P(0, 0)), run_time=1.2)
        M2o = faixas(v2, lambda Y: Y * Y, n, "#1A1534", E2, 4.0, "y", z=2)      # o espelho leva a faixa vertical k na horizontal k
        b2 = borda_ch(v2, GEO, 2)
        d2 = lin_px([v2.px(0, 0), v2.px(2, 2)], BR, 2, dash=(10, 8), z=5)
        st = seta_px(v1.px(2.15, 1), v1.px(2.65, 1), GEO, 3, 14)
        self.play(Transform(cp, M2o), GrowFromPoint(st, PX(*v1.px(2.15, 1))), run_time=1.4)
        self.remove(cp)
        self.add(M2o)
        self.play(FadeIn(b2), Create(d2), run_time=0.5)
        ly1 = TC(r"\Mg{y^2}", *v2.px(1, 2.22), 34, "c")
        self.pena(ly1)
        self.gat("a região continua a")
        esp = leg("ESPELHO NA DIAGONAL", 560, 880, GEO, "center", 26)
        self.pena(esp)
        self.gat("então as duas integrais")
        q = TC(r"\iint \Am{x^2}=\iint \Mg{y^2}", 1240, 330, 44)
        self.pena(q)
        self.gat("como somam trinta e")
        N = L([("n", r"\Ci{\tfrac{32}{3}}")], 1240, 470, 52)
        self.escreve(N, voos=[(gl(chip, "n"), N._ix["n"])])
        self.some(chip, chip_l, rt=0.4)
        self.gat("cada uma vale dezesseis")
        N2 = L([("n", r"\Ci{\tfrac{32}{3}}"), ("eq", "="), ("a", r"\Am{\tfrac{16}{3}}"), ("p", "+"), ("b", r"\Mg{\tfrac{16}{3}}")], 1240, 470, 52)
        gm(self, N, N2, [("n", "n"), ("n", "a"), ("n", "b")], rt=1.4, copia=True, nota="mapa 2")
        self.remove(N)
        self.gat("nenhuma soma nova")
        s1 = leg("NENHUMA SOMA NOVA", 1240, 560, CI, "left", 26)
        self.pena(s1)
        self.gat("e a simetria do")
        s2 = leg("SOMA + SIMETRIA", 1240, 600, GEO, "left", 26)
        self.pena(s2)
        self.marca("06")

        # ── B1-4 · multiplicar por uma constante (alvo 07), 3D b14 ──
        self.an("B1-4")
        self.limpa(rt=0.5)
        self.grade_off(rt=0)
        pk = Palco3D(self, "b14", CAM_K, modo="k", k=1.0, ly=3.3, lz=2.25, c1=0.0, c2=0.0)
        pk.fundo.op.set_value(0.0)
        self.add(pk.fundo)
        self.play(pk.fundo.op.animate.set_value(1.0), run_time=0.8)
        self.gat("todas as caixinhas têm")
        c1 = leg("CAIXAS ESTICAM k VEZES", 1120, 330, GEO, "left", 26)
        self.pena(c1)
        self.gat("se cá vale dois")
        self.play(*pk.anim(1.2, k=2.0), run_time=1.2)
        self.gat("se vale meio")
        self.play(*pk.anim(1.2, k=0.5), run_time=1.2)
        self.gat("em todos os casos")
        self.play(*pk.anim(1.0, k=1.0), run_time=1.0)
        self.gat("e a constante sai")
        K1 = L([("ii", r"\iint_B"), ("kf", r"k\,\f"), ("eq", "="), ("k2", "k"), ("ii2", r"\iint_B\f")], 1120, 260, 48)
        self.pena(K1)
        self.gat("lê se a integral")
        self.sublinha(K1[0], 1.4)
        self.gat("agora junta com a")
        pk.rumo(CAM_BAIXO)
        self.play(*pk.anim(2.2, s=1.0, k=0.0, ly=2.45, lz=1.55), run_time=2.2)
        pk.set(modo="camadas")
        self.gat("uma camada de um")
        self.play(*pk.anim(1.4, c1=1.0), run_time=1.4)
        lc = pk.prende(TP(r"1\ \text{kg/m}^2", 0, 0, 30), "camada", 60, 40, "l")
        g1 = leg("CAMADA: 1 kg/m² NA CHAPA TODA", 1120, 420, GEO, "left", 26)
        self.pena(lc, g1, lag=0.3)
        self.gat("mais um reforço de")
        self.play(*pk.anim(1.4, c2=1.0), run_time=1.4)
        lr = pk.prende(TP(r"+2\ \text{kg/m}^2", 0, 0, 30), "reforco", -110, -40, "r")
        g2 = leg("REFORÇO: 2 kg/m² SÓ EM CIMA", 1120, 550, GEO, "left", 26)
        self.pena(lr, g2, lag=0.3)
        self.gat("a camada dá quatro")
        a1 = L([("a", r"1\cdot 4"), ("eq", "="), ("r", r"\Ci{4}")], 1120, 465, 40)
        self.pena(a1)
        self.gat("o reforço aproximadamente três")
        a2 = L([("a", r"2\cdot 1{,}53"), ("ap", r"\approx"), ("r", r"\Ci{3{,}06}")], 1120, 595, 40)
        self.pena(a2)
        T0 = L([("a1", r"1\cdot 4"), ("p", "+"), ("a2", r"2\cdot 1{,}53")], 1120, 700, 48)
        self.escreve(T0, voos=[(gl(a1, "a"), T0._ix["a1"]), (gl(a2, "a"), T0._ix["a2"])], atraso_caneta=0.4)
        T1 = L([("r1", r"\Ci{4}"), ("p", "+"), ("r2", r"\Ci{3{,}06}")], 1120, 700, 48)
        gm(self, T0, T1, [("a1", "r1"), ("p", "p"), ("a2", "r2")], rt=1.2, nota="mapa 3a")
        self.gat("total sete vírgula")
        T2 = L([("r1", r"\Ci{4}"), ("p", "+"), ("r2", r"\Ci{3{,}06}"), ("ap", r"\approx"), ("t", r"\Ci{7{,}06}"), ("u", r"\ \text{kg}")], 1120, 700, 48)
        gm(self, T1, T2, [("r1", "r1"), ("p", "p"), ("r2", "r2"), (["r1", "p", "r2"], "t")], rt=1.4, copia=True, nota="mapa 3b")
        self.remove(T1)
        self.gat("agora montado em camadas")
        g3 = leg("A MESMA MASSA, EM CAMADAS", 1120, 760, CI, "left", 26)
        self.pena(g3)
        self.marca("07")
        self.sai_fim()
