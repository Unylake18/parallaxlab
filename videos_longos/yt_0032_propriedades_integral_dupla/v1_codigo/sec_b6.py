R83 = math.sqrt(8 / 3)


def arco_r(v, r, cor, wpx, a0=0.0, a1=PI / 2, n=90, z=6):
    return lin_px([v.px(r * math.cos(a0 + (a1 - a0) * k / n), r * math.sin(a0 + (a1 - a0) * k / n)) for k in range(n + 1)], cor, wpx, z=z)


def caminho(t):
    return (2 * t + .35 * math.sin(PI * t), 2 * t - .35 * math.sin(PI * t))


