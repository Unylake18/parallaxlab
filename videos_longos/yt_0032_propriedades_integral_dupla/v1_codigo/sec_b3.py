    ANTES = "SINAL E COMPARAÇÃO"

    def corpo(self):
        # ── B3-1 · uma linha pode ter massa? (alvo 10) ──
        self.an("B3-1")
        self.secao("A SOLDA NÃO PESA")
        pal = Palco3D(self, "b31", CAM_BAIXO, n=16, cob=0.0, muro=0.0, alt=1.5, lz=1.95, marca=0.0)
        pal.fundo.op.set_value(0.0)
        self.add(pal.fundo)
        self.play(pal.fundo.op.animate.set_value(1.0), run_time=0.9)
        self.gat("uma curva sem espessura")
        sm = leg("SOLDA MATEMÁTICA: SÓ UMA CURVA", 1120, 660, GEO, "left", 26)
        self.pena(sm)
        self.gat("dá para cobri la")
        self.play(*pal.anim(1.4, cob=1.0), run_time=1.4)
        self.gat("existe um número eme")
        pal.set(marca=1.0)
        lM = pal.prende(TP(r"M", 0, 0, 30), "M", -10, 0, "r")
        self.pena(lM)
        f1 = TC(r"|\f|\le M", 1120, 390, 40)
        self.pena(f1)
        lim = leg("LIMITADA", 1260, 395, GEO, "left", 26)
        self.pena(lim)
        self.gat("a contribuição das células")
        self.play(*pal.anim(2.2, muro=1.0), run_time=2.2)
        self.gat("fica limitada por eme")
        f2 = TC(r"\iint\ \le\ M\cdot\Me{\text{área da cobertura}}", 1120, 500, 40)
        self.pena(f2)
        self.gat("a altura pode ser")
        l3 = leg("ALTO, MAS CADA VEZ MAIS FINO", 1120, 580, CORAL, "left", 26)
        self.pena(l3)
        self.gat("essa é a quarta")
        f0 = TC(r"B\text{ tem conteúdo nulo}\ \Rightarrow\ \iint_B\f=0", 1120, 280, 42)
        self.pena(f0)
        self.gat("mas fica tão fino")
        pal.set(n=32)                                    # a grade refina uma vez: o muro já afina (a cobertura encolhe)
        self.play(*pal.anim(0.8, muro=1.0), run_time=0.8)
        self.marca("10")

        # ── B3-2 · um muro de cem (alvo 11) ──
        self.an("B3-2")
        self.some(f0, f1, f2, lim, l3, sm, rt=0.4)
        self.gat("densidade de cem quilos")
        self.some(lM, rt=0.25)
        self.play(*pal.anim(2.0, alt=2.0, lz=2.35), run_time=2.0)
        l100 = pal.prende(TP(r"100", 0, 0, 30), "M", -10, 0, "r")
        esc = leg("ESCALA VERTICAL REDUZIDA", 420, 1010, GEO, "left", 26)
        self.pena(l100, esc, lag=0.3)
        self.gat("o muro coral fica")
        tit = T("COTA SUPERIOR", 1120, 250, 32, "left", CORAL)
        cab = VGroup(*[leg(c, 1140 + j * 230, 320, GEO, "left", 26) for j, c in enumerate(("n", "ÁREA (m²)", "COTA (kg)"))])
        self.pena(tit)
        self.pena(cab)
        linhas = [("64", "0,093", "9,3"), ("128", "0,046", "4,6"), ("256", "0,023", "2,3"), ("512", "0,011", "1,2"), ("1024", "0,006", "0,6")]
        gats = ["com sessenta e quatro", "dobra a resolução", "depois dois vírgula três", "depois um vírgula dois", "e continuando seis décimos"]
        for i, ((n, a, c), gg) in enumerate(zip(linhas, gats)):
            self.gat(gg)
            pal.set(n=int(n))
            row = VGroup(T(n, 1140, 320 + (i + 1) * 62, 32), T(a, 1370, 320 + (i + 1) * 62, 32), T(c, 1600, 320 + (i + 1) * 62, 32, "left", CORAL))
            self.pena(row, passo=0.045)
            if i == 0:
                self.gat("atenção é uma cota")
                cn = pal.prende(TPt("COTA, NÃO MASSA", 0, 0, 26, CORAL), "muro", 0, -30)
                self.pena(cn)
        self.gat("a altura continua cem")
        lf = leg("A ALTURA FICA; A LARGURA SOME", 1120, 740, GEO, "left", 26)
        self.pena(lf)
        self.gat("repetindo a contribuição fica")
        z0 = TC(r"\to 0", 1120, 800, 40)
        self.pena(z0)
        self.gat("então a solda matemática")
        na = leg("A SOLDA NÃO ACRESCENTA MASSA", 1120, 880, MEN, "left", 26)
        self.pena(na)
        self.gat("e contar zero duas")
        zz = TC(r"0+0=0", 1120, 940, 36)
        self.pena(zz)
        self.marca("11")

        # ── B3-3 · mas uma solda real pesa (alvo 12) ──
        self.an("B3-3")
        self.limpa(rt=0.5)
        self.grade_on(CH, rt=0.4)
        leve, pes = metais_liso(CH)
        bord = borda_ch(CH, GEO, 2)
        cord = cordao_ch(CH, 6)
        sx, sy, lx, ly = eixos_chapa(CH)
        self.play(FadeIn(leve), FadeIn(pes), FadeIn(bord), GrowFromPoint(sx, CH.P(0, 0)), GrowFromPoint(sy, CH.P(0, 0)), run_time=0.9)
        self.pena(lx, ly)
        self.play(deposita(cord, 1.6), run_time=1.6)
        self.gat("uma solda de verdade")
        cx = lin_px([CH.px(.8, 1.65), CH.px(1.4, 1.65), CH.px(1.4, 1.05), CH.px(.8, 1.05), CH.px(.8, 1.65)], BR, 2, dash=(8, 6), z=9)
        pn = painel(1100, 200, 700, 330)
        pn.set_z_index(2)
        lz1 = lin_px([CH.px(1.4, 1.65), (1100, 214)], GEO, 1.5, alpha=0.45, z=1)
        lz2 = lin_px([CH.px(1.4, 1.05), (1100, 516)], GEO, 1.5, alpha=0.45, z=1)
        self.play(Create(cx), run_time=0.6)
        self.play(Create(lz1), Create(lz2), Create(pn), run_time=0.8)
        pts = [(1150 + 600 * k / 40, 400 - 70 * math.sin(PI * k / 40)) for k in range(41)]
        zc = Cordao(pts, 28, z=8)
        meio = lin_px(pts, BR, 2, dash=(6, 5), z=12)
        ttl = T("CORDÃO DE 1 cm (ZOOM)", 1450, 250, 26, "center")
        self.play(deposita(zc, 2.0), run_time=2.0)
        self.play(Create(meio), run_time=0.6)
        self.pena(ttl)
        self.gat("com seis quilos por")
        l6 = leg("6 kg/m², LARGURA 1 cm → 1 mm", 1120, 650, GEO, "left", 26)
        self.pena(l6)
        self.gat("a linha da solda")
        Lm = TC(r"L\approx 2{,}25\ \text{m}", 1120, 600, 36)
        self.pena(Lm)
        Ch = L([("a", r"135\ \text{g}"), ("b", r"\ \to\ 13\ \text{g}"), ("c", r"\ \to\ 0")], 1120, 720, 40, caneta=False)
        pa, pb, pc = parte(Ch, Ch._ix["a"], "135"), parte(Ch, Ch._ix["b"], "13"), parte(Ch, Ch._ix["c"], "0")
        self.gat("com um centímetro de")
        g1 = TP(r"\approx 135\ \text{g}", 1450, 480, 34)
        self.pena(g1)
        self.pena(pa)
        self.gat("com um milímetro uns")
        ttl2 = T("CORDÃO DE 1 mm (ZOOM)", 1450, 250, 26, "center")
        g2 = TP(r"\approx 13\ \text{g}", 1450, 480, 34)
        self.play(Transform(zc, Cordao(pts, 2.8, z=8)), FadeOut(ttl), FadeOut(g1), run_time=1.4)
        self.remove(ttl, g1)
        self.pena(ttl2, g2, lag=0.2)
        self.pena(pb)
        self.gat("e conforme a largura")
        g3 = TP(r"\to 0\ \text{g}", 1450, 480, 34)
        self.play(Transform(zc, Cordao(pts, 1.2, z=8, corpo=BR, borda=BR, escama=BR)), FadeOut(meio), FadeOut(g2), run_time=1.4)
        self.remove(meio, g2)
        self.pena(g3)
        self.pena(pc)
        self.gat("uma massa realmente concentrada")
        mq = leg("E UMA MASSA SÓ NA LINHA?", 1120, 780, GEO, "left", 26)
        self.pena(mq)
        self.gat("aí usamos uma densidade")
        lk = leg("kg/m (MASSA NUMA LINHA) → INTEGRAL DE LINHA", 1120, 820, MEN, "left", 26)
        self.pena(lk)
        self.marca("12")
        self.sai_fim()
