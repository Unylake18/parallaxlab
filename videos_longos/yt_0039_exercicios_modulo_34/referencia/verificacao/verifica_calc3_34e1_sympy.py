# Verificação sympy · Cálculo III · 3.4-E1 (yt_0039 · EP. 14) · exercícios integradores do módulo 3.4
# Rodar: python verifica_calc3_34e1_sympy.py  (todas as linhas devem dar True)
import sympy as sp
x, y, u, v, r, t, k, a, b, z, R = sp.symbols('x y u v r theta k a b z R', positive=True)
th = t
ok = []
def chk(nome, cond):
    cond = bool(cond)
    ok.append(cond); print(f"{len(ok):02d} {nome}: {cond}")

# ---------- H1 / E5 · meia arruela 1 <= r <= 2, y >= 0 ----------
A_arr = sp.integrate(sp.integrate(r, (r, 1, 2)), (th, 0, sp.pi))
chk("E5 área meia arruela = 3π/2", sp.simplify(A_arr - 3*sp.pi/2) == 0)
chk("E5 área = π(4-1)/2 pela diferença de meios discos", sp.simplify(sp.pi*4/2 - sp.pi*1/2 - A_arr) == 0)
Mx_h_in = sp.integrate(r*sp.sin(th)*r, (r, 1, 2))
chk("E5 de dentro (homog.) = (7/3) sen θ", sp.simplify(Mx_h_in - sp.Rational(7, 3)*sp.sin(th)) == 0)
chk("E5 [r³/3]₁² = 8/3 − 1/3 = 7/3", sp.Rational(8, 3) - sp.Rational(1, 3) == sp.Rational(7, 3))
chk("E5 ∫₀^π sen θ = [−cos θ]₀^π = 1 + 1 = 2", sp.integrate(sp.sin(th), (th, 0, sp.pi)) == 2 and (-sp.cos(sp.pi) + sp.cos(0)) == 2)
Mx_h = sp.integrate(Mx_h_in, (th, 0, sp.pi))
chk("E5 M_x (homog.) = 14/3", Mx_h == sp.Rational(14, 3))
yb_h = sp.simplify(Mx_h / A_arr)
chk("E5 ȳ homog. = (14/3)/(3π/2) = 28/(9π)", sp.simplify(yb_h - 28/(9*sp.pi)) == 0)
chk("E5 28/(9π) ≈ 0,990 < 1 (cai no buraco)", abs(float(yb_h) - 0.9903) < 5e-4 and float(yb_h) < 1)
chk("E5 x̄ = 0 (simetria: M_y = 0)", sp.integrate(sp.integrate(r*sp.cos(th)*r, (r, 1, 2)), (th, 0, sp.pi)) == 0)
m_k_in = sp.integrate((k*r)*r, (r, 1, 2))
chk("E5 massa de dentro (ρ = k r) = 7k/3", sp.simplify(m_k_in - 7*k/3) == 0)
m_k = sp.integrate(m_k_in, (th, 0, sp.pi))
chk("E5 massa (ρ = k r) = 7kπ/3", sp.simplify(m_k - 7*k*sp.pi/3) == 0)
Mx_k_in = sp.integrate(r*sp.sin(th)*(k*r)*r, (r, 1, 2))
chk("E5 M_x de dentro (ρ = k r) = k(16/4 − 1/4) sen θ = (15k/4) sen θ", sp.simplify(Mx_k_in - sp.Rational(15, 4)*k*sp.sin(th)) == 0)
Mx_k = sp.integrate(Mx_k_in, (th, 0, sp.pi))
chk("E5 M_x (ρ = k r) = 15k/2", sp.simplify(Mx_k - sp.Rational(15, 2)*k) == 0)
yb_k = sp.simplify(Mx_k/m_k)
chk("E5 ȳ (ρ = k r) = (15k/2)/(7kπ/3) = 45/(14π)", sp.simplify(yb_k - 45/(14*sp.pi)) == 0)
chk("E5 (15/2)·(3/7) = 45/14", sp.Rational(15, 2)*sp.Rational(3, 7) == sp.Rational(45, 14))
chk("E5 45/(14π) ≈ 1,023 > 1 (volta para a chapa)", abs(float(yb_k) - 1.0231) < 5e-4 and float(yb_k) > 1)
# fórmula geral homogênea e casos-limite
ag, bg = sp.symbols('a_g b_g', positive=True)
yb_gen = sp.Rational(4, 3)/sp.pi*(bg**3 - ag**3)/(bg**2 - ag**2)
chk("E6 fórmula geral ȳ = 4(b³−a³)/(3π(b²−a²)) com a=1,b=2 = 28/(9π)", sp.simplify(yb_gen.subs({ag: 1, bg: 2}) - 28/(9*sp.pi)) == 0)
chk("E6 a → 0: ȳ → 4b/(3π) (meio disco)", sp.simplify(sp.limit(yb_gen, ag, 0) - 4*bg/(3*sp.pi)) == 0)
chk("E6 a → b: ȳ → 2b/π (arame semicircular)", sp.simplify(sp.limit(yb_gen, ag, bg) - 2*bg/sp.pi) == 0)
chk("E6 (b³−a³)/(b²−a²) = (a²+ab+b²)/(a+b)", sp.simplify((bg**3 - ag**3)/(bg**2 - ag**2) - (ag**2 + ag*bg + bg**2)/(ag + bg)) == 0)
# a partir de que buraco o centroide cai no buraco: ȳ < a  <=>  t = a/b > t*
tt = sp.symbols('t', positive=True)
eq = sp.Rational(4, 3)/sp.pi*(tt**2 + tt + 1)/(tt + 1) - tt
tstar = sp.nsolve(eq, tt, 0.5)
chk("E6 limiar t* = a/b ≈ 0,494 (a = 1, b = 2 dá t = 0,5: cai por um triz)", abs(float(tstar) - 0.4937) < 5e-4)
# ---------- E6 · Pappus ----------
# meio disco de raio a girando em torno da base → bola
chk("E6 Pappus meio disco: 2π·(4a/3π)·(πa²/2) = 4πa³/3", sp.simplify(2*sp.pi*(4*a/(3*sp.pi))*(sp.pi*a**2/2) - sp.Rational(4, 3)*sp.pi*a**3) == 0)
# Pappus como ∬ 2π y dA no meio disco (polares)
V_md = sp.integrate(sp.integrate(2*sp.pi*(r*sp.sin(th))*r, (r, 0, a)), (th, 0, sp.pi))
chk("E6 ∬ 2πy dA no meio disco = 4πa³/3", sp.simplify(V_md - sp.Rational(4, 3)*sp.pi*a**3) == 0)
# casca: meia arruela girando → casca esférica
V_casca = sp.Rational(4, 3)*sp.pi*(2**3 - 1**3)
chk("E6 casca: (4/3)π(8 − 1) = 28π/3", sp.simplify(V_casca - 28*sp.pi/3) == 0)
chk("E6 Pappus meia arruela: 2π·(28/9π)·(3π/2) = 28π/3", sp.simplify(2*sp.pi*(28/(9*sp.pi))*(3*sp.pi/2) - 28*sp.pi/3) == 0)
chk("E6 ȳ = V/(2πA) = (28π/3)/(3π²) = 28/(9π)", sp.simplify((28*sp.pi/3)/(2*sp.pi*3*sp.pi/2) - 28/(9*sp.pi)) == 0)
chk("E6 2π · 3π/2 = 3π²", sp.simplify(2*sp.pi*3*sp.pi/2 - 3*sp.pi**2) == 0)
# fatia deitada: ∬ 2π y dA = ∫ 2π y L(y) dy (meio disco: L = 2√(a²−y²))
V_cascas = sp.integrate(2*sp.pi*y*2*sp.sqrt(a**2 - y**2), (y, 0, a))
chk("E6 cascas ∫₀^a 2πy·2√(a²−y²) dy = 4πa³/3", sp.simplify(V_cascas - sp.Rational(4, 3)*sp.pi*a**3) == 0)
# toro R = 2, raio 1
V_toro_pappus = 2*sp.pi*2*sp.pi*1**2
zz = sp.symbols('zz', real=True)
V_toro_arr = sp.integrate(sp.pi*((2 + sp.sqrt(1 - zz**2))**2 - (2 - sp.sqrt(1 - zz**2))**2), (zz, -1, 1))
chk("E6 toro (R=2, a=1): Pappus 2π·2·π·1² = 4π²", sp.simplify(V_toro_pappus - 4*sp.pi**2) == 0)
chk("E6 toro por arruelas = 4π² (confere)", sp.simplify(V_toro_arr - 4*sp.pi**2) == 0)
chk("E6 4π² ≈ 39,48", abs(float(4*sp.pi**2) - 39.478) < 1e-3)
# ---------- E1 · faixa entre parábolas (Guidorizzi Ex. 4.2-5 e 4.2-1h) ----------
X, Y = u, v + u**2   # x = u, y = v + u²
Jm = sp.Matrix([[sp.diff(X, u), sp.diff(X, v)], [sp.diff(Y, u), sp.diff(Y, v)]])
chk("E1 jacobiano de (u, v + u²) = 1", sp.simplify(Jm.det()) == 1)
chk("E1 ida: ∂(u,v)/∂(x,y) de (x, y − x²) = 1", sp.Matrix([[1, 0], [-2*x, 1]]).det() == 1)
# área direta (fatias em pé): x em [0,1] comprimento 1; x em [1,2] comprimento 2 − x
A_dir = sp.integrate(1, (x, 0, 1)) + sp.integrate(2 - x, (x, 1, 2))
chk("E1 área direta = 1 + [2x − x²/2]₁² = 1 + 1/2 = 3/2", A_dir == sp.Rational(3, 2))
chk("E1 [2x − x²/2]₁² = (4 − 2) − (2 − 1/2) = 1/2", (4 - 2) - (2 - sp.Rational(1, 2)) == sp.Rational(1, 2))
A_uv = sp.integrate(sp.integrate(1, (u, 0, v)), (v, 1, 2))
chk("E1 área no plano u,v (trapézio) = ∫₁² v dv = 3/2", A_uv == sp.Rational(3, 2))
chk("E1 trapézio pela fórmula (1 + 2)/2 · 1 = 3/2", sp.Rational(1 + 2, 2) == sp.Rational(3, 2))
I1_in = sp.integrate(sp.exp(v)/v, (u, 0, v))
chk("E1 de dentro ∫₀^v (e^v/v) du = (e^v/v)·v = e^v", sp.simplify(I1_in - sp.exp(v)) == 0)
I1 = sp.integrate(I1_in, (v, 1, 2))
chk("E1 ∫₁² e^v dv = e² − e", sp.simplify(I1 - (sp.E**2 - sp.E)) == 0)
chk("E1 e² − e ≈ 4,671", abs(float(sp.E**2 - sp.E) - 4.6708) < 1e-3)
# conferência numérica no plano x,y (região original)
import mpmath as mp
f = lambda xx, yy: mp.e**(yy - xx**2)/(yy - xx**2)
num = mp.quad(lambda xx: mp.quad(lambda yy: f(xx, yy), [max(1 + xx**2, xx + xx**2), 2 + xx**2]), [0, 1, 2])
chk("E1 integral numérica na região original ≈ e² − e", abs(num - (mp.e**2 - mp.e)) < 1e-8)
# ---------- E2 · hipérboles u = xy, v = y/x ----------
xs, ys = sp.sqrt(u/v), sp.sqrt(u*v)
Jinv = sp.Matrix([[sp.diff(xs, u), sp.diff(xs, v)], [sp.diff(ys, u), sp.diff(ys, v)]]).det()
chk("E2 jacobiano direto de (√(u/v), √(uv)) = 1/(2v)", sp.simplify(Jinv - 1/(2*v)) == 0)
Jida = sp.Matrix([[y, x], [-y/x**2, 1/x]]).det()
chk("E2 ∂(u,v)/∂(x,y) = y·(1/x) − x·(−y/x²) = 2y/x", sp.simplify(Jida - 2*y/x) == 0)
chk("E2 2y/x = 2v ⇒ volta = 1/(2v)", sp.simplify(1/Jida.subs({x: xs, y: ys}) - 1/(2*v)) == 0)
A2 = sp.integrate(sp.integrate(1/(2*v), (u, 1, 2)), (v, 1, 2))
chk("E2 área = ∫₁²∫₁² 1/(2v) du dv = (ln 2)/2", sp.simplify(A2 - sp.log(2)/2) == 0)
chk("E2 (ln 2)/2 ≈ 0,347 ≈ 5,5 quadradinhos de 1/16", abs(float(sp.log(2)/2) - 0.3466) < 1e-3 and abs(float(sp.log(2)/2)*16 - 5.545) < 1e-2)
# conferência numérica no plano x,y: x de 1/√2 a √2
A2num = mp.quad(lambda xx: max(0, min(2/xx, 2*xx) - max(1/xx, xx)), [1/mp.sqrt(2), 1, mp.sqrt(2)])
chk("E2 área numérica direta ≈ (ln 2)/2", abs(A2num - mp.log(2)/2) < 1e-8)
m2 = sp.integrate(sp.integrate(u/(2*v), (u, 1, 2)), (v, 1, 2))
chk("E2 massa ρ = xy: ∫∫ u/(2v) = [u²/2]₁² · [ln v/2]₁² = (3/2)(ln 2/2) = (3/4) ln 2", sp.simplify(m2 - sp.Rational(3, 4)*sp.log(2)) == 0)
chk("E2 (3/4) ln 2 ≈ 0,520", abs(float(sp.Rational(3, 4)*sp.log(2)) - 0.5199) < 1e-3)
m2num = mp.quad(lambda xx: mp.quad(lambda yy: xx*yy, [max(1/xx, xx), max(max(1/xx, xx), min(2/xx, 2*xx))]), [1/mp.sqrt(2), 1, mp.sqrt(2)])
chk("E2 massa numérica direta ≈ (3/4) ln 2", abs(m2num - 0.75*mp.log(2)) < 1e-8)
# ---------- E3 · ler a região nos limites (Guidorizzi Ex. 4.2-2e) ----------
I3_in = sp.integrate(sp.sqrt(a**2 - r**2)*r, (r, 0, a))
chk("E3 de dentro ∫₀^a √(a²−r²) r dr = a³/3", sp.simplify(I3_in - a**3/3) == 0)
U = sp.symbols('U', positive=True)
chk("E3 com U = a² − r²: (1/2)∫₀^{a²} U^{1/2} dU = (1/2)(2/3)a³ = a³/3", sp.simplify(sp.Rational(1, 2)*sp.integrate(sp.sqrt(U), (U, 0, a**2)) - a**3/3) == 0)
I3 = sp.integrate(I3_in, (th, 0, sp.pi/2))
chk("E3 total = (π/2)(a³/3) = πa³/6", sp.simplify(I3 - sp.pi*a**3/6) == 0)
chk("E3 confere: (4πa³/3)/8 = πa³/6 (um oitavo da bola)", sp.simplify(sp.Rational(4, 3)*sp.pi*a**3/8 - sp.pi*a**3/6) == 0)
I3xy = mp.quad(lambda xx: mp.quad(lambda yy: mp.sqrt(max(0, 1 - xx**2 - yy**2)), [0, mp.sqrt(1 - xx**2)]), [0, 1])
chk("E3 iterada original em x, y (a = 1, numérica) = π/6", abs(I3xy - mp.pi/6) < 1e-6)
# ---------- E4 · elipse e meia elipse com ρ = k y (Guidorizzi 4.2-4, 4.2-6, 4.3-1b) ----------
Je = sp.Matrix([[a*sp.cos(th), -a*r*sp.sin(th)], [b*sp.sin(th), b*r*sp.cos(th)]]).det()
chk("E4 jacobiano das polares esticadas = abr", sp.simplify(Je - a*b*r) == 0)
chk("E4 a²r²cos²/a² + b²r²sen²/b² = r² ≤ 1", sp.simplify((a*r*sp.cos(th))**2/a**2 + (b*r*sp.sin(th))**2/b**2 - r**2) == 0)
Ael = sp.integrate(sp.integrate(a*b*r, (r, 0, 1)), (th, 0, 2*sp.pi))
chk("E4 área da elipse = ab·(1/2)·2π = πab", sp.simplify(Ael - sp.pi*a*b) == 0)
# meia elipse x² + 4y² <= 1, y >= 0: a = 1, b = 1/2, J = r/2
yE = r*sp.sin(th)/2
m4 = sp.integrate(sp.integrate(k*yE*r/2, (r, 0, 1)), (th, 0, sp.pi))
chk("E4 massa meia elipse ρ = k y: (k/4)·[r³/3]₀¹·2 = k/6", sp.simplify(m4 - k/6) == 0)
Mx4 = sp.integrate(sp.integrate(yE*k*yE*r/2, (r, 0, 1)), (th, 0, sp.pi))
chk("E4 M_x = (k/8)·[r⁴/4]₀¹·∫sen² = (k/8)(1/4)(π/2) = kπ/64", sp.simplify(Mx4 - k*sp.pi/64) == 0)
chk("E4 ∫₀^π sen²θ dθ = [θ/2 − sen 2θ/4]₀^π = π/2", sp.integrate(sp.sin(th)**2, (th, 0, sp.pi)) == sp.pi/2)
yb4 = sp.simplify(Mx4/m4)
chk("E4 ȳ = (kπ/64)/(k/6) = 6π/64 = 3π/32", sp.simplify(yb4 - 3*sp.pi/32) == 0)
chk("E4 3π/32 ≈ 0,295 (de 0,5 de altura)", abs(float(yb4) - 0.2945) < 1e-3)
chk("E4 x̄ = 0 (M_y = 0 pela simetria)", sp.integrate(sp.integrate(r*sp.cos(th)*k*yE*r/2, (r, 0, 1)), (th, 0, sp.pi)) == 0)
# conferência: meio disco unitário com ρ = k y, depois esticar y por 1/2
m_c = sp.integrate(sp.integrate(k*r*sp.sin(th)*r, (r, 0, 1)), (th, 0, sp.pi))
Mx_c = sp.integrate(sp.integrate((r*sp.sin(th))**2*k*r, (r, 0, 1)), (th, 0, sp.pi))
chk("E4 meio disco ρ = k y: ȳ = (kπ/8)/(2k/3) = 3π/16; × 1/2 = 3π/32", sp.simplify(Mx_c/m_c - 3*sp.pi/16) == 0 and sp.simplify((Mx_c/m_c)/2 - yb4) == 0)
chk("E4 homogênea: ȳ = 4b/(3π) com b = 1/2 → 2/(3π) ≈ 0,212", abs(float(2/(3*sp.pi)) - 0.2122) < 1e-3)
# direto em x, y
m4xy = sp.integrate(sp.integrate(k*y, (y, 0, sp.sqrt(1 - x**2)/2)), (x, -1, 1))
chk("E4 massa direta em x, y = k/6", sp.simplify(m4xy - k/6) == 0)
print()
print(f"{sum(ok)}/{len(ok)} True")
