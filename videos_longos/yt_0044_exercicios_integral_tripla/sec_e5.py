class PE5(B44):
    ANTES = "E SE A DENSIDADE CRESCER PARA FORA?"

    def corpo(self):
        # ── E5-1 · a lata na dobradiça: o eixo de giro vira o eixo z (alvo 19, C5.1–C5.2, GM17) ──────────────
        self.an("E5-1")
        self.titulo("A LATA NA DOBRADIÇA")
        # a lata do começo (H1), com o eixo central e a reta da parede, volta para a troca de eixos
        pal = self.palco("lataParede", OL, eixo=1.0, parede=1.0, seta=1.0, cota=0.0)
        rz = self.rot3(pal, "ez", r"\Z", size=38, ancora="c")
        self.entra(pal.fundo, rt=0.6)
        self.pena(rz)

        self.gat("a reta da parede vira o eixo z")
        self.degrau("C5.1a", "EIXO DE GIRO = EIXO z (a reta da parede vira o eixo z)")
        pal, rots = self.troca3d(pal, [rz], "lataDobradica", OL, eixo=1.0, seta=1.0, rots=[("ez", r"\Z", dict(size=38, ancora="c"))])
        l1 = leg("EIXO DE GIRO = EIXO z", C51, 190, EZ, "left", 32)
        self.pena(l1)
        self.col("E5-1", l1)

        self.gat("A lata escorrega para o lado")
        self.degrau("C5.1", "LATA: (x - R)^2 + y^2 <= R^2, 0 <= z <= h, rho = k")
        l2 = mixl([("t", "LATA:", GEO), ("m", r"(\X-R)^2+\Y^2\le R^2,\ 0\le\Z\le h,\ \de=k")], C51, 270, 36)
        self.pena(l2)
        self.col("E5-1", l2)

        self.gat("a distância até o eixo z")
        self.degrau("C5.1b", "I_z = iiint (x^2 + y^2) k dV")
        l3 = TC(r"I_{\Z}=\iiint(\X^2+\Y^2)\,k\,dV", C51, 370, 44)
        self.pena(l3)
        self.col("E5-1", l3)

        self.gat("o polo das cilíndricas no centro da lata")
        self.degrau("C5.2a", "polo no centro da lata: x = R + s cos theta, y = s sen theta, z = z; o fator continua s")
        # etapa 2: a lata sai (corte) e o painel DE CIMA entra já desenhado
        pn = painel2d44(60, 160, 900, 780)
        lb = leg("DE CIMA", 84, 202, GEO, "left", 26)
        v = Vista2D(220, 560, 300)
        circ = [(1 + math.cos(a), math.sin(a)) for a in np.linspace(0, 2 * PI, 97)]
        dfill = poly_px([v.P(*p) for p in circ], mixh("#16123A", GEO, 0.30), 1.0, z=1)
        dcont = v.linha(circ, GEO, 3)
        ex = v.linha([(-.3, 0), (2.35, 0)], E1, 2)
        ey = v.linha([(0, -1.15), (0, 1.15)], E2, 2)
        pO = v.ponto((0, 0), EZ, 11)
        pC = v.ponto((1, 0), BR, 7)
        t_, s_ = .9, .7
        Pc = (1 + s_ * math.cos(t_), s_ * math.sin(t_))
        fio_s = v.linha([(1, 0), Pc], SOMB, 5)
        qc = v.P(*Pc)
        cel = ret_px(qc[0] - 12, qc[1] - 12, qc[0] + 12, qc[1] + 12, fill=LI, fop=1.0, stroke=None, z=8)
        cC = v.P(1, 0)
        arc_t = lin_px([(cC[0] + 60 * math.cos(a), cC[1] - 60 * math.sin(a)) for a in np.linspace(0, t_, 24)], TH, 3, z=6)
        fio_o = v.linha([(0, 0), Pc], EZ, 3, dash=(9, 7))
        o0 = v.P(0, 0)
        eixoz = mixl([("t", "EIXO", BR), ("m", r"\Z")], 0, 0, 26)
        eixoz.shift(RIGHT * (o0[0] - 20 - pxof(eixoz.get_right())[0]) / 120 + UP * ((540 - (o0[1] - 34)) / 120 - eixoz.get_center()[1]))
        eixoz._txt = "EIXO z"
        tC0 = TC(r"C=(R,0)", cC[0] + 14, cC[1] + 30, 26, "l")
        tC = VGroup(placa_min(tC0), tC0)
        tC._txt = "C=(R,0)"
        ms = v.P(1 + .5 * s_ * math.cos(t_), .5 * s_ * math.sin(t_))
        tS = TC(r"\S", ms[0] + 18, ms[1] + 8, 30, "l")
        mt = v.P(1.27, .13)
        tT = TC(r"\T", mt[0] + 10, mt[1] - 6, 26, "l")
        mq = v.P(.45, .62)
        tQ = TC(r"\sqrt{\X^2+\Y^2}", mq[0] - 30, mq[1] - 28, 26, "r")
        gQ = VGroup(placa_min(tQ), tQ)
        gQ._txt = "sqrt(x2+y2)"
        mx_, my_ = v.P(2.4, 0), v.P(0, 1.2)
        tX = TC(r"\X", mx_[0], mx_[1] + 4, 28, "l")
        tY = TC(r"\Y", my_[0] + 18, my_[1], 28, "l")
        self.sai(pal.fundo, *rots, rt=0.35, extra=[FadeIn(pn), FadeIn(dfill), Create(dcont), Create(ex), Create(ey), FadeIn(pO), FadeIn(pC),
                                                     Create(fio_s), FadeIn(cel), Create(arc_t), Create(fio_o)])
        self.pena(lb, eixoz, tC, tS, tT, gQ, tX, tY)
        self.dentro(pn._painel, lb, eixoz, tC0, tS, tT, tQ, tX, tY)
        l4 = TC(r"\X=R+\S\cos\T,\ \ \Y=\S\sen\T,\ \ \Z=\Z", C51, 480, 40)
        self.pena(l4)
        cg_f, cf_f, cm_f = chipm([("t", "O FATOR CONTINUA", BR), ("m", r"\Js")], C51, 560, 26, LI)
        self.chip_pena(cg_f, cf_f, cm_f)
        self.col("E5-1", l4, cg_f, chips=1)

        self.gat("O quadrado da distância")
        self.degrau("C5.2b", "x^2 + y^2 = (R + s cos theta)^2 + (s sen theta)^2")
        l5 = L([("lhs", r"\X^2+\Y^2="), ("a", r"(R+\S\cos\T)^2"), ("p", "+"), ("b", r"(\S\sen\T)^2")], C51, 660, 40)
        self.pena(l5)
        self.col("E5-1", l5, chips=1)

        self.gat("Abre os quadrados")
        self.degrau("C5.2c", "= R^2 + 2Rs cos theta + s^2 cos^2 theta + s^2 sen^2 theta")
        l6 = L([("eq", "="), ("r2", r"R^2+2R\S\cos\T+"), ("c2", r"\S^2\cos^2\T"), ("p", "+"), ("s2", r"\S^2\sen^2\T")], C51 + 30, 760, 38)
        self.gm(17, l5, l6, [("a", ["r2", "c2"]), ("p", "p"), ("b", "s2")], rt=1.1, copia=True,
                nota="GM17a: (R + s cos)^2 + (s sen)^2 -> R^2 + 2Rs cos + s^2 cos^2 + s^2 sen^2")
        self.col("E5-1", l6, chips=1)

        self.gat("o cosseno ao quadrado mais o seno ao quadrado")
        self.degrau("C5.2", "= R^2 + 2Rs cos theta + s^2   (cos^2 + sen^2 = 1)")
        self.sub(gl(l6, "c2", "p", "s2"), rt=0.5, cor=MEN)
        l7 = L([("eq", "="), ("r2", r"R^2+2R\S\cos\T+"), ("s2", r"\S^2")], C51 + 30, 870, 46)
        self.gm(17, l6, l7, [("eq", "eq"), ("r2", "r2"), (["c2", "p", "s2"], "s2")], rt=1.0, copia=True,
                nota="GM17b: s^2 cos^2 + s^2 sen^2 -> s^2 (cos^2 + sen^2 = 1 acende em menta)")
        mol7 = caixa_men(l7, 10)
        lg7 = leg("cos² + sen² = 1", C51 + 520, 878, GEO, "left", 26)
        self.play(Create(mol7), run_time=0.4)
        self.pena(lg7)
        self.col("E5-1", l7, lg7, chips=1)
        self.marca("19_E5-1")
        self.sobe_sai(l1, l2, l3, l4, cg_f, l5, l6, lg7, mol7, pn, lb, dfill, dcont, ex, ey, pO, pC, fio_s, cel, arc_t, fio_o, eixoz, tC, tS, tT, gQ, tX, tY,
                      rt=0.35)

        # ── E5-2 · três pedaços: o atalho aparece sozinho (alvo 20, C5.3–C5.6, GM18) ───────────────────────────
        self.an("E5-2")
        self.titulo("TRÊS PEDAÇOS: O ATALHO APARECE", rt=0.25)
        pal = self.palco("lataDob3", OC, eixo=1.0, seta=1.0, p1=0.0, p2=0.0, p3=0.0)
        rz2 = self.rot3(pal, "ez", r"\Z", size=34, ancora="c")
        self.entra(pal.fundo, rt=0.5)
        self.pena(rz2)

        self.gat("cada um dos três pedaços")
        self.degrau("C5.2d", "I_z = k int_0^2pi int_0^R int_0^h (R^2 + 2Rs cos theta + s^2) s dz ds dtheta")
        m1 = L([("pre", r"I_{\Z}=k\int_0^{2\pi}\!\!\int_0^R\!\!\int_0^h\big("), ("r2", "R^2"), ("p1", "+"), ("cr", r"2R\S\cos\T"), ("p2", "+"), ("s2", r"\S^2"),
                ("pos", r"\big)\,\Js\,\dZ\,\dS\,\dT")], COLC, 180, 42)
        self.escreve(m1, voos=[(l7, ["r2", "p1", "cr", "p2", "s2"])], rt_voo=1.0, nota="o integrando R^2 + 2Rs cos + s^2 vem da moldura do E5-1")
        self.remove(l7)
        self.col("E5-2", m1)

        self.gat("O primeiro pedaço")
        self.degrau("C5.3", "(1) kR^2 iiint s dz ds dtheta = R^2 (k pi R^2 h) = MR^2")
        rR = self.rot3(pal, "fioR", "R", size=28, ancora="c")
        sq1, lq1 = legqn(LIL, 1, "DISTÂNCIA R ATÉ O CENTRO", 120, 1020, 30)
        self.play(*pal.anim(0.9, p1=1.0), FadeIn(sq1), run_time=0.9)
        self.pena(rR, lq1)
        n1 = num(1, COLC + 26, 310, 44)
        a1 = L([("k", "k"), ("r2", "R^2"), ("res", r"\iiint\S\,\dZ\,\dS\,\dT=R^2\cdot(k\pi R^2h)=MR^2")], COLC + 70, 310, 40)
        self.pena(n1)
        self.gm(18, m1, a1, [("r2", "r2")], rt=0.9, copia=True, nota="GM18-1: R^2 do integrando voa para a linha 1")
        lg1 = leg("TODA A MASSA A UMA DISTÂNCIA R", COLC + 60, 370, LIL, "left", 26)
        self.pena(lg1)
        self.col("E5-2", n1, a1, lg1)

        self.gat("O segundo")
        self.degrau("C5.4", "(2) 2kR (int_0^2pi cos theta dtheta)(int_0^R s^2 ds)(int_0^h dz) = 2kR * 0 * ... = 0")
        self.play(*pal.anim(0.9, p2=1.0), run_time=0.9)
        rmais = self.rot3(pal, "cmais", "+", size=30, ancora="c")
        rmenos = self.rot3(pal, "cmenos", "-", size=30, ancora="c")
        self.pena(rmais, rmenos)
        n2 = num(2, COLC + 26, 460, 44)
        a2 = L([("c", "2kR"), ("cr", r"\Big(\int_0^{2\pi}\cos\T\,\dT\Big)"), ("res", r"\Big(\int_0^R\S^2\dS\Big)\Big(\int_0^h\dZ\Big)=2kR\cdot0\cdots=0")],
               COLC + 70, 460, 38)
        self.pena(n2)
        self.gm(18, m1, a2, [("cr", "cr")], rt=0.9, copia=True, nota="GM18-2: 2Rs cos do integrando voa para a linha 2")
        lg2 = leg("VOLTA INTEIRA: O + E O − SE CANCELAM", COLC + 60, 525, GEO, "left", 26)
        self.pena(lg2)
        self.col("E5-2", n2, a2, lg2)

        self.gat("E o terceiro")
        self.degrau("C5.5", "(3) k iiint s^2 * s dz ds dtheta = k * h * R^4/4 * 2pi = pi k R^4 h/2 = MR^2/2")
        sq3, lq3 = legqn(SOMB, 3, "CASCA EM VOLTA DO CENTRO", 660, 1020, 30)
        rS = self.rot3(pal, "s", r"\S", size=28, ancora="c")
        self.play(*pal.anim(1.0, p3=1.0), FadeIn(sq3), run_time=1.0)
        self.pena(lq3, rS)
        n3 = num(3, COLC + 26, 620, 44)
        a3 = L([("k", "k"), ("int", r"\iiint"), ("s2", r"\S^2"), ("res", r"\cdot\S\,\dZ\,\dS\,\dT=k\cdot h\cdot\dfrac{R^4}{4}\cdot2\pi=\dfrac{\pi kR^4h}{2}=\dfrac{MR^2}{2}")],
               COLC + 70, 620, 38)
        self.pena(n3)
        self.gm(18, m1, a3, [("s2", "s2")], rt=0.9, copia=True, nota="GM18-3: s^2 do integrando voa para a linha 3")
        lg3 = leg("O GIRO PELO CENTRO DA LATA", COLC + 60, 690, SOMB, "left", 26)
        self.pena(lg3)
        self.col("E5-2", n3, a3, lg3)

        self.gat("Somando")
        self.degrau("C5.6", "I_z = MR^2 + 0 + MR^2/2 = (3/2) MR^2")
        m5 = TC(r"I_{\Z}=MR^2+0+\dfrac{MR^2}{2}=\dfrac32\,MR^2", COLC + 10, 800, 52)
        self.pena(m5)
        mol5 = caixa_men(m5)
        self.play(Create(mol5), run_time=0.4)
        self.col("E5-2", m5)

        self.gat("o triplo")
        lg5 = leg("TRÊS VEZES O GIRO PELO CENTRO", COLC, 920, CI, "left", 30)
        self.pena(lg5)
        self.col("E5-2", lg5)
        self.marca("20_E5-2")
        cg_i, cf_i, cm_i = chipm([("m", r"I_{\Z}=\tfrac32MR^2"), ("t", "(POLO NO CENTRO)", BR)], C53, 140, 28)
        self.sobe_sai(m1, n1, a1, lg1, n2, a2, lg2, n3, a3, lg3, lg5, sq1, lq1, sq3, lq3, rt=0.3)
        self.chip_vira(cg_i, cf_i, cm_i, m5, sai=[mol5], rt=0.45, nota="o (3/2)MR^2 vira o chip do E5-3")

        # ── E5-3 · conferindo com o polo na origem (alvo 21, C5.7–C5.12, GM19) ────────────────────────────────
        self.an("E5-3")
        self.titulo("CONFERINDO: POLO NA DOBRADIÇA", rt=0.25)
        self.sai(pal.fundo, rz2, rR, rmais, rmenos, rS, rt=0.3)

        self.gat("o polo na origem, na dobradiça")
        self.degrau("C5.7a", "(x - R)^2 + y^2 <= R^2 <=> x^2 + y^2 <= 2Rx")
        pn = painel2d44(60, 160, 640, 780)
        lb = leg("DE CIMA", 84, 202, GEO, "left", 26)
        v = Vista2D(130, 560, 250)
        dfill = poly_px([v.P(*p) for p in circ], mixh("#16123A", GEO, 0.30), 1.0, z=1)
        dcont = v.linha(circ, GEO, 3)
        ex = v.linha([(-.2, 0), (2.2, 0)], E1, 2)
        pO = v.ponto((0, 0), EZ, 11)
        self.play(FadeIn(pn), FadeIn(dfill), Create(dcont), Create(ex), FadeIn(pO), run_time=0.5)
        self.pena(lb)
        self.dentro(pn._painel, lb)
        k1 = TC(r"(\X-R)^2+\Y^2\le R^2\iff\X^2+\Y^2\le2R\X", C53, 240, 28)
        self.pena(k1)
        self.col("E5-3", cg_i, k1, chips=1)

        self.gat("o círculo vira")
        self.degrau("C5.7", "<=> s^2 <= 2Rs cos theta <=> s <= 2R cos theta, -pi/2 <= theta <= pi/2")
        raios = VGroup(*[v.linha([(0, 0), (2 * math.cos(t) * math.cos(t), 2 * math.cos(t) * math.sin(t))], SOMB if t == 0 else RO, 5 if t == 0 else 3)
                         for t in (-PI / 3, 0, PI / 4)])
        o0 = v.P(0, 0)
        arc_th = lin_px([(o0[0] + 70 * math.cos(a), o0[1] - 70 * math.sin(a)) for a in np.linspace(-PI / 2, PI / 2, 40)], TH, 3, z=6)
        ps = v.P(1.1, 0)
        tS = TC(r"\S=2R\cos\T", ps[0], ps[1] + 34, 26, "c")
        gS = VGroup(placa_min(tS), tS)
        gS._txt = "s = 2R cos"
        pt_ = v.P(.1, -1.15)
        tTh = TC(r"-\tfrac{\pi}{2}\le\T\le\tfrac{\pi}{2}", pt_[0], pt_[1] + 20, 28, "l")
        gTh = VGroup(placa_min(tTh), tTh)
        gTh._txt = "-pi/2 <= theta <= pi/2"
        self.play(*[Create(r) for r in raios], Create(arc_th), run_time=0.6)
        self.pena(gS, gTh)
        self.dentro(pn._painel, tS, tTh)
        k2 = TC(r"\iff\S^2\le2R\S\cos\T\iff\S\le2R\cos\T", C53, 240, 28)
        k2.shift(RIGHT * (pxof(k1.get_right())[0] + 8 - pxof(k2.get_left())[0]) / 120)
        self.pena(k2)
        self.col("E5-3", k2, chips=1)

        self.gat("a integral fica")
        self.degrau("C5.7b", "I_z = k int_{-pi/2}^{pi/2} int_0^{2R cos theta} int_0^h s^2 * s dz ds dtheta")
        k3 = TC(r"I_{\Z}=k\int_{-\pi/2}^{\pi/2}\!\int_0^{2R\cos\T}\!\!\int_0^h\S^2\cdot\Js\,\dZ\,\dS\,\dT", C53, 350, 40)
        self.pena(k3)
        self.col("E5-3", k3, chips=1)

        self.gat("A de dentro em s")
        self.degrau("C5.8", "int_0^{2R cos theta} s^3 ds = (2R cos theta)^4/4 = 4R^4 cos^4 theta")
        k4 = L([("pre", r"\int_0^{2R\cos\T}\S^3\dS=\dfrac{(2R\cos\T)^4}{4}=4R^4"), ("c4", r"\cos^4\T")], C53, 460, 40)
        self.pena(k4)
        self.col("E5-3", k4, chips=1)

        self.gat("baixar a potência")
        self.degrau("C5.9", "cos^4 theta = ((1 + cos 2theta)/2)^2 = (1 + 2cos 2theta + cos^2 2theta)/4")
        k5a = L([("c4", r"\cos^4\T"), ("eq", "=")], C53, 570, 38)
        self.escreve(k5a, voos=[(gl(k4, "c4"), "c4")], rt_voo=0.8, nota="cos^4 theta voa da linha de cima")
        k5b = L([("sq", r"\Big(\dfrac{1+\cos2\T}{2}\Big)^2")], C53, 570, 38)
        ao_lado(k5a, k5b, sel(k5a, "eq")[0], sel(k5b, "sq")[0], gap=12)
        k5b.shift(UP * (k5a[0][sel(k5a, "eq")[0]].get_center()[1] - k5b.get_center()[1]))
        self.gm(19, k5a, k5b, [("c4", "sq")], rt=1.0, copia=True, nota="GM19a: cos^4 theta -> ((1 + cos 2theta)/2)^2")
        k5c = L([("eq", "="), ("fr", r"\dfrac{1+2\cos2\T+\cos^22\T}{4}")], C53, 570, 38)
        ao_lado(k5b, k5c, sel(k5b, "sq")[0], 0, gap=12)
        k5c.shift(UP * (k5a[0][sel(k5a, "eq")[0]].get_center()[1] - k5c[0][0].get_center()[1]))
        self.pena(k5c)
        self.col("E5-3", k5a, k5b, k5c, chips=1)

        self.gat("de novo no cosseno de dois téta")
        self.degrau("C5.10", "cos^2 2theta = (1 + cos 4theta)/2 => cos^4 theta = 3/8 + (1/2) cos 2theta + (1/8) cos 4theta")
        k6a = TC(r"\cos^22\T=\dfrac{1+\cos4\T}{2}\ \Rightarrow\ \cos^4\T=", C53, 680, 36)
        self.pena(k6a)
        k6b = L([("res", r"\dfrac38+\dfrac12\cos2\T+\dfrac18\cos4\T")], C53, 680, 36)
        k6b.shift(RIGHT * (pxof(k6a.get_right())[0] + 10 - pxof(k6b.get_left())[0]) / 120 + UP * (k6a.get_center()[1] - k6b.get_center()[1]))
        self.gm(19, k5c, k6b, [("fr", "res")], rt=1.1, copia=True, nota="GM19b: (1 + 2cos 2theta + cos^2 2theta)/4 -> 3/8 + 1/2 cos 2theta + 1/8 cos 4theta")
        self.col("E5-3", k6a, k6b, chips=1)

        self.gat("Nos limites")
        self.degrau("C5.11", "int_{-pi/2}^{pi/2} cos^4 theta dtheta = [3theta/8 + sen 2theta/4 + sen 4theta/32] = 3pi/8 + 0 + 0")
        k7 = TC(r"\int_{-\pi/2}^{\pi/2}\cos^4\T\,\dT=\Big[\dfrac{3\T}{8}+\dfrac{\sen2\T}{4}+\dfrac{\sen4\T}{32}\Big]_{-\pi/2}^{\pi/2}=\dfrac{3\pi}{8}+0+0", C53, 790, 34)
        self.pena(k7)
        self.col("E5-3", k7, chips=1)

        self.gat("Juntando tudo")
        self.degrau("C5.12", "I_z = k * h * 4R^4 * 3pi/8 = (3/2)(k pi R^2 h) R^2 = (3/2) MR^2 ✓")
        k8 = TC(r"I_{\Z}=k\cdot h\cdot4R^4\cdot\dfrac{3\pi}{8}=\dfrac32(k\pi R^2h)R^2=\dfrac32MR^2\ \Me{\checkmark}", C53 + 10, 910, 42)
        self.pena(k8)
        mol8 = caixa_men(k8)
        self.play(Create(mol8), run_time=0.4)
        self.col("E5-3", k8, chips=1)
        self.marca("21_E5-3")

        self.sai_fim(rt=0.35)
