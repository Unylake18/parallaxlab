"""yt_0044 · Lote PE2: E2-1 a E2-4 (o tetraedro x + y + z ≤ 1 com ρ = x + y: sombra e sonda, massa, centroide, z̄ trocando a ordem).
C2.1–C2.16, GM7–GM10, alvos 08 a 11."""
from k44 import *  # noqa: F401,F403

COL = 1020
COLC = 780


def lado(A, B, ga=None, gb=0, gap=12):
    B.shift(RIGHT * (A.get_right()[0] - B.get_left()[0] + gap / 120))
    ya = A[0][ga].get_center()[1] if ga is not None else A.get_center()[1]
    B.shift(UP * (ya - B[0][gb].get_center()[1]))
    return B


class PE2(B44):
    ANTES = "A FOLHA QUE NÃO PESA"

    def eixos_tetra(self, pal, size=38):
        return [self.rot3(pal, n, t, size=size, ancora="c") for n, t in (("ez", r"\Z"), ("ex", r"\X"), ("ey", r"\Y"))]

    def corpo(self):
        # ── E2-1 · o tetraedro: a sombra e a sonda (alvo 08, C2.1) ──────────────────────────────────────────
        self.an("E2-1")
        pal = self.palco("tetraSonda", OT, sombra=0.0, sonda=0.0)
        rots = self.eixos_tetra(pal)
        self.titulo("O TETRAEDRO: SOMBRA E SONDA")
        self.entra(pal.fundo, rt=0.6)
        self.pena(*rots)

        self.gat("o canto de um cubo cortado por um plano")
        self.degrau("C2.1a", "SÓLIDO x + y + z <= 1, x, y, z >= 0, rho = x + y")
        l1 = mixl([("t", "SÓLIDO", GEO), ("m", r"\X+\Y+\Z\le1,\ \X,\Y,\Z\ge0,\ \de=\X+\Y")], COL, 170, 38)
        self.pena(l1)
        self.col("E2-1", l1)

        self.gat("Primeira pergunta")
        sqS, lqS = legq(SOMB, "SOMBRA", 120, 1020, 30)
        self.play(*pal.anim(0.5, sombra=1.0), FadeIn(sqS), run_time=0.5)
        self.pena(lqS)

        self.gat("a sonda entra pelo chão")
        self.degrau("C2.1b", "SONDA: entra z = 0, sai z = 1 - x - y")
        sqE, lqE = legq(AZC, "ENTRA z = 0", 360, 1020, 30)
        sqA, lqA = legq(CORAL, "SAI NO PLANO", 640, 1020, 30)
        self.play(*pal.anim(1.2, sonda=1.0), FadeIn(sqE), FadeIn(sqA), run_time=1.2)
        self.pena(lqE, lqA)
        l2 = mixl([("t", "SONDA:", GEO), ("m", r"\Az{\Z=0}\ \to\ \Co{\Z=1-\X-\Y}")], COL, 260, 40)
        self.pena(l2)
        self.col("E2-1", l2)

        self.gat("olhando de cima")
        self.degrau("C2.1c", "SOMBRA: 0 <= x <= 1, 0 <= y <= 1 - x")
        pn = painel2d44(COL, 560, 420, 380)
        lbp = leg("A SOMBRA", COL + 230, 600, GEO, "left", 26)
        v = Vista2D(COL + 70, 890, 300)
        tri_f = poly_px([v.P(0, 0), v.P(1, 0), v.P(0, 1)], mixh("#16123A", SOMB, .35), 1.0, z=1)
        tri_l = v.linha([(0, 0), (1, 0), (0, 1), (0, 0)], SOMB, 3)
        tira = v.linha([(.35, 0), (.35, .65)], "#E8ECF8", 5)
        pa, pb = v.ponto((.35, 0), AZC, 8), v.ponto((.35, .65), CORAL, 8)
        q = v.P(.55, .55)
        tr1 = TC(r"\Y=1-\X", q[0], q[1], 28, "l")
        q = v.P(1.05, 0)
        tx = TC(r"\X", q[0], q[1] + 10, 28, "l")
        q = v.P(-.09, .88)
        ty = TC(r"\Y", q[0], q[1], 28, "c")
        self.play(FadeIn(pn), FadeIn(tri_f), Create(tri_l), Create(tira), FadeIn(pa), FadeIn(pb), run_time=0.5)
        self.pena(lbp, tr1, tx, ty)
        self.dentro(pn._painel, lbp, tr1, tx, ty)
        l3 = mixl([("t", "SOMBRA:", SOMB), ("m", r"0\le\X\le1,\ \ 0\le\Y\le1-\X")], COL, 350, 40)
        self.pena(l3)
        self.col("E2-1", l3)

        self.gat("Juntando tudo")
        self.degrau("C2.1", "M = int_0^1 int_0^{1-x} int_0^{1-x-y} (x + y) dz dy dx")
        l4 = TC(r"M=\int_0^1\!\!\int_0^{1-\X}\!\!\int_0^{1-\X-\Y}(\X+\Y)\,\dZ\,\dY\,\dX", COL, 460, 42)
        self.pena(l4)
        self.col("E2-1", l4)
        self.marca("08_E2-1")
        self.sai(pn, lbp, tri_f, tri_l, tira, pa, pb, tr1, tx, ty, l1, l2, l3, l4, sqS, lqS, sqE, lqE, sqA, lqA, *rots[1:], rt=0.35)

        # ── E2-2 · a massa (alvo 09, C2.2–C2.6, GM7, GM8) ─────────────────────────────────────────────────────
        self.an("E2-2")
        pal, rots = self.troca3d(pal, [rots[0]], "tetraSonda", OC, sombra=1.0, sonda=1.0, rots=[("ez", r"\Z", dict(size=34, ancora="c"))])
        self.titulo("O TETRAEDRO: A MASSA", rt=0.15)

        self.gat("A de dentro é em z")
        self.degrau("C2.2", "int_0^{1-x-y} (x + y) dz = (x + y)[z]_0^{1-x-y} = (x + y)(1 - x - y)")
        m1 = TC(r"\int_0^{1-\X-\Y}(\X+\Y)\,\dZ=(\X+\Y)\Big[\Z\Big]_0^{1-\X-\Y}=(\X+\Y)(1-\X-\Y)", COLC, 190, 40)
        self.pena(m1)
        self.col("E2-2", m1)

        self.gat("uma letra nova")
        self.degrau("C2.3", "w = x + y (x parado): dw = dy; y = 0 -> w = x; y = 1 - x -> w = 1")
        m2 = mixl([("m", r"\ww=\X+\Y"), ("t", "(x PARADO):", GEO), ("m", r"\dw=\dY;\ \ \Y=0\to\ww=\X;\ \ \Y=1-\X\to\ww=1")], COLC, 300, 35)
        self.pena(m2)
        self.col("E2-2", m2)

        self.gat("vira uma integral em w")
        self.degrau("C2.4", "int_0^{1-x} (x + y)(1 - x - y) dy = int_x^1 w(1 - w) dw")
        m3a = L([("int", r"\int_0^{1-\X}"), ("a", r"(\X+\Y)"), ("b1", r"(1-"), ("b2", r"\X-\Y"), ("b3", ")"), ("d", r"\,\dY")], COLC, 420, 42)
        self.pena(m3a)
        self.sub(gl(m3a, "a"), gl(m3a, "b2"), rt=0.5, cor=UU)
        m3b = L([("eq", "="), ("int", r"\int_{\X}^{1}"), ("w1", r"\ww"), ("b1", r"(1-"), ("w2", r"\ww"), ("b3", ")"), ("d", r"\,\dw")], COLC, 420, 42)
        lado(m3a, m3b)
        self.gm(7, m3a, m3b, [("int", "int"), ("a", "w1"), ("b1", "b1"), ("b2", "w2"), ("b3", "b3"), ("d", "d")], rt=1.1, copia=True,
                nota="GM7: (x + y)(1 - x - y) dy -> w(1 - w) dw; limites 0, 1-x -> x, 1")
        self.col("E2-2", m3a, m3b)

        self.gat("Aplica os limites")
        self.degrau("C2.5", "= [w^2/2 - w^3/3]_x^1 = (1/2 - 1/3) - (x^2/2 - x^3/3) = 1/6 - x^2/2 + x^3/3")
        m4 = TC(r"=\Big[\dfrac{\ww^2}{2}-\dfrac{\ww^3}{3}\Big]_{\X}^{1}=\Big(\dfrac12-\dfrac13\Big)-\Big(\dfrac{\X^2}{2}-\dfrac{\X^3}{3}\Big)=\dfrac16-\dfrac{\X^2}{2}+\dfrac{\X^3}{3}",
                COLC, 560, 40)
        self.pena(m4)
        self.col("E2-2", m4)

        self.gat("a de fora, em x")
        self.degrau("C2.6a", "M = int_0^1 (1/6 - x^2/2 + x^3/3) dx = [x/6 - x^3/6 + x^4/12]_0^1")
        m5 = TC(r"M=\int_0^1\Big(\dfrac16-\dfrac{\X^2}{2}+\dfrac{\X^3}{3}\Big)\dX=\Big[\dfrac{\X}{6}-\dfrac{\X^3}{6}+\dfrac{\X^4}{12}\Big]_0^1", COLC, 700, 40)
        self.pena(m5)
        self.degrau("C2.6", "= 1/6 - 1/6 + 1/12 = 1/12")
        m6a = L([("eq", "="), ("s1", r"\dfrac16"), ("mn", "-"), ("s2", r"\dfrac16"), ("p", "+"), ("c", r"\dfrac1{12}")], COLC + 50, 830, 50)
        self.pena(m6a)
        self.sub(gl(m6a, "s1"), gl(m6a, "s2"), rt=0.5, cor=AL)
        m6b = L([("eq", "="), ("r", r"\dfrac1{12}")], COLC + 50, 830, 50)
        lado(m6a, m6b, 0, 0)
        self.gm(8, m6a, m6b, [("eq", "eq"), ("c", "r")], rt=0.9, copia=True, nota="GM8: 1/6 - 1/6 + 1/12 -> 1/12 (os dois 1/6 acendem e saem)")
        x0, _ = pxof(m6a.get_corner(UL))
        x1, _ = pxof(m6b.get_corner(DR))
        top = min(pxof(m.get_corner(UL))[1] for m in (m6a, m6b))
        bot = max(pxof(m.get_corner(DR))[1] for m in (m6a, m6b))
        mol6 = moldura(x0 - 14, top - 10, (x1 - x0) + 28, (bot - top) + 20, MEN, 1.0, 3, 12)
        self.play(Create(mol6), run_time=0.4)
        self.col("E2-2", m5, m6a, m6b)
        self.marca("09_E2-2")
        self.sobe_sai(m1, m2, m3a, m3b, m4, m5, m6a, mol6, rt=0.3)

        # ── E2-3 · conferindo sem integral: o centroide (alvo 10, C2.7–C2.10) ────────────────────────────────
        self.an("E2-3")
        pal, rots = self.troca3d(pal, rots, "tetraCent", OT, vertices=0.0, centroide=0.0, rots=[("ez", r"\Z", dict(size=38, ancora="c"))])
        self.titulo("CONFERINDO SEM INTEGRAL", rt=0.3)

        self.gat("sem fazer integral nenhuma")
        cg_m, cf_m, cm_m = chip(r"M=\frac1{12}", COL, 140, 28)
        self.chip_vira(cg_m, cf_m, cm_m, m6b, rt=0.6, nota="o M = 1/12 do E2-2 vira o chip do E2-3")
        self.col("E2-3", cg_m, chips=1)

        self.gat("a média dos quatro vértices")
        self.degrau("C2.7", "CENTROIDE = (1/4, 1/4, 1/4) (média dos 4 vértices)")
        xc, yc = pal.pt("cent")
        anel = circ_px(xc, yc, 12, GEO, 3, z=20)
        sqC, lqC = legq(GEO, "CENTROIDE = MÉDIA DOS 4 VÉRTICES", 120, 1020, 30)
        self.play(*pal.anim(0.4, vertices=1.0), run_time=0.4)
        self.play(*pal.anim(1.0, centroide=1.0), run_time=1.0)
        self.play(Create(anel), FadeIn(sqC), run_time=0.3)
        c1 = mixl([("t", "CENTROIDE", BR), ("m", r"=\Big(\frac14,\frac14,\frac14\Big)")], COL, 250, 44)
        self.pena(lqC, c1)
        self.col("E2-3", c1, chips=1)

        self.gat("a densidade no centroide")
        self.degrau("C2.8", "rho(centroide) = 1/4 + 1/4 = 1/2")
        c2 = mixl([("m", r"\de("), ("g", -10), ("t", "CENTROIDE", BR), ("g", -10), ("m", r")=\frac14+\frac14=\frac12")], COL, 350, 44)
        self.pena(c2)
        self.col("E2-3", c2, chips=1)

        self.gat("um terço da base vezes a altura")
        self.degrau("C2.9", "V = (1/2 * 1 * 1) * 1 * 1/3 = 1/6 (área da base * altura / 3)")
        c3 = TC(r"V=\Big(\frac12\cdot1\cdot1\Big)\cdot1\cdot\frac13=\frac16", COL, 450, 44)
        lg3 = leg("ÁREA DA BASE · ALTURA / 3", COL + 500, 458, GEO, "left", 26)
        self.pena(c3)
        self.pena(lg3)
        self.col("E2-3", c3, lg3, chips=1)

        self.gat("Multiplica")
        self.degrau("C2.10a", "rho(centroide) * V = 1/2 * 1/6 = 1/12 ✓")
        c4 = mixl([("m", r"\de("), ("g", -10), ("t", "CENTROIDE", BR), ("g", -10), ("m", r")\cdot V=\frac12\cdot\frac16=\frac1{12}\ \Me{\checkmark}")], COL + 10, 570, 48)
        self.pena(c4)
        mol4 = caixa_men(c4)
        self.play(Create(mol4), run_time=0.4)
        self.col("E2-3", c4, chips=1)

        self.gat("Por que funciona")
        self.degrau("C2.10b", "iiint (Ax + By + Cz + D) dV = V (A xbar_c + B ybar_c + C zbar_c + D)")
        c5 = TC(r"\iiint(A\X+B\Y+C\Z+D)\,dV=V\,(A\,\xb_c+B\,\yb_c+C\,\zb_c+D)", COL, 700, 30)
        self.pena(c5)
        self.col("E2-3", c5, chips=1)

        self.gat("Mas cuidado")
        self.degrau("C2.10", "só para densidade linear: rho = x^2 dá 1/60, não 1/96")
        mol_a, t_a = selo("SÓ PARA DENSIDADE LINEAR: ρ = x² DÁ 1/60, NÃO 1/96", COL, 830, AL, 26)
        self.play(Create(mol_a), run_time=0.3)
        self.pena(t_a)
        self.col("E2-3", t_a, chips=1)
        self.marca("10_E2-3")
        self.sai(cg_m, c1, c2, c3, lg3, c4, mol4, c5, mol_a, t_a, anel, sqC, lqC, rt=0.3)

        # ── E2-4 · onde o tetraedro equilibra: trocando a ordem (alvo 11, C2.11–C2.16, GM9, GM10) ───────────
        self.an("E2-4")
        pal, rots = self.troca3d(pal, rots, "tetraPlano", OC, plano=0.0, rots=[("ez", r"\Z", dict(size=34, ancora="c"))])
        self.titulo("ONDE O TETRAEDRO EQUILIBRA", rt=0.3)
        cg_m2, cf_m2, cm_m2 = chip(r"M=\frac1{12}", COLC, 140, 28)

        self.gat("a altura de equilíbrio")
        self.degrau("C2.11a", "M_xy = iiint z(x + y) dV")
        e1 = TC(r"\Mxy=\iiint\Z(\X+\Y)\,dV", COLC, 260, 44)
        self.pena(e1)
        self.chip_pena(cg_m2, cf_m2, cm_m2)
        self.col("E2-4a", e1, chips=1)

        self.gat("a de dentro de novo")
        self.degrau("C2.11", "int_0^{1-x-y} z(x + y) dz = (x + y)[z^2/2]_0^{1-x-y} = (x + y)(1 - x - y)^2/2")
        e2 = TC(r"\int_0^{1-\X-\Y}\Z(\X+\Y)\,\dZ=(\X+\Y)\Big[\dfrac{\Z^2}{2}\Big]_0^{1-\X-\Y}=\dfrac{(\X+\Y)(1-\X-\Y)^2}{2}", COLC, 380, 40)
        self.pena(e2)
        self.col("E2-4a", e2, chips=1)

        self.gat("a mesma troca de letra")
        self.degrau("C2.12", "em w: M_xy = int_0^1 int_x^1 (1/2) w(1 - w)^2 dw dx")
        PW = [("lhs", r"\Mxy="), ("i1", r"\int_0^1\!\!"), ("i2", r"\int_{\X}^{1}"), ("f", r"\frac12\,\ww(1-\ww)^2"), ("dw", r"\,\dw"), ("dx", r"\,\dX")]
        e3 = mixl([("t", "EM w:", UU), ("L", PW)], COLC, 500, 42)
        self.pena(e3)
        self.col("E2-4a", e3, chips=1)

        self.gat("Olha a região")
        self.degrau("C2.13", "0 <= x <= w <= 1: troca a ordem")
        # etapa 2: o tetra sai, o painel do triângulo entra; a linha EM w vira o chip do topo
        cg_w, cf_w, cm_w = chipL(PW, COLC, 140, 28)
        self.sai(pal.fundo, *rots, rt=0.3, extra=[FadeOut(cg_m2), FadeOut(e1), FadeOut(e2)])
        self.remove(cg_m2, e1, e2, e3)
        self.add(*e3.p)
        self.chip_vira(cg_w, cf_w, cm_w, e3.p[1], sai=[e3.p[0]], rt=0.5, nota="a linha EM w vira o chip do E2-4 (etapa 2)")
        self.col_zera("E2-4a")
        pn = painel2d44(60, 170, 640, 560)
        lbp = leg("O TRIÂNGULO EM (x, w)", 84, 212, GEO, "left", 26)
        v = Vista2D(150, 660, 420)
        trf = poly_px([v.P(0, 0), v.P(1, 1), v.P(0, 1)], mixh("#16123A", UU, .30), 1.0, z=1)
        trl = v.linha([(0, 0), (1, 1), (0, 1), (0, 0)], UU, 3)
        ax_x = v.linha([(0, 0), (1.05, 0)], E1, 3)
        ax_w = v.linha([(0, 0), (0, 1.08)], UU, 3)
        q = v.P(1.06, 0)
        tx = TC(r"\X", q[0], q[1], 30, "l")
        q = v.P(-.08, 1)
        tw = TC(r"\ww", q[0], q[1], 30, "l")
        q = v.P(.62, .42)
        twx = TC(r"\ww=\X", q[0], q[1], 26, "l")
        self.play(FadeIn(pn), FadeIn(trf), Create(trl), Create(ax_x), Create(ax_w), run_time=0.5)
        self.pena(lbp, tx, tw, twx)
        self.dentro(pn._painel, lbp, tx, tw, twx)
        f1 = leg("0 ≤ x ≤ w ≤ 1: TROCA A ORDEM", COLC, 260, UU, "left", 30)
        self.pena(f1)
        self.col("E2-4b", cg_w, f1, chips=1)

        self.gat("fica só o comprimento")
        self.degrau("C2.14", "M_xy = int_0^1 (1/2) w(1 - w)^2 (int_0^w dx) dw = int_0^1 (1/2) w^2 (1 - w)^2 dw")
        tira = v.linha([(0, .62), (.62, .62)], "#E8ECF8", 6)
        q = v.P(.05, .70)
        tcw = mixl([("t", "COMPRIMENTO", BR), ("m", r"\ww")], q[0], q[1], 26)
        gcw = VGroup(placa_min(tcw), tcw)
        gcw._txt = "COMPRIMENTO w"
        self.play(Create(tira), run_time=0.4)
        self.pena(gcw)
        self.dentro(pn._painel, tcw)
        f2a = L([("lhs", r"\Mxy="), ("i1", r"\int_0^1"), ("f", r"\frac12\,\ww(1-\ww)^2"), ("lp", r"\Big("), ("i2", r"\int_0^{\ww}"), ("dx", r"\dX"), ("rp", r"\Big)"),
                 ("dw", r"\dw")], COLC, 350, 40)
        self.gm(9, cf_w, f2a, [("lhs", "lhs"), ("i1", "i1"), ("f", "f"), ("i2", "i2"), ("dx", "dx"), ("dw", "dw")], rt=1.2, copia=True,
                nota="GM9: int_0^1 int_x^1 ... dw dx -> int_0^1 ... (int_0^w dx) dw (troca de ordem)")
        f2b = TC(r"=\int_0^1\frac12\,\ww^2(1-\ww)^2\,\dw", COLC, 350, 40)
        lado(f2a, f2b, sel(f2a, "lhs")[-1], 0)
        self.pena(f2b)
        self.col("E2-4b", f2a, f2b, chips=1)

        self.gat("Abre o quadrado")
        self.degrau("C2.15a", "w^2(1 - w)^2 = w^2 - 2w^3 + w^4")
        f3a = L([("a", r"\ww^2(1-\ww)^2")], COLC, 460, 42)
        self.pena(f3a)
        f3b = L([("eq", "="), ("b", r"\ww^2-2\ww^3+\ww^4")], COLC, 460, 42)
        lado(f3a, f3b)
        self.gm(10, f3a, f3b, [("a", "b")], rt=1.0, copia=True, nota="GM10: w^2(1 - w)^2 -> w^2 - 2w^3 + w^4")
        self.col("E2-4b", f3a, f3b, chips=1)

        self.gat("Integra termo a termo")
        self.degrau("C2.15", "int_0^1 (w^2 - 2w^3 + w^4) dw = [w^3/3 - w^4/2 + w^5/5]_0^1 = 1/3 - 1/2 + 1/5 = 10/30 - 15/30 + 6/30 = 1/30")
        f4 = TC(r"\int_0^1(\ww^2-2\ww^3+\ww^4)\,\dw=\Big[\dfrac{\ww^3}{3}-\dfrac{\ww^4}{2}+\dfrac{\ww^5}{5}\Big]_0^1=\dfrac13-\dfrac12+\dfrac15", COLC, 575, 38)
        self.pena(f4)
        f5a = TC(r"=\dfrac{10}{30}-\dfrac{15}{30}+\dfrac{6}{30}=\dfrac1{30}", COLC + 40, 690, 40)
        self.pena(f5a)
        self.col("E2-4b", f4, f5a, chips=1)

        self.gat("a metade que estava na frente")
        self.degrau("C2.16a", "M_xy = 1/2 * 1/30 = 1/60")
        f5b = TC(r"\Mxy=\dfrac12\cdot\dfrac1{30}=\dfrac1{60}", COLC + 40, 690, 40)
        f5b.shift(RIGHT * (pxof(f5a.get_right())[0] + 60 - pxof(f5b.get_left())[0]) / 120)
        self.pena(f5b)
        self.col("E2-4b", f5b, chips=1)

        self.gat("Dividindo pela massa")
        self.degrau("C2.16", "zbar = (1/60)/(1/12) = 12/60 = 1/5")
        f6 = TC(r"\zb=\dfrac{1/60}{1/12}=\dfrac{12}{60}=\dfrac15", COLC + 10, 820, 50)
        self.pena(f6)
        mol6 = caixa_men(f6)
        self.play(Create(mol6), run_time=0.4)
        self.col("E2-4b", f6, chips=1)

        self.gat("abaixo do centroide")
        lg6 = leg("ABAIXO DO CENTROIDE (1/4): A PONTA DE CIMA É LEVE", COLC, 945, GEO, "left", 28)
        self.pena(lg6)
        self.col("E2-4b", lg6, chips=1)
        self.marca("11_E2-4", agora=True)
        # o corte z = 1/5 e o tracejado 1/4 no tetraedro (o painel do triângulo sai; o tetra volta pequeno, OC)
