"""yt_0042 · H · a lata pesada trava em cartesianas e racha em esféricas (H1, alvo 01) e a grade da lata (H2, alvo 02).
H1: a lata com o degradê gira ~30° e para; a caneta escreve a coluna (DENSIDADE, LATA, MASSA, a integral cartesiana de fora para dentro, a primitiva de
dentro com k², TRAVA) e o painel EM ESFÉRICAS. H2: a lata vira traço; entram cilindro, página e andar uma por vez, saem, ficam as duas células lima com ?;
o canto troca para QUAL É O VOLUME DE CADA PEDAÇO?."""
from k42 import *


class PH(B42):
    ANTES = "A LATA PESADA"

    def corpo(self):
        # ── H1 ────────────────────────────────────────────────────────────────────────────────────────────
        self.an("H1")
        self.papel_on(rt=0)
        lata = self.palco("lata", cam_alvo("h1"), giro=-30.0, quina=0.0)
        rx = self.rot3(lata, "ex", r"\X", dx=18, dy=14, size=38)
        ry = self.rot3(lata, "ey", r"\Y", dx=18, dy=-6, size=38)
        rz = self.rot3(lata, "ez", r"\Z", dx=28, dy=-6, size=38)
        self.add(lata.fundo)
        self.gat("pensa numa lata")
        self.pena(rx, ry, rz, lag=0.15)
        self.play(lata.tr["giro"].animate(rate_func=smooth).set_value(0.0), run_time=2.6)
        self.gat("mais denso conforme se afasta")
        lf = self.rot3(lata, "fundo", "LEVE NA ORIGEM", dx=-60, dy=120, size=26, txtp=True, cor=CI)
        lq = self.rot3(lata, "quina", "PESADA NA QUINA", dx=-300, dy=110, size=26, txtp=True, cor=CI)
        self.pena(lf, lq, lag=0.3)
        self.gat("a densidade, rô")
        den = mixl([("t", "DENSIDADE", CI), ("L", [("rho", r"\de"), ("eq", "="), ("f", r"\Ci{\sqrt{\X^2+\Y^2+\Z^2}}")])], 1010, 180, 44)
        self.pena(den)
        self.degrau("H1", "DENSIDADE ρ = √(x²+y²+z²)")
        self.gat("quanto pesa essa lata")
        ms = mixl([("t", "LATA", GEO), ("m", r"\X^2+\Y^2\le 1,\quad 0\le\Z\le 1")], 1010, 270, 40)
        self.pena(ms)
        m_ = mixl([("t", "MASSA", GEO), ("L", [("eq", "="), ("int", r"\iiint"), ("f", r"\de"), ("dv", r"\,dV")])], 1010, 360, 44)
        self.pena(m_.p[0])
        self.escreve(m_.p[1], voos=[(gl(den.p[1], "f"), "f")], nota="H1: o integrando da massa voa da densidade")
        self.degrau("H1", "MASSA = ∭ ρ dV")
        self.gat("o x vai de menos um a um")
        car = L([("eq", "="), ("i1", r"\int_{-1}^{1}\!\!"), ("i2", r"\int_{-\sqrt{1-\X^2}}^{\sqrt{1-\X^2}}\!\!"), ("i3", r"\int_0^1"),
                 ("f", r"\Ci{\sqrt{\X^2+\Y^2+\Z^2}}"), ("dz", r"\,\dZ"), ("dy", r"\,\dY"), ("dx", r"\,\dX")], 1010, 480, 36)
        poe_parte(self, car)
        self.voos([(gl(m_.p[1], "f"), parte(car, sel(car, "f"), "integrando"))], rt=0.9, nota="H1: o integrando desce da massa")
        self.pena(parte(car, sel(car, "eq"), "="))
        self.pena(parte(car, sel(car, ["i1", "dx"]), "x"))
        self.degrau("H1", "limite de fora: x de −1 a 1")
        self.gat("o x vai de menos um a um")
        self.pena(parte(car, sel(car, ["i2", "dy"]), "y"))
        self.degrau("H1", "limite do meio: y")
        self.pena(parte(car, sel(car, ["i3", "dz"]), "z"))
        self.degrau("H1", "limite de dentro: z de 0 a 1")
        self.gat("a integral de dentro")
        pr = L([("i", r"\int"), ("f", r"\Ci{\sqrt{k^2+\Z^2}}"), ("dz", r"\,\dZ"), ("eq", "="), ("m", r"\dfrac12"), ("a", r"\Big["),
                ("t1", r"\Z\sqrt{k^2+\Z^2}"), ("mais", "+"), ("t2", r"k^2\ln\!\big(\Z+\sqrt{k^2+\Z^2}\big)"), ("b", r"\Big]")], 1010, 590, 34)
        poe_parte(self, pr)
        self.pena(parte(pr, sel(pr, ["i", "f", "dz", "eq"]), "∫ √(k²+z²) dz ="))
        com = mixl([("t", "COM", GEO), ("m", r"k^2=\X^2+\Y^2")], 1010, 645, 34)
        self.pena(com)
        self.pena(parte(pr, sel(pr, ["m", "a"]), "1/2 ["))
        self.pena(parte(pr, sel(pr, ["t1"]), "z√"))
        self.pena(parte(pr, sel(pr, ["mais", "t2", "b"]), "k² ln"))
        self.degrau("H1", "primitiva de dentro: ½[z√(k²+z²) + k² ln(z+√(k²+z²))]")
        self.gat("trava")
        mol, tt = selo("TRAVA", 1010, 700, AL, 30)
        self.pena(tt, extra=[Create(mol)])
        self.degrau("H1", "trava")
        self.gat("e em esféricas")
        pc = painel2d41(1010, 760, 400, 272)
        self.play(Create(pc), run_time=0.5)
        tp = leg("EM ESFÉRICAS", 1030, 800, GEO, "left", 26)
        self.pena(tp)
        vq = Vista2D(1060, 1010, 180)
        quad = Polygon(*[PX(*vq.P(*p)) for p in [(0, 0), (1, 0), (1, 1), (0, 1)]]).set_fill(mixh("#16123A", GEO, .25), 1).set_stroke(width=0).set_z_index(-1)
        bordq = vq.linha([(1, 0), (1, 1), (0, 1)], GEO, 3)
        self.play(FadeIn(quad), Create(bordq), run_time=0.5)
        pw = (1, 1 / math.tan(PI / 3))
        ptp = (math.tan(PI / 8), 1)
        s1 = vq.linha([(0, 0), pw], RO, 5)
        s2 = vq.linha([(0, 0), ptp], RO, 5)
        self.play(Create(s1), Create(s2), run_time=0.5)
        dg = vq.linha([(0, 0), (1, 1)], AL, 3, dash=(9, 7))
        self.gat("a fórmula racha")
        self.play(Create(dg), run_time=0.5)
        rq = leg("RACHA NA QUINA", 1040, 950, AL, "left", 30)
        self.pena(rq)
        self.col("H1", den, ms, m_, car, pr, com, tt)
        self.marca("01_H1")

        # ── H2 ────────────────────────────────────────────────────────────────────────────────────────────
        self.an("H2")
        coluna = VGroup(den, ms, m_, car, pr, com, tt, mol, pc, quad, bordq, s1, s2, dg, rq, tp)
        grade = self.palco("grade", cam_alvo("h2"), cil=0.0, pag=0.0, andar=0.0, cels=0.0)
        rz2 = pronto(self.rot3(grade, "ez", r"\Z", dx=30, dy=40, size=32))
        self.gat("a lata tem um eixo")
        grade.fundo.op.set_value(0.0)
        self.add(grade.fundo)
        self.play(lata.fundo.op.animate.set_value(0.0), grade.fundo.op.animate.set_value(1.0), FadeOut(lf), FadeOut(lq), FadeOut(rx), FadeOut(ry),
                  ReplacementTransform(rz, rz2), coluna.animate.shift(UP * 1.2).set_opacity(0), run_time=1.2)
        for m in (lata.fundo, lf, lq, rx, ry, coluna):
            m.clear_updaters()
        self.remove(lata.fundo, lf, lq, rx, ry, coluna)
        self.col_zera("H1")
        pn = painel41(1080, 250, 760, 480, alpha=.35, fop=1.0)
        tg = T("A GRADE DA LATA", 1120, 320, 30, "left", BR)
        self.play(Create(pn), run_time=0.5)
        self.pena(tg)
        self.dentro((1080, 250, 1840, 730), tg)
        l1 = mixl([("t", "CILINDROS", SOMB), ("m", r"\S=\text{cte}")], 1120, 410, 40)
        l2 = mixl([("t", "PÁGINAS", TH), ("m", r"\T=\text{cte}")], 1120, 490, 40)
        l3 = mixl([("t", "ANDARES", EZ), ("m", r"\Z=\text{cte}")], 1120, 570, 40)
        for (fr, ln, k) in (("primeiro, cilindros", l1, "cil"), ("depois, páginas", l2, "pag"), ("por fim, andares", l3, "andar")):
            self.gat(fr)
            self.pena(ln, extra=[grade.tr[k].animate(run_time=1.0, rate_func=linear).set_value(1.0)])
            self.degrau("H2", f"família {k} + linha")
        self.gat("repara nestes dois pedaços")
        self.play(*grade.anim(rt=0.8, rate=linear, cil=0.0, pag=0.0, andar=0.0), run_time=0.8)
        self.play(*grade.anim(rt=1.0, rate=linear, cels=1.0), run_time=1.0)
        a, b = grade.pt("celEixo"), grade.pt("celPar")
        q1 = T("?", a[0] - 40, a[1] - 40, 64, "left", LI)
        q2 = T("?", b[0] + 30, b[1] - 50, 64, "left", LI)
        self.gat("o mesmo delta s")
        l4 = mixl([("t", "MESMO", GEO), ("m", r"\DS,\ \DT,\ \DZ")], 1120, 670, 40)
        self.pena(l4)
        self.gat("qual é o volume")
        self.titulo("QUAL É O VOLUME DE CADA PEDAÇO?")
        self.pena(q1, q2, lag=0.2)
        self.marca("02_H2")
        self.sai_fim()
