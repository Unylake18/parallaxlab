"""Lote PB6: B6 — DE VOLTA À MESA (Three.js 'mesa_furo': C_34 → C_TOPO; reprise da puxada em CÂMERA LENTA ×0,5).
Mostradores r, I, ω, L (e v_θ) na coluna direita, fora da mesa. τ = dL/dt com I variável: τ_z = I α + İ ω (em r = 0,45 m: I = 0,0405, ω = 4,44,
İ = −0,054 ⇒ α = +5,9 rad/s²). v_θ × 2 e ω × 4. Triângulos de 0,20 s ao longo da espiral (0,090 m² cada). Em r = 0,45 m: v⃗ = v_r + v_θ
(8,5°), a tração tem componente ao longo de v⃗ (trabalho positivo). Energia nos estados com v_r = 0: K₀ = 0,225 J, K_f = 0,900 J, W = 0,675 J.
B6-8 e B6-9 em 2D (a mesa sai): barras de energia e o gráfico T × r com r̈ = 0 (0,75 N → 6,0 N)."""
from pecas24 import *  # noqa: F401,F403

T45 = F.TR + (F.R0 - F.VR * F.TR / 2 - 0.45) / F.VR       # tempo da puxada em que r = 0,45 m (fase de v_r constante)


class LoteB6(Lote24):
    def corpo(self):
        self.camA = self.camB = C34
        self.mov = mov_puxada(self)
        self.zp = zp_puxada(self)
        self.anda(1.0, tf=0.0)
        f3 = self.mesa()
        f3.op.set_value(0.0)
        self.canto("DE VOLTA À MESA")
        Z = 0.012

        def est():
            return F.puxada(self.tf() - self.tp)

        def pD():
            x, y = self.disco()
            return np.array([x, y, Z])

        def t_viva():
            a, o = self.tela(pD()), self.tela((0, 0, Z))
            u = (o - a) / max(np.linalg.norm(o - a), 1e-6)
            n = np.array([-u[1], u[0], 0])
            return VGroup(seta(a + 0.2 * u, a + 1.0 * u, FC, 6, tip=0.2), T(r"\vec T", 40, FC).move_to(a + 0.62 * u + 0.38 * n))

        # ── B6-1: C_34, órbita de 0,60 m; hipóteses; tração central ⇒ L constante ──
        self.an("B6-1")
        self.play(f3.op.animate.set_value(1.0), run_time=0.6)
        self.gat("de volta à mesa")
        self.hip("SEM ATRITO · FIO IDEAL · DISCO PEQUENO")
        Tv = vivo(t_viva)
        self.gat("a tração aponta sempre para o furo")
        self.play(OpVivo(Tv), run_time=0.5)
        A, ia = Mx(r"\vec\tau", "=", "0", r"\ \Rightarrow\ ", r"\vec L", r"\ \text{constante}")
        self.pilha.poe(A)
        self.gat("é uma força central")
        self.lei(A, ia, rt=1.3, metodo="lei")
        self.gat("mesmo enquanto alguém puxa")
        self.play(Indicate(gl(A, J(ia, 4)), color=LMAG, scale_factor=1.2), run_time=0.7)
        self.ate(0.99)

        # ── B6-2: C_TOPO; reprise da puxada ×0,5; mostradores; L = I ω → m r² ω = cte → r ÷ 2 ⇒ I ÷ 4 ⇒ ω × 4 ──
        self.an("B6-2")
        self.play(OpVivo(Tv, entra=False), run_time=0.3)
        self.remove(Tv)
        self.pilha.limpa()
        self.dolly(CTOPO, 1.6)
        self.selo("CÂMERA LENTA", "×0,5")
        mr = mostrador("r", lambda: est()["r"], 2, r"\mathrm{m}", VETC, P3(0.8, -1.55))
        mI = mostrador("I", lambda: est()["I"], 4, r"\mathrm{kg\,m^2}", MAS, P3(3.75, -1.55))
        mw = mostrador(r"\omega", lambda: est()["w"], 2, r"\mathrm{rad/s}", VEL, P3(0.8, -2.35))
        mL = mostrador("L", lambda: est()["L"], 3, r"\mathrm{kg\,m^2/s}", LMAG, P3(3.75, -2.35))
        self.play(OpVivo(mr), OpVivo(mI), OpVivo(mw), OpVivo(mL), run_time=0.5)
        self.pilha.base = -1.05                      # a CONTA para acima dos mostradores (y −1,25 … −3,45)
        B1, b1 = Mx("L", "=", "I", r"\omega")
        self.pilha.poe(B1)
        self.gat("no disco")
        self.lei(B1, b1, rt=0.9, metodo="lei")
        B2, b2 = Mx("I", "=", "m", "r^2")
        self.pilha.poe(B2)
        self.lei(B2, b2, rt=0.8, metodo="lei")
        self.gat("quando o raio cai pela metade")
        self.anda(0.5)
        self.tp = self.tf() + 0.15
        B3, b3 = Mx("m", "r^2", r"\omega", "=", r"\text{constante}")
        self.pilha.poe(B3)
        self.gm(B1, B3, (J(b1, 2), J(b3, 0, 1)), (J(b1, 3), J(b3, 2)), (J(b1, 1), J(b3, 3)), (J(b1, 0), J(b3, 4)), rt=1.4)
        B4, b4 = Mx("r", r"\div 2", r"\Rightarrow", "I", r"\div 4", r"\Rightarrow", r"\omega", r"\times 4", size=50)
        self.pilha.poe(B4)
        self.gat("cai para um quarto")
        self.lei(B4, b4, {0: mr, 3: mI, 6: mw}, rt=1.6)
        self.resultado(B4, VEL)
        self.ate(0.99)

        # ── B6-3: congela em r = 0,45 m; τ⃗ = dL⃗/dt → τ_z = d(Iω)/dt → I dω/dt + (dI/dt) ω → I α + İ ω (hold) ──
        self.an("B6-3")
        self.anda(0.0, tf=self.tp + T45)
        self.sem_selo()
        self.pilha.limpa()
        marca = Circle(radius=0.32).set_stroke(WHITE_, 2.6)
        marca.move_to(self.tela_disco())
        self.play(Create(marca), run_time=0.4)
        C1, c1 = Mx(r"\vec\tau", "=", r"\frac{d\vec L}{dt}")
        self.pilha.poe(C1)
        lg = txt("LEI GERAL", 22, bold=True, color=GEO).next_to(C1, RIGHT, buff=0.3)
        self.gat("a lei geral")
        self.lei(C1, c1, rt=1.0, metodo="lei")
        self.play(FadeIn(lg), run_time=0.3)
        C2, c2 = Mx(r"\tau_z", "=", r"\frac{d(I\omega)}{dt}")
        self.pilha.poe(C2)
        self.gat("derivando o momento de inércia")
        self.gm(C1, C2, (J(c1, 0), J(c2, 0)), (J(c1, 1), J(c2, 1)), (J(c1, 2)[0:1], J(c2, 2)[0:1]), (J(c1, 2)[1:3], J(c2, 2)[1:5]), (J(c1, 2)[3:], J(c2, 2)[5:]), rt=1.3)
        C3, c3 = Mx(r"\tau_z", "=", "I", r"\frac{d\omega}{dt}", "+", r"\frac{dI}{dt}", r"\omega", size=44)
        self.pilha.poe(C3)
        self.gat("a regra do produto")
        self.gm(C2, C3, (J(c2, 0), J(c3, 0)), (J(c2, 1), J(c3, 1)), (J(c2, 2)[2:3], J(c3, 2)), (J(c2, 2)[3:4], J(c3, 3)[1:2]), (J(c2, 2)[0:1], J(c3, 3)[0:1]),
                (J(c2, 2)[5:], J(c3, 3)[2:]), ([], J(c3, 4, 5, 6)), (J(c2, 2)[1:2] + J(c2, 2)[4:5], []), rt=1.8)
        C4, c4 = Mx(r"\tau_z", "=", "I", r"\alpha", "+", r"\dot I", r"\omega", size=58)
        self.pilha.poe(C4)
        self.gat("mais a taxa de variação")
        self.gm(C3, C4, (J(c3, 0), J(c4, 0)), (J(c3, 1), J(c4, 1)), (J(c3, 2), J(c4, 2)), (J(c3, 3), J(c4, 3)), (J(c3, 4), J(c4, 4)), (J(c3, 5), J(c4, 5)),
                (J(c3, 6), J(c4, 6)), rt=1.4)
        self.resultado(C4, FC)
        self.gat("a versão curta")
        Cc, cc = Mx(r"\tau_z", "=", "I", r"\alpha", size=42)
        Cc.set_opacity(0.85)
        nota = txt("SÓ COM I CONSTANTE", 22, bold=True, color=MAS)
        self.pilha.poe(VGroup(Cc, nota).arrange(RIGHT, buff=0.3))
        self.play(FadeIn(Cc), FadeIn(nota), run_time=0.5)
        Cc.set_opacity(0.85)
        self.gat("aqui não é")
        self.play(Indicate(gl(C4, J(c4, 5, 6)), color=MAS, scale_factor=1.2), run_time=0.8)
        self.ate(0.99)

        # ── B6-4: 0 = I α + İ ω → I α = −İ ω → números em r = 0,45 m → α = +5,9 rad/s² ──
        self.an("B6-4")
        self.pilha.so(C4)
        self.play(FadeOut(lg), run_time=0.2)
        D1, d1 = Mx("0", "=", "I", r"\alpha", "+", r"\dot I", r"\omega")
        self.pilha.poe(D1)
        self.gat("com torque zero")
        self.gm(C4, D1, (J(c4, 0), J(d1, 0)), (J(c4, 1), J(d1, 1)), (J(c4, 2), J(d1, 2)), (J(c4, 3), J(d1, 3)), (J(c4, 4), J(d1, 4)), (J(c4, 5), J(d1, 5)),
                (J(c4, 6), J(d1, 6)), rt=1.2)
        D2, d2 = Mx("I", r"\alpha", "=", "-", r"\dot I", r"\omega")
        self.pilha.poe(D2)
        self.gat("tem que cancelar a segunda")
        self.gm(D1, D2, (J(d1, 2), J(d2, 0)), (J(d1, 3), J(d2, 1)), (J(d1, 1), J(d2, 2)), (J(d1, 4), J(d2, 3)), (J(d1, 5), J(d2, 4)), (J(d1, 6), J(d2, 5)),
                (J(d1, 0), []), rt=1.4)
        mId = mostrador(r"\dot I", lambda: est()["Idot"], 3, r"\mathrm{kg\,m^2/s}", MAS, P3(3.75, -3.15))
        self.play(OpVivo(mId), run_time=0.3)
        D3, d3 = Mx(r"\alpha", "=", r"\frac{-(-0{,}054)\cdot 4{,}44}{0{,}0405}", size=44)
        self.pilha.poe(D3)
        self.gat("a quarenta e cinco centímetros")
        self.lei(D3, d3, {2: mId}, rt=1.4, numero=True)
        D4, d4 = Mx("=", r"+5{,}9", r"\,\mathrm{rad/s^2}", size=56, cores={1: ACC})
        self.pilha.poe(D4)
        self.gat("quase seis radianos")
        self.lei(D4, d4, rt=0.8, numero=True)
        self.resultado(D4, ACC)
        self.ate(0.99)

        # ── B6-5: ω × 4 e v_θ × 2 (hold) ──
        self.an("B6-5")
        self.pilha.limpa()
        self.play(OpVivo(mId, entra=False), FadeOut(marca), run_time=0.3)
        self.remove(mId)
        mv = mostrador(r"v_\theta", lambda: est()["vth"], 2, r"\mathrm{m/s}", VEL, P3(3.75, -3.15))
        self.play(OpVivo(mv), run_time=0.3)
        self.gat("a velocidade angular quadruplicou")
        self.anda(0.5)
        self.wait(1.4)
        E1, e1 = Mx(r"v_\theta", "=", r"\frac{L}{m r}", r"\ \Rightarrow\ ", r"\times 2")
        E2, e2 = Mx(r"\omega", "=", r"\frac{L}{m r^2}", r"\ \Rightarrow\ ", r"\times 4")
        self.pilha.poe(E1)
        self.gat("só dobrou")
        self.lei(E1, e1, {0: mv}, rt=1.2)
        self.pilha.poe(E2)
        self.gat("depende do raio ao quadrado")
        self.lei(E2, e2, {0: mw}, rt=1.2)
        self.ate(0.99)

        # ── B6-6: triângulos de 0,20 s ao longo da espiral (0,090 m² cada) ──
        self.an("B6-6")
        self.pilha.limpa()
        t0 = self.tp - 0.1
        tris = VGroup()
        for k in range(6):
            ta = t0 + 0.2 * k
            pts = [self.tela((*self.mov(ta + 0.2 * s), 0.012)) for s in np.linspace(0, 1, 14)]
            tris.add(Polygon(self.tela((0, 0, 0.012)), *pts).set_fill(GEO, 0.38 if k % 2 == 0 else 0.24).set_stroke(GEO, 2).set_z_index(5))
        self.anda(0.5, tf=t0)
        self.gat("e as áreas")
        for k in range(6):
            self.play(FadeIn(tris[k]), run_time=0.4, rate_func=linear)
        a_lbl = T(r"0{,}090\,\mathrm{m^2}", 34, WHITE_)
        a_lbl.move_to(P3(2.5, 0.8))
        fr = txt("CADA TRIÂNGULO:", 26, bold=True, color=GEO).next_to(a_lbl, UP, buff=0.18)
        self.gat("continuam iguais")
        self.play(FadeIn(fr), FadeIn(a_lbl), run_time=0.5)
        f6 = txt("MAIS BAIXO, MAIS LARGO", 30, bold=True, color=GEO).move_to(P3(3.2, -0.2))
        self.gat("tem que ficar mais largo")
        self.play(FadeIn(f6), run_time=0.5)
        self.ate(0.99)

        # ── B6-7: congela em r = 0,45 m; ZOOM ×3: v⃗ = v_r + v_θ (8,5°); T⃗ para o furo; a componente de T⃗ ao longo de v⃗ ──
        self.an("B6-7")
        self.play(FadeOut(VGroup(tris, a_lbl, fr, f6)), run_time=0.4)
        self.anda(0.0, tf=self.tp + T45)
        self.selo("ZOOM ×3", "PERTO DO DISCO")
        e = est()
        Zc = P3(3.5, -0.4)
        ut = np.array([0.0, 1.0, 0.0])          # tangente (desenho do inset)
        ur = np.array([-1.0, 0.0, 0.0])         # para o furo
        k = 1.25
        v_th = seta(Zc, Zc + k * e["vth"] * ut, VEL, 6, tip=0.2)
        v_r = seta(Zc, Zc + k * (-e["vr"]) * ur * 1.0, VEL, 6, tip=0.16)
        vtot = Zc + k * e["vth"] * ut + k * (-e["vr"]) * ur
        v_v = seta(Zc, vtot, VEL, 7, tip=0.22)
        disco_i = Circle(radius=0.2).move_to(Zc).set_fill("#4E5766", 1).set_stroke(MAS, 3).set_z_index(9)
        quadro = RoundedRectangle(width=5.4, height=3.9, corner_radius=0.12).move_to(P3(3.4, 0.25)).set_fill(PANEL, 0.6).set_stroke(GEO, 1.6)
        quadro._fundo = True
        cham = DashedLine(self.tela_disco() + P3(0.25, 0), quadro.get_left(), dash_length=0.09).set_stroke(GEO, 2, opacity=0.8)
        self.gat("olha a velocidade durante a puxada")
        self.play(FadeIn(quadro), Create(cham), FadeIn(disco_i), run_time=0.5)
        self.gat("uma parte ao longo da volta")
        self.play(FadeIn(v_th), FadeIn(T(r"v_\theta", 38, VEL).next_to(Zc + k * e["vth"] * ut, RIGHT, buff=0.15)), run_time=0.5)
        lvr = T(r"v_r", 38, VEL).next_to(Zc + k * (-e["vr"]) * ur, DOWN, buff=0.15)
        self.gat("uma parte apontando para o furo")
        self.play(FadeIn(v_r), FadeIn(lvr), run_time=0.5)
        self.play(FadeIn(v_v), FadeIn(T(r"\vec v", 40, VEL).next_to(vtot, LEFT, buff=0.15)), run_time=0.5)
        ang = arco_ang(Zc, Zc + ut, vtot, r=1.5, cor=ANG, w=4)
        l_ang = T(r"8{,}5^\circ", 34, ANG).move_to(Zc + P3(-0.42, 1.85))
        self.play(Create(ang), FadeIn(l_ang), run_time=0.5)
        self.gat("a tração também aponta para o furo")
        sT = seta(Zc + 0.25 * ur, Zc + 1.45 * ur, FC, 7, tip=0.22)
        lT = T(r"\vec T", 40, FC).next_to(Zc + 1.45 * ur, DOWN, buff=0.15)
        self.play(FadeIn(sT), FadeIn(lT), run_time=0.5)
        uv = (vtot - Zc) / np.linalg.norm(vtot - Zc)
        proj_T = float(1.45 * (ur @ uv))
        comp = Line(Zc, Zc + proj_T * uv).set_stroke(FC, 9)
        self.gat("tem uma componente na direção do movimento")
        self.play(Create(comp), run_time=0.6)
        self.play(Indicate(comp, color=FC, scale_factor=1.3), run_time=0.7)
        f7 = txt("FAZ TRABALHO POSITIVO", 28, bold=True, color=KC).move_to(P3(3.4, -2.1))
        self.gat("faz trabalho positivo")
        self.play(FadeIn(f7), run_time=0.4)
        self.ate(0.99)

        # ── B6-8: barras de energia (estados com v_r = 0); W = ΔK; P = T v_r (hold); a mesa sai ──
        self.an("B6-8")
        inset = [m for m in self.mobjects if m not in self.fixos() and m not in (f3, mr, mI, mw, mL, mv, self.s1) and not isinstance(m, ValueTracker)
                 and m is not self.clk and m is not self.h2]
        self.play(*[FadeOut(m) for m in inset], f3.op.animate.set_value(0.0), OpVivo(mr, entra=False), OpVivo(mI, entra=False), OpVivo(mw, entra=False),
                  OpVivo(mL, entra=False), OpVivo(mv, entra=False), run_time=0.5)
        self.remove(*inset, mr, mI, mw, mL, mv)
        self.pilha.base = -3.30
        self.selo("ESTADOS COM", [[T("v_r", 32, VEL), T(r"=\,0", 32, WHITE_)]])
        y0, esc = -3.0, 4.6
        b_K0 = Rectangle(width=0.9, height=0.225 * esc).set_fill(KC, 0.85).set_stroke(KC, 2).move_to(P3(-5.9, y0 + 0.225 * esc / 2))
        b_Kf = Rectangle(width=0.9, height=0.900 * esc).set_fill(KC, 0.85).set_stroke(KC, 2).move_to(P3(-3.4, y0 + 0.900 * esc / 2))
        b_W = Rectangle(width=0.9, height=0.675 * esc).set_fill(KC, 0.35).set_stroke(KC, 2.5).move_to(P3(-1.4, y0 + 0.225 * esc + 0.675 * esc / 2))
        base_l = Line(P3(-6.8, y0), P3(-0.6, y0)).set_stroke(GEO, 2)
        lK0 = VGroup(T("K_0", 36, KC), T(r"0{,}225\,\mathrm{J}", 30, WHITE_)).arrange(DOWN, buff=0.08).next_to(b_K0, UP, buff=0.15)
        lKf = VGroup(T("K_f", 36, KC), T(r"0{,}900\,\mathrm{J}", 30, WHITE_)).arrange(DOWN, buff=0.08).next_to(b_Kf, UP, buff=0.15)
        lW = VGroup(T("W", 36, KC), T(r"0{,}675\,\mathrm{J}", 30, WHITE_)).arrange(DOWN, buff=0.08).next_to(b_W, UP, buff=0.15)
        self.gat("a energia cinética vai de")
        self.play(Create(base_l), GrowFromEdge(b_K0, DOWN), FadeIn(lK0), run_time=0.7)
        self.play(GrowFromEdge(b_Kf, DOWN), FadeIn(lKf), run_time=0.7)
        self.gat("quatro vezes mais")
        G1, g1 = Mx("W", "=", r"\Delta K")
        self.pilha.poe(G1)
        self.lei(G1, g1, rt=0.8, metodo="lei")
        G2, g2 = Mx(r"\Delta K", "=", r"\tfrac{1}{2} m v_{\theta,f}^2", "-", r"\tfrac{1}{2} m v_{\theta,0}^2", size=44)
        self.pilha.poe(G2)
        self.lei(G2, g2, rt=1.3, metodo="lei")
        G3, g3 = Mx("=", r"0{,}900", "-", r"0{,}225", cores={1: KC, 3: KC})
        self.pilha.poe(G3)
        self.lei(G3, g3, {1: lKf[1], 3: lK0[1]}, rt=1.2, numero=True)
        G4, g4 = Mx("=", r"0{,}675", r"\,\mathrm{J}", size=56, cores={1: KC})
        self.pilha.poe(G4)
        self.gat("são o trabalho da mão")
        self.lei(G4, g4, rt=0.8, numero=True)
        self.play(GrowFromEdge(b_W, DOWN), FadeIn(lW), run_time=0.7)
        self.resultado(G4, KC)
        G5, g5 = Mx("P", "=", "T", "v_r", "=", r"1{,}78", r"\cdot", r"0{,}30", "=", r"0{,}53", r"\,\mathrm{W}", size=40, cores={5: FC, 7: VEL, 9: KC})
        self.pilha.poe(G5)
        self.lei(G5, g5, rt=1.4, numero=True)
        self.gat("se conservou")
        f8 = linha_base([T("L", 40, LMAG), txt("CONSERVA,", 30, bold=True), T("K", 40, KC), txt("NÃO", 30, bold=True)], 0.14)
        self.pilha.poe(f8)
        self.play(FadeIn(f8), run_time=0.5)
        self.ate(0.99)

        # ── B6-9: ATENÇÃO; gráfico T × r com r̈ = 0 (0,75 N em 0,60 m → 6,0 N em 0,30 m) ──
        self.an("B6-9")
        self.pilha.limpa()
        self.play(FadeOut(VGroup(b_K0, b_Kf, b_W, base_l, lK0, lKf, lW)), run_time=0.4)
        self.selo("ATENÇÃO", "PUXADA SEM ACELERAÇÃO RADIAL")
        ox, oy, sx, sy = -6.3, -3.0, 13.0, 0.82        # r de 0,25 a 0,65 m; T de 0 a 6,5 N
        R = lambda r: ox + (r - 0.25) * sx
        Y = lambda t: oy + t * sy
        ax_r = Arrow(P3(ox - 0.1, oy), P3(R(0.67), oy), buff=0, stroke_width=3, tip_length=0.16).set_color(GEO)
        ax_T = Arrow(P3(ox, oy - 0.1), P3(ox, Y(6.6)), buff=0, stroke_width=3, tip_length=0.16).set_color(GEO)
