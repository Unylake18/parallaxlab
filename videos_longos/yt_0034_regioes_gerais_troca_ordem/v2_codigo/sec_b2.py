"""yt_0034 · B2 · o teorema: a região em pé (alvo 07) e a região deitada com a regra dos limites (alvo 08)."""
from pecas34 import *

A_, B_ = .3, 1.85            # região em pé: x de a a b
C_, D_ = .3, 1.8             # região deitada: y de c a d
YS = 1.05                    # altura da reta-sonda / tira deitada


def picos(m, chave):
    g = list(gl(m, chave))
    return VGroup(*g)


class PB2(B34):
    ANTES = "O TEOREMA"

    def corpo(self):
        # ── B2-1 · o enunciado: a região em pé (alvo 07) ──
        self.an("B2-1")
        g = papel_v(CH, (0, 2.2, 0, 2.2))
        self.grade = g
        reg = regiao(CH, cX(c_b21, A_, B_) + cX(d_b21, A_, B_)[::-1])
        sx, sy, lx, ly = eixos_v(CH, 2.35, 2.35)
        self.play(FadeIn(g), GrowFromPoint(sx, CH.P(0, 0)), GrowFromPoint(sy, CH.P(0, 0)), run_time=0.6)
        self.pena(lx, ly)
        lB = TC("B", *CH.px(.62, 1.05), 40, "c")
        self.gat("sejam cê e dê")
        cc = curva(CH, cX(c_b21, A_, B_), AZC, 4)
        dd = curva(CH, cX(d_b21, A_, B_), CORAL, 4)
        l1 = mixl([("m", r"\Az{c},\ \Co{d}"), ("t", "CONTÍNUAS EM"), ("L", [("ab", r"[\Am{a},\Am{b}],\ \ "), ("c", r"\Az{c(\X)}"), ("le", r"\le"), ("d", r"\Co{d(\X)}")])],
                  1120, 230, 36)
        self.pena(l1.p[0], extra=[Succession(Create(cc, run_time=0.8), Create(dd, run_time=0.8))], rt=1.6)     # c e d, uma de cada vez
        self.pena(l1.p[1])
        self.gat("no intervalo fechado")
        ta, tb = tick(CH, "x", A_, r"\Am{a}"), tick(CH, "x", B_, r"\Am{b}")
        va = curva(CH, [(A_, 0), (A_, d_b21(A_))], E1, 2, dash=(6, 7), alpha=.7, z=3)
        vb = curva(CH, [(B_, 0), (B_, d_b21(B_))], E1, 2, dash=(6, 7), alpha=.7, z=3)
        self.play(Create(va), Create(vb), Create(ta[0]), Create(tb[0]), run_time=0.7)
        self.pena(ta[1], tb[1])
        self.pena(parte(l1.p[2], sel(l1.p[2], "ab"), "[a,b]"))
        self.gat("cê de xis menor")
        self.pena(parte(l1.p[2], sel(l1.p[2], ["c", "le", "d"]), "c ≤ d"))
        self.gat("menor ou igual a")
        acende(self, (gl(l1.p[2], "le"), None), rt=0.9)
        self.gat("a região b é")
        self.play(FadeIn(reg), run_time=0.8)
        self.pena(lB)
        l2 = L([("B", "B="), ("ab", r"\{"), ("xy", r"(\X,\Y)"), ("dp", ":"), ("c1", r"\ \Am{a}\le\X\le\Am{b},"), ("c2", r"\ \Az{c(\X)}\le\Y\le\Co{d(\X)}"),
                ("fc", r"\}")], 1120, 330, 36)
        self.pena(l2)
        self.gat("xis está entre á")                       # uma faixa âmbar a 10 % pinta de a até b e some
        fx_ = regiao(CH, [(A_, 0), (B_, 0), (B_, 2.2), (A_, 2.2)], mixh(BG_, E1, .10), z=0)
        self.play(FadeIn(fx_), run_time=0.5)
        acende(self, (gl(l2, "c1"), E1), rt=0.6)
        self.play(FadeOut(fx_), run_time=0.4)
        self.remove(fx_)
        self.gat("ípsilon está entre")                     # o ponto P anda na vertical de x = 1,1, de c(x) a d(x), sem sair de B
        XP = 1.1
        yP = ValueTracker((c_b21(XP) + d_b21(XP)) / 2)
        self.add(yP)
        pP = always_redraw(lambda: ponto_px(*CH.px(XP, yP.get_value()), BR, 8, z=9))
        pjP = always_redraw(lambda: VGroup(curva(CH, [(0, yP.get_value()), (XP, yP.get_value())], GEO, 1.5, dash=(4, 5), z=8),
                                           curva(CH, [(XP, 0), (XP, yP.get_value())], GEO, 1.5, dash=(4, 5), z=8)))
        self.play(FadeOut(lB), run_time=0.2)              # o B sai antes de a tracejada de P nascer (folga ≥ 12 px)
        self.play(FadeIn(pP, scale=.5), FadeIn(pjP), run_time=0.3)
        acende(self, (gl(l2, "c2"), None), rt=0.4)
        self.play(yP.animate.set_value(d_b21(XP) - .04), run_time=1.0)
        self.play(yP.animate.set_value(c_b21(XP) + .04), run_time=1.0)
        self.gat("as chaves se leem")
        pP.clear_updaters()
        pjP.clear_updaters()
        self.play(FadeOut(pP), FadeOut(pjP), FadeIn(lB), run_time=0.3)
        self.remove(pP, pjP, yP)
        acende(self, (gl(l2, "ab"), None), (gl(l2, "fc"), None), rt=1.2)
        self.gat("dois pontos tais que")
        acende(self, (gl(l2, "dp"), None), rt=1.0)
        self.gat("se f é contínua")
        l3 = mixl([("m", r"\f"), ("t", "CONTÍNUA EM B")], 1120, 420, 36)
        self.pena(*l3.p, lag=0.15)
        acende(self, (l3, None), rt=0.8)
        self.gat("então a integral dupla")
        l4 = TC(r"\Rightarrow\ \iint_B\f\,\dX\,\dY=\int_{\Am{a}}^{\Am{b}}\Big[\int_{\Az{c(\X)}}^{\Co{d(\X)}}\f(\X,\Y)\,\dY\Big]\dX", 1120, 560, 36)
        self.pena(l4, passo=0.06)
        self.gat("à integral de á")
        xa = ValueTracker(A_)
        self.add(xa)
        vv = always_redraw(lambda: curva(CH, [(xa.get_value(), 0), (xa.get_value(), d_b21(xa.get_value()))], E1, 2, dash=(6, 6), z=6))
        self.play(FadeIn(vv), FadeOut(lB), run_time=0.2)
        self.play(xa.animate.set_value(B_), run_time=2.0, rate_func=linear)
        self.play(xa.animate.set_value(1.1), run_time=0.8)
        vv.clear_updaters()
        X0 = 1.1
        tv = tiraV(CH, X0, c_b21(X0), d_b21(X0))
        self.gat("da integral de cê")
        self.play(FadeOut(vv), GrowFromEdge(tv, DOWN), FadeIn(lB), run_time=1.0)
        self.remove(vv, xa)
        self.gat("na figura a fatia")
        self.gat("entra na região pela")
        pe, ps = pontos_es(CH, (X0, c_b21(X0)), (X0, d_b21(X0)))
        rc = rot(CH, r"\Az{\Y=c(\X)}", (1.35, c_b21(1.35)), 0, 40, 30)
        self.play(FadeIn(pe, scale=0.5), run_time=0.4)
        self.pena(rc)
        self.gat("e sai pela curva")
        rd = rot(CH, r"\Co{\Y=d(\X)}", (1.45, d_b21(1.45)), 0, -40, 30)
        self.play(FadeIn(ps, scale=0.5), run_time=0.4)
        self.pena(rd)
        self.gat("uma região que se")
        realce(self, reg, tv)                                          # a região que se fatia em pé
        self.gat("região do tipo um")
        s1 = selo("REGIÃO EM PÉ (TIPO I)", 1120, 720)
        self.play(Create(s1[0]), run_time=0.5)
        self.pena(s1[1])
        self.marca("07")

        # ── B2-2 · a região deitada e a regra dos limites (alvo 08) ──
        self.an("B2-2")
        self.secao("A REGIÃO DEITADA")
        self.gat("trocando os papéis")
        col = [l1, l2, l3, l4, *s1]
        reg2 = regiao(CH, cY(a_b22, C_, D_) + cY(b_b22, C_, D_)[::-1])
        aa = curva(CH, cY(a_b22, C_, D_), AZC, 4)
        bb = curva(CH, cY(b_b22, C_, D_), CORAL, 4)
        hc = curva(CH, [(0, C_), (b_b22(C_), C_)], E2, 2, dash=(6, 7), alpha=.7, z=3)
        hd = curva(CH, [(0, D_), (b_b22(D_), D_)], E2, 2, dash=(6, 7), alpha=.7, z=3)
        tc_, td_ = tick(CH, "y", C_, r"\Mg{c}"), tick(CH, "y", D_, r"\Mg{d}")
        self.play(*[FadeOut(m) for m in col + [tv, pe, ps, rc, rd, ta[1], tb[1], lB]], run_time=0.4)
        self.play(ReplacementTransform(reg, reg2), ReplacementTransform(cc, aa), ReplacementTransform(dd, bb), ReplacementTransform(va, hc),
                  ReplacementTransform(vb, hd), ReplacementTransform(ta[0], tc_[0]), ReplacementTransform(tb[0], td_[0]),
                  run_time=1.0)
        lB.move_to(PX(*CH.px(1, .6)))
        self.play(FadeIn(lB), run_time=0.3)
        self.remove(*col, tv, pe, ps, rc, rd, ta[1], tb[1])
        self.pena(tc_[1], td_[1])
        self.gat("ípsilon entre cê e")
        m1 = L([("B", "B="), ("ab", r"\{"), ("xy", r"(\X,\Y)"), ("dp", ":"), ("c1", r"\ \Mg{c}\le\Y\le\Mg{d},"), ("c2", r"\ \Az{a(\Y)}\le\X\le\Co{b(\Y)}"),
                ("fc", r"\}")], 1120, 230, 36)
        self.pena(m1)
        self.gat("e xis entre á")
        ra = rot(CH, r"\Az{\X=a(\Y)}", (a_b22(1.55), 1.55), 30, 0, 28, "l")      # D7: 16 px mais para dentro
        rb = rot(CH, r"\Co{\X=b(\Y)}", (b_b22(1.5), 1.5), 14, 0, 28, "l")
        self.pena(ra, rb, lag=0.3)
        self.gat("a integral de dentro é em")
        m2 = TC(r"\iint_B\f=\int_{\Mg{c}}^{\Mg{d}}\Big[\int_{\Az{a(\Y)}}^{\Co{b(\Y)}}\f\,\dX\Big]\dY", 1120, 345, 38)
        self.pena(m2)
        self.gat("da curva da esquerda")
        th = tiraH(CH, YS, a_b22(YS), b_b22(YS))
        self.play(GrowFromEdge(th, LEFT), run_time=0.9)
        self.gat("a de fora é em")
        s2 = selo("REGIÃO DEITADA (TIPO II)", 1120, 460)
        self.play(Create(s2[0]), run_time=0.5)
        self.pena(s2[1])
        self.gat("você vai usar em")
        realce(self, th, aa, bb)                                       # a fatia deitada, de a(y) a b(y)
        self.gat("são sempre números")
        pn = painel(1120, 500, 720, 150)
        f1 = T("FORA: NÚMEROS", 1150, 560, 30)
        self.play(Create(pn), run_time=0.5)
        self.pena(f1)
        acende(self, (tc_[1], E2), (td_[1], E2), rt=0.8)
        self.gat("até onde as fatias")
        self.play(hc.animate.set_stroke(opacity=1, width=W(3)), hd.animate.set_stroke(opacity=1, width=W(3)), run_time=0.5)
        self.play(hc.animate.set_stroke(opacity=.7, width=W(2)), hd.animate.set_stroke(opacity=.7, width=W(2)), run_time=0.5)
        self.gat("só da variável de")
        f2 = T("DENTRO: SÓ A VARIÁVEL DE FORA", 1150, 620, 30)
        self.pena(f2)
        acende(self, (ra.f, AZC), (rb.f, CORAL), rt=0.8)
        self.gat("está congelada na")
        self.play(th.animate.set_fill(mixh(BG_, E2, .8)), run_time=0.4)
        self.play(th.animate.set_fill(mixh(BG_, E2, .55)), run_time=0.4)
        self.gat("e atravessa a região")
        yt = ValueTracker(.08)
        self.add(yt)
        sonda = always_redraw(lambda: curva(CH, [(-.02, yt.get_value()), (2.15, yt.get_value())], BR, 2, dash=(4, 6), alpha=.8, z=6))
        self.play(FadeIn(sonda), FadeOut(lB), run_time=0.3)
        self.play(yt.animate.set_value(YS), run_time=1.6)
        sonda.clear_updaters()
        self.play(FadeIn(lB), run_time=0.3)
        self.gat("onde ela entra")
        pe2, ps2 = pontos_es(CH, (a_b22(YS), YS), (b_b22(YS), YS))
        qa_, qb_ = CH.px(a_b22(YS), YS), CH.px(b_b22(YS), YS)
        lc = leg("COMEÇA", qa_[0] + 16, qa_[1] - 26, AZC, "left", 26)
        lt = leg("TERMINA", qb_[0] + 14, qb_[1] - 24, CORAL, "left", 26)
        self.play(FadeIn(pe2, scale=0.5), run_time=0.4)
        self.pena(lc)
        self.gat("onde ela sai termina")
        self.play(FadeIn(ps2, scale=0.5), run_time=0.4)
        self.pena(lt)
        self.gat("na fatia em pé")
        vs = curva(CH, [(1.2, -.02), (1.2, 2.15)], BR, 2, dash=(4, 6), alpha=.8, z=6)
        self.play(Create(vs), run_time=0.8)
        self.gat("na deitada da esquerda")
        self.play(FadeOut(vs), run_time=0.4)
        self.remove(vs)
        self.gat("dois pedaços separados")
        U = Vw(1150, 960, 85)
        upts = [(0, 0), (2, 0), (2, 2), (1.4, 2), (1.4, .7), (.6, .7), (.6, 2), (0, 2)]
        ur = regiao(U, upts, z=2)
        ub = curva(U, upts + [(0, 0)], GEO, 2, z=3)
        ul = curva(U, [(-.15, 1.4), (2.2, 1.4)], BR, 2, dash=(4, 6), z=4)
        ud = [ponto_px(*U.px(p, 1.4), AZC, 7) for p in (0, 1.4)] + [ponto_px(*U.px(q, 1.4), CORAL, 7) for q in (.6, 2)]
        self.play(FadeIn(ur), Create(ub), run_time=0.8)
        self.play(Create(ul), run_time=0.6)
        self.play(*[FadeIn(d, scale=0.5) for d in ud], run_time=0.4)
        dt = placa_txt("DOIS TRECHOS?", 1380, 880, AL, 28)
        self.pena(dt)
        self.marca("08")
        self.sai_fim()
