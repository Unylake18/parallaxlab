"""yt_0034 · B7 · quando a região se divide: o telhado (alvo 21) e o metal leve deitado em três pedaços (alvo 22); quando vale trocar (alvo 23).
A tira em pé desliza no telhado (um ValueTracker): o rótulo da saída troca de y = 1 + x para y = 1 − x ao passar por x = 0."""
from pecas34 import *

gsol = lambda a: 1 + .42 * math.sin(1.7 * a - .4)


class PB7(B34):
    ANTES = "QUANDO A REGIÃO SE DIVIDE"

    def corpo(self):
        # ── B7-1a · o telhado (alvo 21) ──
        self.an("B7-1")
        g = papel_v(TEL, (-1.1, 1.1, 0, 1.15))
        self.grade = g
        sx = seta_px(TEL.px(-1.15, 0), TEL.px(1.25, 0), E1, 3, 16, z=6)
        sy = seta_px(TEL.px(0, -.05), TEL.px(0, 1.2), E2, 3, 16, z=6)
        lx = TC(r"\X", *TEL.px(1.31, 0), 32, "c")
        self.play(FadeIn(g), GrowFromPoint(sx, TEL.P(-1.15, 0)), GrowFromPoint(sy, TEL.P(0, 0)), run_time=0.5)
        self.pena(lx)
        self.gat("olha este telhado")
        r1 = regiao(TEL, [(-1, 0), (0, 1), (0, 0)], mixh(BG_, GEO, .22))
        r2 = regiao(TEL, [(0, 0), (0, 1), (1, 0)], mixh(BG_, GEO, .22))
        ed = curva(TEL, [(-1, 0), (0, 1), (1, 0)], CORAL, 4)
        tm, tp = tick(TEL, "x", -1, r"\Am{-1}"), tick(TEL, "x", 1, r"\Am{1}")
        self.play(FadeIn(r1), FadeIn(r2), Create(ed), Create(tm[0]), Create(tp[0]), run_time=1.0)
        self.pena(tm[1], tp[1])
        self.gat("de vértices menos um")
        realce(self, ed, tm[0], tp[0])                                 # o telhado e os vértices lidos
        self.gat("fatiando em pé a")
        xt = ValueTracker(-.85)
        self.add(xt)
        alt = lambda: 1 - abs(xt.get_value())
        tira = always_redraw(lambda: tiraV(TEL, xt.get_value(), 0, max(.002, alt())))
        pe = always_redraw(lambda: ponto_px(*TEL.px(xt.get_value(), 0), AZC, 9))
        ps = always_redraw(lambda: ponto_px(*TEL.px(xt.get_value(), alt()), CORAL, 9))
        self.play(FadeIn(tira), FadeIn(pe), FadeIn(ps), run_time=0.5)
        self.play(xt.animate.set_value(-.55), run_time=1.0)
        self.gat("muda de fórmula no")
        ra = rot(TEL, r"\Co{\Y=1+\X}", (-.62, .4), -24, -6, 30, "r")
        self.pena(ra)
        self.play(xt.animate.set_value(.55), run_time=2.2, rate_func=smooth)
        self.gat("à direita um menos")
        rb = rot(TEL, r"\Co{\Y=1-\X}", (.62, .4), 24, -6, 30, "l")
        self.pena(rb)
        self.gat("não descreve a saída")
        realce(self, ed, ra, rb)                                       # a saída muda de fórmula no topo
        tira.clear_updaters()
        pe.clear_updaters()
        ps.clear_updaters()
        self.gat("se divide em duas")
        dv = curva(TEL, [(0, 0), (0, 1.12)], BR, 2, dash=(6, 7), z=5)
        t1 = tiraV(TEL, -.55, 0, .45)
        q1, q2 = pontos_es(TEL, (-.55, 0), (-.55, .45))
        self.play(Create(dv), FadeIn(t1), FadeIn(q1), FadeIn(q2), r1.animate.set_fill(mixh(BG_, GEO, .22)), r2.animate.set_fill(mixh(BG_, GEO, .14)),
                  run_time=0.9)
        b1 = TC(r"B_1", *TEL.px(-.32, .2), 36, "c")
        b2 = TC(r"B_2", *TEL.px(.32, .2), 36, "c")
        self.pena(b1, b2, lag=0.3)
        ep = leg("EM PÉ: DUAS CONTAS", 1120, 200, E1, "left", 30)
        self.pena(ep)
        self.gat("bê um e bê")
        acende(self, (b1, None), (b2, None), rt=0.8)
        self.gat("vira duas integrais")
        D1 = TC(r"\int_{-1}^{0}\!\int_{\Az{0}}^{\Co{1+\X}}\!\dY\,\dX+\int_0^1\!\int_{\Az{0}}^{\Co{1-\X}}\!\dY\,\dX", 1120, 300, 34)
        self.pena(D1)
        self.play(r1.animate.set_fill(mixh(BG_, GEO, .4)), run_time=0.35)
        self.play(r1.animate.set_fill(mixh(BG_, GEO, .22)), r2.animate.set_fill(mixh(BG_, GEO, .4)), run_time=0.35)
        self.play(r2.animate.set_fill(mixh(BG_, GEO, .14)), run_time=0.35)
        self.gat("meio mais meio")
        D2 = TC(r"=\dfrac12+\dfrac12", 1160, 410, 40)
        self.pena(D2)
        self.gat("fatiando deitado")
        th = tiraH(TEL, .74, -.26, .26)
        q3, q4 = pontos_es(TEL, (-.26, .74), (.26, .74))
        self.play(GrowFromEdge(th, LEFT), FadeIn(q3, scale=.5), run_time=0.8)
        self.gat("em xis igual a ípsilon")
        rc = rot(TEL, r"\Az{\X=\Y-1}", (-.26, .74), -30, -12, 26, "r")
        self.pena(rc)
        self.gat("e sai pela direita")
        rd = rot(TEL, r"\Co{\X=1-\Y}", (.26, .74), 30, -12, 26, "l")
        self.play(FadeIn(q4, scale=.5), run_time=0.3)
        self.pena(rd)
        realce(self, th, q3, q4)                                       # a fatia deitada, uma fórmula de cada lado
        self.gat("uma conta só a")
        realce(self, th, rc, rd)
        dl = leg("DEITADO: UMA CONTA", 1120, 540, MEN, "left", 30)
        D3 = TC(r"\int_0^1\!\int_{\Az{\Y-1}}^{\Co{1-\Y}}\!\dX\,\dY=1", 1120, 640, 38)
        self.pena(dl, D3, lag=0.4)
        for yy_ in (.3, .74):
            a3, b3 = pontos_es(TEL, (yy_ - 1, yy_), (1 - yy_, yy_))
            self.play(Transform(th, tiraH(TEL, yy_, yy_ - 1, 1 - yy_)), Transform(q3, a3), Transform(q4, b3), run_time=0.9)
        self.gat("muda de comportamento")
        st = ValueTracker(-1.0)
        self.add(st)
        pt = always_redraw(lambda: ponto_px(*TEL.px(st.get_value(), 1 - abs(st.get_value())), CORAL, 8, z=9))
        self.play(FadeIn(pt), run_time=0.2)
        self.play(st.animate.set_value(1.0), run_time=2.4, rate_func=linear)
        self.play(FadeOut(pt), run_time=0.3)
        pt.clear_updaters()
        self.remove(pt, st)
        self.gat("onde a mudança acontece")
        self.play(dv.animate.set_stroke(width=W(4)), run_time=0.4)
        self.play(dv.animate.set_stroke(width=W(2)), run_time=0.4)
        self.marca("21", agora=True)

        # ── B7-1b · o metal leve deitado em três pedaços (alvo 22) ──
        self.gat("na chapa de dois")
        self.limpa(rt=0.4)
        self.remove(self.grade)
        self.grade = None
        g2 = papel_v(CH, (0, 2.2, 0, 2.2))
        self.grade = g2
        leve = poly_px([CH.px(0, 0), CH.px(2, 0)] + [CH.px(a, gsol(a)) for a in np.linspace(2, 0, 121)], LEVE, z=1)
        pes = poly_px([CH.px(0, 2), CH.px(2, 2)] + [CH.px(a, gsol(a)) for a in np.linspace(2, 0, 121)], mixh(BG_, PESADO, .08), z=1)
        so = solda_px(CH, BR, 4)
        bd = borda_ch(CH, GEO, 2)
        sx, sy, lx, ly = eixos_chapa(CH)
        self.play(FadeIn(g2), FadeIn(leve), FadeIn(pes), Create(bd), GrowFromPoint(sx, CH.P(0, 0)), GrowFromPoint(sy, CH.P(0, 0)), Create(so), run_time=0.9)
        self.pena(lx, ly)
        nl = leg("LEVE", *CH.px(1.55, .2), BR, "left", 26)
        np_ = leg("PESADO", *CH.px(1.55, 1.8), GEO, "left", 26)
        self.pena(nl, np_, lag=0.2)
        self.gat("o metal leve fatiado")
        e1 = T("EM PÉ: UMA CONTA", 1120, 330, 34, "left", E1)
        E1f = TC(r"\int_0^2\!\int_{\Az{0}}^{\Co{g(\X)}}\!\dY\,\dX", 1120, 420, 38)
        self.pena(e1, E1f, lag=0.3, passo=0.04)
        self.gat("deitado a reta cortava")
        yt = ValueTracker(.37)                              # começa acima do rótulo LEVE (a sonda não cruza o nome)
        self.add(yt)
        reta = always_redraw(lambda: curva(CH, [(-.02, yt.get_value()), (2.04, yt.get_value())], BR, 2, dash=(4, 6), alpha=.9, z=8))
        self.play(FadeIn(reta), run_time=0.2)
        faixas = [(.42, "CHEIA", 0, 2, .836, "0{,}836"), (.95, "1 CORTE", .27, 2, 1.059, "1{,}059"), (1.24, "2 CORTES", .61, 1.708, 1.42, "1{,}42")]
        d1 = T("DEITADO: TRÊS PEDAÇOS", 1120, 560, 34, "left", E2)
        for k, (yb, nome, a, b, ym, sm) in enumerate(faixas):
            self.play(yt.animate.set_value(yb), run_time=0.5)
            t = tiraH(CH, yb, a, b, h=.05)
            pa, pb = pontos_es(CH, (a, yb), (b, yb))
            q = CH.px(2.12, yb)
            ln = leg(nome, q[0], q[1] + 9, GEO, "left", 26)
            mk = curva(CH, [(0, ym), (2.02, ym)], BR, 1.6, dash=(5, 6), alpha=.8, z=3)
            tk = tick(CH, "y", ym, sm, 26)
            self.pena(ln, tk[1], *([d1] if k == 0 else []), lag=0.15, passo=0.04,
                      extra=[GrowFromEdge(t, LEFT), FadeIn(pa, scale=.5), FadeIn(pb, scale=.5), Create(mk), Create(tk[0])])
        self.play(FadeOut(reta), run_time=0.2)
        reta.clear_updaters()
        self.remove(reta, yt)
        d2 = TC(r"1{,}6729+0{,}4097+0{,}3895", 1120, 640, 38)
        self.pena(d2, passo=0.04)
        self.gat("dois vírgula quatro sete")
        ar = TC(r"\Me{\approx 2{,}4721\ \text{m}^2}", 1120, 760, 44)
        nd = leg("NAS DUAS ORDENS", 1430, 770, GEO, "left", 26)
        self.pena(ar, nd, lag=0.3)
        self.marca("v2_11", agora=True)

        # ── B7-2 · quando vale trocar (alvo v2_12): miniaturas grandes, uma por motivo ──
        self.an("B7-2")
        self.secao("QUANDO VALE TROCAR")
        rows = [290, 520, 750]
        pns = [painel(140, Y - 110, 360, 200) for Y in rows]
        M1 = Lat(180, rows[0] + 70, 170, 150)
        a1 = regiao(M1, [(0, 0)] + cX(gs, 0, 1.7) + [(1.7, 0)], mixh(BG_, CI, .2), z=2)
        c1 = curva(M1, cX(gs, 0, 1.7), CI, 3)
        e1_ = seta_px(M1.px(-.02, 0), M1.px(1.85, 0), E2, 2, 12, z=6)
        self.limpa(rt=0.3)
        self.remove(self.grade)
        self.grade = None
        self.play(Create(pns[0]), FadeIn(a1), Create(c1), GrowFromPoint(e1_, M1.P(0, 0)), run_time=0.6)
        self.gat("primeiro quando a")
        ck0 = check_px(600, rows[0] - 8, MEN)
        tx0 = T("A DE DENTRO SEM PRIMITIVA", 650, rows[0] + 6, 40)
        self.play(Create(ck0), run_time=0.3)
        self.pena(tx0)
        self.gat("como o sino")
        self.play(c1.animate.set_stroke(width=W(6)), run_time=0.4)
        self.play(c1.animate.set_stroke(width=W(3)), run_time=0.4)
        self.gat("e o seno de")
        realce(self, a1, c1)                                           # o sino e o seno de x³: sem primitiva
        self.gat("depende de uma variável")
        realce(self, c1)
        self.gat("no sentido da outra")
        realce(self, e1_, cor=E2)                                      # a fatia no sentido da outra variável
        self.gat("vira um retângulo")
        rr = poly_px([M1.px(0, 0), M1.px(.6, 0), M1.px(.6, gs(.6)), M1.px(0, gs(.6))], mixh(BG_, CI, .35), z=3)
        rr.set_stroke(E2, W(3), 1)
        self.play(GrowFromEdge(rr, DOWN), run_time=0.8)              # o retângulo cresce sob o sino
        self.gat("entra como fator")
        sp0 = leg("O RETÂNGULO TRAZ O FATOR", 650, rows[0] + 60, GEO, "left", 28)
        self.pena(sp0)
        self.gat("não é garantia")
        self.play(rr.animate.set_fill(mixh(BG_, E2, .5)), run_time=0.4)
        self.play(rr.animate.set_fill(mixh(BG_, CI, .35)), run_time=0.4)
        self.gat("a primeira coisa a")
        realce(self, rr, c1)                                           # a primeira coisa a tentar: o retângulo sob o sino
        self.gat("segundo quando uma")
        M2 = Lat(320, rows[1] + 70, 130, 130)
        h1_ = regiao(M2, [(-1, 0), (0, 1), (0, 0)], mixh(BG_, GEO, .22), z=2)
        h2_ = regiao(M2, [(0, 0), (0, 1), (1, 0)], mixh(BG_, GEO, .14), z=2)
        ed2 = curva(M2, [(-1, 0), (0, 1), (1, 0)], CORAL, 3)
        bs2 = curva(M2, [(-1.1, 0), (1.15, 0)], GEO, 2)
        dv2 = curva(M2, [(0, 0), (0, 1.05)], BR, 2, dash=(5, 5))
        ck1 = check_px(600, rows[1] - 8, MEN)
        tx1 = T("UMA ORDEM DIVIDE A REGIÃO", 650, rows[1] + 6, 40)
        self.play(Create(pns[1]), FadeIn(h1_), FadeIn(h2_), Create(ed2), Create(bs2), Create(ck1), run_time=0.6)
        self.pena(tx1)
        self.gat("divide a região em")                                  # as duas tiras em pé acendem, uma em cada metade
        tA = poly_px([M2.px(-.6, 0), M2.px(-.52, 0), M2.px(-.52, .48), M2.px(-.6, .4)], mixh(BG_, E1, .5), z=4)
        tB = poly_px([M2.px(.52, 0), M2.px(.6, 0), M2.px(.6, .4), M2.px(.52, .48)], mixh(BG_, E1, .5), z=4)
        tA.set_stroke(E1, W(2), 1)
        tB.set_stroke(E1, W(2), 1)
        self.play(Create(dv2), GrowFromEdge(tA, DOWN), GrowFromEdge(tB, DOWN), run_time=0.7)
        self.gat("e a outra não")                                       # a tira deitada atravessa as duas metades, uma conta só
        tD = tiraH(M2, .55, -.45, .45, h=.08, alpha=.5)
        sp1 = leg("EM PÉ: DUAS · DEITADO: UMA", 650, rows[1] + 60, GEO, "left", 28)
        self.play(GrowFromEdge(tD, LEFT), run_time=0.6)
        self.pena(sp1)
        self.gat("terceiro quando os")
        M3 = Lat(240, rows[2] + 75, 75, 75)
        r3_ = regiao(M3, [(0, 0), (2, 0), (2, 2)], mixh(BG_, CI, .3), z=2)
        e3_ = curva(M3, [(0, 0), (2, 0), (2, 2)], GEO, 2)
        dg3 = curva(M3, [(0, 0), (2, 2)], BR, 3)
        ck2 = check_px(600, rows[2] - 8, MEN)
        tx2 = T("LIMITES MAIS SIMPLES", 650, rows[2] + 6, 40)
        self.play(Create(pns[2]), FadeIn(r3_), Create(e3_), Create(dg3), Create(ck2), run_time=0.6)
        self.pena(tx2)
        tv3 = poly_px([M3.px(1.17, 0), M3.px(1.29, 0), M3.px(1.29, 1.29), M3.px(1.17, 1.17)], mixh(BG_, E1, .6), z=4)
        tv3.set_stroke(E1, W(2), 1)
        p31, p32 = pontos_es(M3, (1.23, 0), (1.23, 1.23), r=6)
        sp2 = mixl([("t", "DE", GEO), ("m", r"\Az{0}"), ("t", "ATÉ", GEO), ("m", r"\Co{\X}")], 650, rows[2] + 55, 34)
        self.gat("ficam mais simples")                                  # a tira em pé vai de 0 até a diagonal
        self.play(GrowFromEdge(tv3, DOWN), FadeIn(p31, scale=.5), FadeIn(p32, scale=.5), run_time=0.7)
        self.pena(*sp2.p, lag=0.1)
        self.gat("o valor não muda")
        mm = T("MESMA REGIÃO, MESMO VALOR", 960, 960, 40, "center", MEN)
        self.pena(mm)
        self.gat("a região é a")
        for reg_ in (a1, h1_, r3_):
            self.play(reg_.animate.set_fill(opacity=.55), run_time=0.25)
        for reg_ in (a1, h1_, r3_):
            self.play(reg_.animate.set_fill(opacity=1), run_time=0.2)
        self.gat("garante as duas ordens")
        self.play(Transform(tD, tiraH(M2, .3, -.7, .7, h=.08, alpha=.5)), run_time=0.8)
        self.play(Transform(tD, tiraH(M2, .55, -.45, .45, h=.08, alpha=.5)), run_time=0.8)
        self.gat("dos dois jeitos")
        acende(self, (mm, MEN), rt=0.8)
        self.marca("v2_12", agora=True)
        self.sai_fim()
