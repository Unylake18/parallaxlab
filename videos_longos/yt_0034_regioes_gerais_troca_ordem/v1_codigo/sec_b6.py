"""yt_0034 · B6 · seno de x³ (alvo 20). Glyph map 12. Leitura deitada pelos limites; a curva x = √y é a parábola y = x² e troca de papel
(entrada azul-claro na tira deitada → saída coral na tira em pé). Painel lateral pequeno (≈ 40 % do alvo 16) no canto vazio do palco (em cima,
à esquerda: o canto de baixo à direita é a própria região), com a miniatura do retângulo do sino por 2–3 s."""
from pecas34 import *

par = lambda a: a * a
X0 = .72


class PB6(B34):
    ANTES = "OUTRA INTEGRAL TRAVADA"

    def corpo(self):
        self.an("B6-1")
        pecasA = [("io", r"\int_{\Mg{0}}^{\Mg{1}}\!"), ("ii", r"\int_{\Az{\sqrt{\Y}}}^{\Co{1}}"), ("s", r"\sen(\X^3)"), ("dx", r"\,\dX"), ("dy", r"\,\dY")]
        A = L(pecasA, 960, 500, 52, "c")
        self.wait(0.1)
        self.pena(A, passo=0.09)
        for fr, ch in (("integral de zero a", "io"), ("raiz de ípsilon até", "ii"), ("de seno de xis", "s"), ("dê xis dê", "dx")):
            self.gat(fr)
            acende(self, (gl(A, ch), None), rt=0.6)
        self.gat("também não se escreve")
        sp = mixl([("m", r"\sen(\X^3)"), ("t", "SEM PRIMITIVA EM FÓRMULA", AL)], 700, 630, 34)
        sp.shift(RIGHT * ((960 - pxof(sp.get_center())[0]) / 120))
        self.pena(*sp.p, lag=0.12)
        self.gat("então o método")
        g = papel_v(TRI, (0, 1.12, 0, 1.12))
        self.grade = g
        sx, sy, lx, ly = eixos_v(TRI, 1.2, 1.2)
        spc = mixl([("m", r"\sen(\X^3)"), ("t", "SEM PRIMITIVA EM FÓRMULA", AL)], 1120, 320, 30)
        for a_, b_ in zip(sp.p, spc.p):
            ja_escrita(b_)
        self.play(Transform(A, L(pecasA, 1120, 220, 40, caneta=False)), *[Transform(a_, b_) for a_, b_ in zip(sp.p, spc.p)], FadeIn(g),
                  GrowFromPoint(sx, TRI.P(0, 0)), GrowFromPoint(sy, TRI.P(0, 0)), run_time=1.1)
        self.pena(lx, ly)
        # "Desenha": os limites voam da fórmula para o palco (deitado)
        self.gat("desenha ípsilon de")
        lo = sorted([x for x in gl(A, "io") if x.height < max(y.height for y in gl(A, "io"))], key=lambda x: x.get_center()[1])
        t0 = TC(r"\Mg{0}", *TRI.px(0, 0), 28, "r").shift(LEFT * 16 / 120 + UP * 4 / 120)
        t1 = tick(TRI, "y", 1, r"\Mg{1}")
        self.play(Create(t1[0]), run_time=0.3)
        voos(self, [(lo[0], t0), (lo[1], t1[1])], rt=1.0)
        self.gat("entra na curva")
        ii = list(gl(A, "ii"))
        alto = max(ii, key=lambda x: x.height)
        inf = VGroup(*[x for x in ii if x is not alto and x.get_center()[1] < alto.get_center()[1]])
        sup = VGroup(*[x for x in ii if x is not alto and x.get_center()[1] > alto.get_center()[1]])
        cv = curva(TRI, cX(par, 0, 1), AZC, 4)
        x1 = curva(TRI, [(1, 0), (1, 1)], CORAL, 4)
        risca_voando(self, [(inf, cv)], rt=1.1)
        rcv = rot(TRI, r"\Az{\X=\sqrt{\Y}}", (.55, .32), -24, -14, 30, "r")
        self.pena(rcv)
        self.gat("e sai em xis")
        risca_voando(self, [(sup, x1)], rt=1.0)
        rx1 = rot(TRI, r"\Co{\X=1}", (1, .75), 22, 0, 30, "l")
        self.pena(rx1)
        th = tiraH(TRI, .5, math.sqrt(.5), 1)
        pe, ps = pontos_es(TRI, (math.sqrt(.5), .5), (1, .5))
        self.play(GrowFromEdge(th, LEFT), FadeIn(pe, scale=.5), FadeIn(ps, scale=.5), run_time=0.8)
        # "pelo outro eixo": x = √y ⇔ y = x² (o quadrado atravessa) e a curva troca de rótulo e de cor (vira a saída da tira em pé)
        self.gat("pelo outro eixo")
        N0 = L([("l", r"\Az{\X=\sqrt{\Y}}")], 1120, 410, 40, caneta=False)
        voa(self, rcv.f, N0, rt=1.0)
        N1 = L([("l", r"\Az{\X=\sqrt{\Y}}"), ("eq", r"\ \Leftrightarrow\ "), ("r", r"\Co{\Y=\X^2}")], 1120, 410, 40)
        passo(self, N0, N1, [("l", "l")], rt=0.5, nota="mapa 12a (B6-1: x = √y ⇔ y = x², o quadrado atravessa)")
        self.gat("é a parábola")
        cv2 = curva(TRI, cX(par, 0, 1), CORAL, 4)
        rcv2 = rot(TRI, r"\Co{\Y=\X^2}", (.55, .32), -24, -14, 30, "r")
        x1d = curva(TRI, [(1, 0), (1, 1)], GEO, 2, dash=(6, 7), z=3)
        self.play(ReplacementTransform(cv, cv2), ReplacementTransform(rcv, rcv2), ReplacementTransform(x1, x1d), FadeOut(rx1), FadeOut(th), FadeOut(pe),
                  FadeOut(ps), run_time=1.2)
        self.remove(rx1, th, pe, ps)
        ja_escrita(rcv2.f)
        t1x = tick(TRI, "x", 1, r"\Am{1}")
        self.play(Create(t1x[0]), run_time=0.3)
        self.pena(t1x[1])
        self.gat("embaixo da parábola")
        reg = regiao(TRI, [(0, 0)] + cX(par, 0, 1) + [(1, 0)])
        self.play(FadeIn(reg), run_time=0.9)
        self.gat("agora fatia em pé")
        tv = tiraV(TRI, X0, 0, X0 * X0)
        pe2, ps2 = pontos_es(TRI, (X0, 0), (X0, X0 * X0))
        r0 = rot(TRI, r"\Az{\Y=0}", (.8, 0), 0, -30, 28)
        self.play(GrowFromEdge(tv, DOWN), FadeIn(pe2, scale=.5), FadeIn(ps2, scale=.5), run_time=0.8)
        self.pena(r0)
        self.gat("ípsilon de zero até")
        B1 = L([("eq", "="), ("io", r"\int_0^1\!"), ("ii", r"\int_{\Az{0}}^{\Co{\X^2}}"), ("s", r"\sen(\X^3)"), ("dy", r"\,\dY"), ("dx", r"\,\dX")], 1120, 520, 40,
               caneta=False)
        jj = list(gl(B1, "ii"))
        alto = max(jj, key=lambda x: x.height)
        supB = [k for k in sel(B1, "ii") if B1[0][k] is not alto and B1[0][k].get_center()[1] > alto.get_center()[1]]
        x2lab = VGroup(*[x for x in rcv2.f[0] if x.get_center()[0] > rcv2.f.get_center()[0]])
        voos(self, [(x2lab.copy(), parte(B1, supB, "x²"))], rt=1.0)                  # o x² voa da parábola para o limite de cima
        self.pena(parte(B1, [k for k in range(len(B1[0])) if k not in supB], "resto"))
        # painel lateral pequeno: a fatia em pé é um retângulo de altura sen(x³) e comprimento x²
        self.gat("não depende de ípsilon")
        LP = Lat(330, 590, 224, 176)
        hh = math.sin(X0 ** 3)
        ln = X0 * X0
        Gp = lateral(LP, 1.0, ymax=1.0, zt=(), yt=(), hcor=E2, hl=r"\Y", vl=r"\f", grade=False)
        rp = poly_px([LP.px(0, 0), LP.px(ln, 0), LP.px(ln, hh), LP.px(0, hh)], mixh(BG_, CI, .3), z=6)
        rp.set_stroke(E1, W(4), 1)
        lh = TC(r"\Ci{\sen(\X^3)}", *LP.px(ln + .08, hh), 26, "l")
        lc = TC(r"\Co{\X^2}", *LP.px(ln / 2, -.28), 28, "c")
        fundo = ret_px(300, 390, 600, 640, fill=BG_, fop=.92, z=5)
        self.play(FadeIn(fundo), GrowFromPoint(Gp["eh"], LP.P(0, 0)), GrowFromPoint(Gp["ev"], LP.P(0, 0)), run_time=0.5)
        self.pena(Gp["lh"], Gp["lv"])
        self.play(FadeIn(rp), run_time=0.6)
        self.pena(lh, lc, lag=0.2)
        self.gat("e a de dentro dá")
        self.wait(0.1)
        self.gat("no sino o comprimento")
        LS = Lat(640, 590, 224, 176)
        hs = gs(.6)
        rs = poly_px([LS.px(0, 0), LS.px(.6, 0), LS.px(.6, hs), LS.px(0, hs)], mixh(BG_, CI, .3), z=6)
        rs.set_stroke(E2, W(4), 1)
        es = TC(r"\Y", *LS.px(.3, -.28), 28, "c")
        ls_ = leg("SINO", LS.px(0, 0)[0], LS.px(0, hs)[1] - 18, GEO, "left", 26)
        fundo2 = ret_px(615, 390, 820, 640, fill=BG_, fop=.92, z=5)
        self.play(FadeIn(fundo2), FadeIn(rs), run_time=0.5)
        self.pena(es, ls_)
        self.wait(1.4)
        self.play(*[FadeOut(m) for m in (fundo2, rs, es, ls_)], run_time=0.4)
        self.remove(fundo2, rs, es, ls_)
        self.gat("trouxe xis ao quadrado")
        B2 = L([("eq", "="), ("io", r"\int_0^1"), ("x2", r"\X^2"), ("s", r"\sen(\X^3)"), ("dx", r"\,\dX")], 1120, 630, 40)
        passo(self, B1, B2, [("eq", "eq"), ("io", "io"), ("s", "s"), ("dx", "dx")], voos=[(lc.copy(), "x2")], rt=1.2, copia=True,
              nota="mapa 12b (B6-1: a de dentro dá x² sen(x³); o x² voa do comprimento)")
        ss = list(gl(B2, "s"))
        x3 = VGroup(*[x for x in ss if x.get_center()[0] > ss[2].get_center()[0]][:2])
        acende(self, (gl(B2, "x2"), E1), (x3, E1), rt=1.2)
        self.gat("mesmo raciocínio outra")
        self.play(cv2.animate.set_stroke(width=W(7)), reg.animate.set_fill(mixh(BG_, GEO, .3)), run_time=0.5)
        self.play(cv2.animate.set_stroke(width=W(4)), reg.animate.set_fill(RB), run_time=0.5)
        self.gat("um menos cosseno de")
        B3 = L([("eq", "="), ("fr", r"\dfrac{1-\cos 1}{3}"), ("ap", r"\approx 0{,}153")], 1120, 750, 44)
        passo(self, B2, B3, [("eq", "eq"), (["io", "x2", "s", "dx"], "fr")], rt=1.3, copia=True, nota="mapa 12c (B6-1: = (1 − cos 1)/3 ≈ 0,153)")
        self.play(*[FadeOut(m) for m in (fundo, rp, lh, lc, Gp["eh"], Gp["ev"], Gp["lh"], Gp["lv"])], run_time=0.5)
        self.remove(fundo, rp, lh, lc, Gp["eh"], Gp["ev"], Gp["lh"], Gp["lv"])
        self.marca("20", agora=True)
        self.sai_fim()
