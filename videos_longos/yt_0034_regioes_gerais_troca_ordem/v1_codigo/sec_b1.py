        self.play(FadeOut(hl), FadeOut(ts3[0]), FadeOut(ts3[1]), FadeOut(z1), FadeOut(z2), run_time=0.3)     # os zeros saem do caminho da faca
        self.play(xt.animate.set_value(0.0), run_time=1.6)
        self.gat("perto de xis igual")
        self.play(xt.animate.set_value(1.9), run_time=2.6)
        self.play(xt.animate.set_value(1.0), run_time=1.4)
        self.play(FadeIn(hl), FadeIn(ts3[0]), FadeIn(ts3[1]), FadeIn(z1), FadeIn(z2), run_time=0.3)
