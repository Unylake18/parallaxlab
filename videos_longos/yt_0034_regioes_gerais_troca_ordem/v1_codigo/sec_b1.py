        FF = L([("im", r"\Rightarrow\ "), ("a", r"\iint_B\f\,dA="), ("io", r"\int_{\Am{a}}^{\Am{b}}\!"), ("ii", r"\int_{\Az{c(\X)}}^{\Co{d(\X)}}"),
                ("r", r"\f\,\dY\,\dX")], 1120, 630, 42)
