        self.play(Create(t1[0]), run_time=0.3)
        self.pena(t1[1])
        self.gat("a fatia atravessa")
        cheia = tiraV(CH, 1, 0, 2)
        self.play(GrowFromEdge(cheia, DOWN), run_time=2.6, rate_func=linear)
        self.gat("só soma zeros")
        tira = always_redraw(lambda: tiraV(CH, xt.get_value(), 0, max(.002, sai_())))
        apag = always_redraw(lambda: curva(CH, [(xt.get_value() - .03, sai_()), (xt.get_value() - .03, 2), (xt.get_value() + .03, 2),
                                                 (xt.get_value() + .03, sai_())], mixh(BG_, E1, .55), 2, dash=(6, 6), z=4))
