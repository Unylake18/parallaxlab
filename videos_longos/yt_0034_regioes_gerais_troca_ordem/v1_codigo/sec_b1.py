        self.gat("essas linhas têm")
        self.play(*[m.animate.set_stroke(width=W(5)) for m in (fa, fs1, fs2)], run_time=0.5)
        self.play(*[m.animate.set_stroke(width=W(2.5)) for m in (fa, fs1, fs2)], run_time=0.5)
        self.gat("a estendida é integrável")
        self.play(Create(c1[1]), run_time=0.4)
        self.pena(c1[2])
        self.gat("cada fatia vale zero")
        Lv = Lat(300, 975, 200, 40)
        G = lateral(Lv, 2.3, ymax=2.25, zt=(0, 2), yt=(0, 2))
        uf = leg("UMA FATIA", 760, 895, GEO, "left", 26)
        self.play(FadeIn(G["grade"]), GrowFromPoint(G["eh"], Lv.P(0, 0)), GrowFromPoint(G["ev"], Lv.P(0, 0)), run_time=0.7)
