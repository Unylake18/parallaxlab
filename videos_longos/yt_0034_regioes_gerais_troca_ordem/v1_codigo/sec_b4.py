def integral_hook(X, Y, size, caneta=True):
    return L([("io", r"\int_{\Am{0}}^{\Am{1}}\!"), ("ii", r"\int_{\Az{\X}}^{\Co{1}}"), ("e", r"e^{-\Y^2}"), ("dy", r"\,\dY"), ("dx", r"\,\dX")],
             X, Y, size, "l", caneta)


def sem_alto(m, chave):
    g = list(gl(m, chave))
    a = max(g, key=lambda x: x.height)
    return [x for x in g if x is not a], a


