"""yt_0034 · B8 · regiões gerais no mundo (alvo 24): três cartões em traço GEO (encontro, curva normal, peça recortada). Legendas a 26 px."""
from pecas34 import *


class PB8(B34):
    ANTES = "REGIÕES GERAIS NO MUNDO"

    def corpo(self):
        self.an("B8")
        p1, p2, p3 = painel(100, 200, 520, 700), painel(700, 200, 520, 700), painel(1300, 200, 520, 700)
        V = Vw(230, 700, 380)
        self.play(Create(p1), run_time=0.5)
        self.gat("na probabilidade o")
        sq = ret_px(*V.px(0, 1), *V.px(1, 0), fill="#1C1846", fop=1, stroke=GEO, wpx=2, z=2)
        self.play(FadeIn(sq), run_time=0.6)
        self.gat("dois amigos combinam")
        realce(self, sq)                                               # o quadrado dos horários
        self.gat("entre meio dia e")
        ana = leg("ANA", *V.px(.5, -.12), E1, "center", 26)
        q = V.px(-.04, .5)
        bia = leg("BIA", q[0] - 6, q[1] + 8, E2, "right", 26)
        self.pena(ana, bia, lag=0.3)
        self.gat("num horário sorteado")
        pp = ponto_px(*V.px(.3, .62), BR, 7, z=6)
        pj = VGroup(curva(V, [(.3, 0), (.3, .62)], GEO, 1.5, dash=(4, 4), z=5), curva(V, [(0, .62), (.3, .62)], GEO, 1.5, dash=(4, 4), z=5))
        self.play(FadeIn(pp, scale=.5), Create(pj), run_time=0.8)
        self.gat("sem um depender do")
        h1 = leg("HORÁRIOS UNIFORMES", 360, 790, GEO, "center", 26)
        h2 = leg("E INDEPENDENTES", 360, 824, GEO, "center", 26)
        self.pena(h1, h2, lag=0.3)
        self.gat("espera só quinze")
        dg = curva(V, [(0, 0), (1, 1)], BR, 2, dash=(5, 5), z=4)
        self.play(Create(dg), run_time=0.8)
        self.gat("coloca o horário de")
        acende(self, (ana, E1), rt=0.6)
        self.gat("e o do outro")
        acende(self, (bia, E2), rt=0.6)
        self.gat("é a faixa em")
        faixa = regiao(V, [(0, 0), (.25, 0), (1, .75), (1, 1), (.75, 1), (0, .25)], mixh(BG_, CI, .45), z=3)
        self.play(FadeIn(faixa), run_time=0.9)
        self.gat("de um quarto de hora")
        realce(self, faixa, dg)                                        # a faixa em volta da diagonal
        # C9 (handoff v3 §2): fatiando daria três pedaços; o atalho é o complemento: dois triângulos nos cantos, com catetos 3/4 (chaves)
        self.gat("daria três pedaços")
        c1 = curva(V, [(.25, 0), (.25, 1)], GEO, 1.5, dash=(4, 5), z=5)
        c2 = curva(V, [(.75, 0), (.75, 1)], GEO, 1.5, dash=(4, 5), z=5)
        self.play(Create(c1), Create(c2), FadeOut(pp), FadeOut(pj), run_time=0.6)
        self.remove(pp, pj)
        self.gat("tem um atalho")
        self.play(FadeOut(c1), FadeOut(c2), run_time=0.4)
        self.remove(c1, c2)
        self.gat("olha o que fica")
        t1_ = regiao(V, [(.25, 0), (1, 0), (1, .75)], mixh(BG_, AL, .35), z=3)
        t2_ = regiao(V, [(0, .25), (0, 1), (.75, 1)], mixh(BG_, AL, .35), z=3)
        b1_ = curva(V, [(.25, 0), (1, 0), (1, .75), (.25, 0)], AL, 2.5, z=6)
        b2_ = curva(V, [(0, .25), (0, 1), (.75, 1), (0, .25)], AL, 2.5, z=6)
        fo = leg("FORA", *V.px(.78, .22), AL, "center", 26)
        fo2 = leg("FORA", *V.px(.22, .8), AL, "center", 26)
        self.play(FadeIn(t1_), FadeIn(t2_), Create(b1_), Create(b2_), FadeOut(h1), FadeOut(h2), run_time=0.8)   # as hipóteses saem (as chaves 3/4 ocupam a faixa de baixo)
        self.remove(h1, h2)
        self.pena(fo, fo2, lag=0.2)
        self.gat("com catetos de")
        ch1 = chave_px(V.px(.25, 0)[0], V.px(1, 0)[0], V.px(0, 0)[1] + 12, AL)
        q1 = V.px(.625, 0)
        l1_ = TC(r"\Al{\dfrac{3}{4}}", q1[0] + 44, q1[1] + 66, 26, "c")
        ch2 = chave_px(V.px(0, 1)[0], V.px(.75, 1)[0], V.px(0, 1)[1] - 12, AL).rotate(PI)
        q2 = V.px(.375, 1)
        l2_ = TC(r"\Al{\dfrac{3}{4}}", q2[0], q2[1] - 66, 26, "c")
        self.play(Create(ch1), Create(ch2), run_time=0.5)
        self.pena(l1_, l2_, lag=0.2)
        self.gat("cada um tem área")
        F_ = mixl([("t", "FORA =", AL), ("m", r"2\cdot\dfrac{1}{2}\cdot\Big(\dfrac{3}{4}\Big)^2"), ("m", r"=\dfrac{9}{16}")], 700, 430, 38)
        self.pena(F_.p[0], F_.p[1], lag=0.15)
        self.gat("nove dezesseis avos")
        self.pena(F_.p[2])
        self.gat("é um menos")
        C_ = mixl([("t", "CHANCE =", MEN), ("m", r"1-\dfrac{9}{16}"), ("m", r"=\dfrac{7}{16}"), ("m", r"\approx 44\%")], 700, 560, 38)
        self.pena(C_.p[0], C_.p[1], lag=0.15)
        self.gat("sete dezesseis avos")
        self.pena(C_.p[2])
        realce(self, faixa, cor=MEN)
        self.gat("quase quarenta e")
        self.pena(C_.p[3])
        self.marca("v3_c9", agora=True)
        self.gat("e aquele sino")
        pr = TC(r"\dfrac{7}{16}\approx 44\%", 360, 265, 38, "c")
        sai_ = [t1_, t2_, b1_, b2_, fo, fo2, ch1, ch2, l1_, l2_, *F_.p, C_.p[0], C_.p[1]]
        voos(self, [(VGroup(C_.p[2], C_.p[3]).copy(), pr)], rt=0.9, extra=[*[FadeOut(m) for m in sai_ + [C_.p[2], C_.p[3]]]])
        self.remove(*sai_, C_.p[2], C_.p[3])
        V2 = Vw(960, 640, 100)
        self.play(Create(p2), run_time=0.5)
        ar = regiao(V2, [(-2.3, 0)] + cX(lambda a: 2.6 * math.exp(-a * a), -2.3, 2.3) + [(2.3, 0)], mixh(BG_, CI, .3), z=2)
        cv = curva(V2, cX(lambda a: 2.6 * math.exp(-a * a), -2.3, 2.3), CI, 4)
        bs = curva(V2, [(-2.4, 0), (2.4, 0)], GEO, 2)
        self.play(Create(bs), Create(cv), run_time=1.0)
        self.play(FadeIn(ar), run_time=0.5)
        ex = TC(r"\Ci{e^{-\X^2}}", 960, 300, 38, "c")
        self.pena(ex)
        self.gat("curva normal da")
        cn = leg("CURVA NORMAL", 960, 790, GEO, "center", 26)
        self.pena(cn)
        self.gat("não tem primitiva em")
        acende(self, (ex, AL), rt=0.8)
        self.gat("na engenharia a")
        realce(self, ar)                                               # a área sob o sino: uma integral numa região de borda curva
        V3 = Vw(1400, 700, 90)
        b2 = cX(lambda a: 2.2 + 1.2 * math.sin(PI * a / 4) - .9 * a / 4, 0, 4)
        self.play(Create(p3), run_time=0.5)
        pc = regiao(V3, [(0, 0), (4, 0)] + b2[::-1], mixh(BG_, CI, .3), z=2)
        l1 = curva(V3, [(0, 0), (4, 0)], GEO, 2)
        l2 = curva(V3, [(0, 0), (0, b2[0][1])], GEO, 2)
        l3 = curva(V3, [(4, 0), (4, b2[-1][1])], GEO, 2)
        bc = curva(V3, b2, CORAL, 4)
        self.play(Create(l1), Create(l2), Create(l3), run_time=0.6)
        self.play(Create(bc), FadeIn(pc), run_time=0.9)
        pr2 = leg("PEÇA RECORTADA", 1560, 790, GEO, "center", 26)
        self.pena(pr2)
        self.gat("peça recortada com")
        realce(self, cv, cor=CI, dur=1.0)                              # borda curva, como a do sino (curto: acaba antes da marca 24)
        self.gat("é exatamente uma integral")
        ms = mixl([("t", "MASSA ="), ("m", r"\iint_B\rr\,dA")], 1360, 290, 34)
        self.pena(*ms.p, lag=0.15)
        self.marca("24", agora=True)
        self.gat("numa região geral")
        realce(self, ar, faixa, atraso=0.4)                            # integrais em regiões gerais
        self.sai_fim()
