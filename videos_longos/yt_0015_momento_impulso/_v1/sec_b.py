"""Lote B: C04 (bola na parede), C05 (chute em 2D), C06 (força que cresce com o tempo)."""
from kit import *  # noqa: F401,F403

KP = 0.15                                   # u por kg·m/s no C04


def tex(s, cor=WHITE_, size=M_MID):
    return MathTex(s, font_size=size, color=cor)


class LoteB(Base):
    def construct(self):
        self.setup_base(cap="IMPULSO")
        self.c04()
        self.c05()
        self.c06()
        self.fim()
        self.relatorio()

    def bola_vel(self, x, y, comp, cor=VEL, w=5):
        b = bola(0.28).move_to(P3(x, y))
        a = arrow(P3(x, y), P3(x + comp[0], y + comp[1]), color=cor, width=w)
        return b, a

    # ── C04 ─────────────────────────────────────────────────────────────────────────────────────────────────
    def c04(self):
        self.clear(rt=0.6)
        self.secao("EXERCÍCIO 1 · BOLA NA PAREDE", "SEARS · EX. 8.2")
        self.an("C04-1")
        parede = Rectangle(width=0.5, height=4.4).set_stroke(GEO, 2).set_fill(STEEL, 0.45).move_to(P3(-7.0, -0.4))
        x_ = VGroup(Arrow(P3(-7.0, -3.5), P3(-5.6, -3.5), buff=0, color=DIM, stroke_width=3, tip_length=0.16),
                    tex("+x", DIM, 34).move_to(P3(-5.2, -3.5)))
        r1 = txt("ANTES", T_SMALL, color=DIM).move_to(P3(-6.0, 1.5))
        r2 = txt("DEPOIS", T_SMALL, color=DIM).move_to(P3(-6.0, -1.0))
        b1, a1 = self.bola_vel(-1.6, 1.4, (-2.4, 0))
        b2, a2 = self.bola_vel(-4.9, -1.5, (1.6, 0))
        t1 = tex(r"30\ \mathrm{m/s}", VEL, 34).next_to(a1, UP, buff=0.12)
        t2 = tex(r"20\ \mathrm{m/s}", VEL, 34).next_to(a2, UP, buff=0.12)
        dados = VGroup(tex(r"m=0{,}40\ \mathrm{kg}", WHITE_, 44), tex(r"\Delta t=0{,}010\ \mathrm{s}", WHITE_, 44)) \
            .arrange(DOWN, buff=0.35, aligned_edge=LEFT).move_to(P3(4.3, 2.0))
        self.play(FadeIn(parede), FadeIn(x_), run_time=0.7)
        self.play(FadeIn(r1), FadeIn(b1), GrowArrow(a1), FadeIn(t1), run_time=0.9)
        self.ate(0.35)
        self.play(FadeIn(r2), FadeIn(b2), GrowArrow(a2), FadeIn(t2), run_time=0.9)
        self.ate(0.6)
        self.play(FadeIn(dados), run_time=0.7)
        self.ate(0.97)
        # C04-2 ----------------------------------------------------------------------------------------------
        self.an("C04-2")
        vi = Mc((r"v_i", VEL), "=", (r"-30\ \mathrm{m/s}", VEL), size=M_MID)
        vf = Mc((r"v_f", VEL), "=", (r"+20\ \mathrm{m/s}", VEL), size=M_MID)
        VGroup(vi, vf).arrange(DOWN, buff=0.35, aligned_edge=LEFT).move_to(P3(4.3, -0.1))
        self.play(FadeIn(vi), run_time=0.7)
        self.play(Indicate(vi[2], color=WHITE_, scale_factor=1.15), run_time=0.9)
        self.play(FadeIn(vf), run_time=0.7)
        self.ate(0.97)
        # C04-3 ----------------------------------------------------------------------------------------------
        self.an("C04-3")
        self.play(*[FadeOut(m) for m in (r1, r2, b1, a1, t1, b2, a2, t2)], run_time=0.5)
        o = P3(-3.2, 0.9)
        pi_ = arrow(o, o + P3(-12 * KP, 0), color=MAG, width=7)
        pf_ = arrow(o, o + P3(8 * KP, 0), color=MAG, width=7)
        o2 = o + P3(-12 * KP, -1.0)
        dp = arrow(o2, o2 + P3(20 * KP, 0), color=MAG, width=9)
        lpi = tex(r"\vec p_i", MAG, 38).next_to(pi_, UP, buff=0.12)
        lpf = tex(r"\vec p_f", MAG, 38).next_to(pf_, UP, buff=0.12)
        ldp = tex(r"\Delta\vec p", MAG, 38).next_to(dp, DOWN, buff=0.12)
        zero = DashedLine(o + P3(0, 0.3), o + P3(0, -1.5), color=DIM, stroke_width=2)
        liga = VGroup(DashedLine(o + P3(-12 * KP, 0), o2, color=DIM, stroke_width=2),
                      DashedLine(o + P3(8 * KP, 0), o2 + P3(20 * KP, 0), color=DIM, stroke_width=2))
        self.play(GrowArrow(pi_), FadeIn(lpi), run_time=0.7)
        self.play(GrowArrow(pf_), FadeIn(lpf), FadeIn(zero), run_time=0.7)
        self.play(FadeIn(liga), GrowArrow(dp), FadeIn(ldp), run_time=0.8)
        eqJ = Mc((r"J", JC), "=", (r"0{,}40", WHITE_), (r"(20-(-30))", WHITE_), "=", (r"20\ \mathrm{N\cdot s}", JC), size=44)
        eqJ.move_to(P3(4.3, -1.7))
        self.ate(0.5)
        self.play(FadeIn(eqJ, shift=0.1 * UP), run_time=0.9)
        self.ate(0.97)
        # C04-4 ----------------------------------------------------------------------------------------------
        self.an("C04-4")
        errada = MathTex(r"0{,}40\,(20-30)=-4\ \mathrm{N\cdot s}", font_size=44, color=APAGADO).move_to(P3(4.3, -3.0))
        pq = txt("A PAREDE PUXOU A BOLA?", T_LAB, color=WHITE_).next_to(errada, UP, buff=0.0).shift(UP * 0.0)
        pq.move_to(P3(-3.0, -3.1))
        self.play(FadeIn(errada, shift=0.1 * UP), run_time=0.8)
        rsc = risco(errada, w=5)
        self.play(Create(rsc), run_time=0.6)
        self.play(FadeIn(pq), run_time=0.6)
        self.ate(0.97)
        # C04-5 ----------------------------------------------------------------------------------------------
        self.an("C04-5")
        self.play(*[FadeOut(m) for m in (errada, rsc, pq, pi_, pf_, dp, lpi, lpf, ldp, zero, liga, vi, vf, dados, eqJ)] +
                 [m.animate.set_opacity(0) for m in ()], run_time=0.5)
        bb = bola(0.28).move_to(P3(-5.9, 0.3))
        fa = arrow(P3(-5.6, 0.3), P3(-2.6, 0.3), color=FC, width=9, tip=0.26)
        fl = tex(r"\vec F", FC, 44).next_to(fa, UP, buff=0.15)
        peso = arrow(P3(-5.9, 0.0), P3(-5.9, -0.45), color=FC, width=4, tip=0.12)
        pl = tex(r"m g=3{,}9\ \mathrm{N}", FC, 30).next_to(peso, DOWN, buff=0.12).shift(RIGHT * 0.5)
        fm = Mc((r"F_{\mathrm{m\acute{e}d}}", FC), "=", (r"\frac{20}{0{,}010}", JC), "=", (r"2.000\ \mathrm{N}", FC), size=M_MID)
        fm.move_to(P3(3.3, 0.9))
        self.play(FadeIn(bb), GrowArrow(fa), FadeIn(fl), run_time=0.8)
        self.play(FadeIn(fm, shift=0.1 * UP), run_time=0.8)
        self.ate(0.6)
        self.play(GrowArrow(peso), FadeIn(pl), run_time=0.7)
        self.ate(0.97)
        # C04-6 ----------------------------------------------------------------------------------------------
        self.an("C04-6")
        self.play(*[FadeOut(m) for m in (bb, fa, fl, peso, pl, fm)], FadeOut(parede), FadeOut(x_), run_time=0.5)
        zx, k = -2.6, KP
        grp = VGroup()
        for y, nome, extra in ((1.2, "PARAR", False), (-1.5, "REBATER", True)):
            r = txt(nome, T_MAIN, bold=True).move_to(P3(-5.8, y))
            pin = arrow(P3(zx, y + 0.5), P3(zx - 12 * k, y + 0.5), color=MAG, width=6)
            dpa = arrow(P3(zx - 12 * k, y - 0.2), P3(zx + (8 * k if extra else 0), y - 0.2), color=MAG, width=8)
            z = DashedLine(P3(zx, y + 0.9), P3(zx, y - 0.6), color=DIM, stroke_width=2)
            ld = tex(r"\Delta\vec p", MAG, 38).next_to(dpa, DOWN, buff=0.1)
            grp.add(r, pin, dpa, z, ld)
        self.play(FadeIn(grp[:5]), run_time=0.9)
        self.ate(0.45)
        self.play(FadeIn(grp[5:]), run_time=0.9)
        nota = tex(r"|\Delta\vec p|:\ 12\ \to\ 20", MAG, 44).move_to(P3(4.3, -0.2))
        self.ate(0.7)
        self.play(FadeIn(nota), run_time=0.7)
        self.ate(0.97)
        self.AUX = (zx, k)

    # ── C05 ─────────────────────────────────────────────────────────────────────────────────────────────────
    def c05(self):
        self.clear(rt=0.6)
        self.secao("EXERCÍCIO 2 · CHUTE EM 2D", "SEARS · EX. 8.3")
        self.an("C05-1")
        r1 = txt("ANTES", T_SMALL, color=DIM).move_to(P3(-6.6, 1.3))
        r2 = txt("DEPOIS", T_SMALL, color=DIM).move_to(P3(-6.6, -1.6))
        b1, a1 = self.bola_vel(-2.2, 1.3, (-2.0, 0))
        b2, a2 = self.bola_vel(-5.0, -1.9, (3.0 * math.cos(PI / 4), 3.0 * math.sin(PI / 4)))
        t1 = tex(r"20\ \mathrm{m/s}", VEL, 34).next_to(a1, UP, buff=0.12)
        t2 = tex(r"30\ \mathrm{m/s}", VEL, 34).move_to(P3(-2.0, 0.15))
        pe = RoundedRectangle(corner_radius=0.12, width=1.2, height=0.38).set_stroke(mix(STEEL, 0.5), 2).set_fill(STEEL, 1.0) \
            .rotate(-PI / 6).move_to(P3(-5.7, -2.35))
        pe_t = txt("CHUTE", T_SMALL, color=DIM).next_to(pe, DOWN, buff=0.15)
        dados = VGroup(tex(r"m=0{,}40\ \mathrm{kg}", WHITE_, 44), tex(r"\Delta t=0{,}010\ \mathrm{s}", WHITE_, 44)) \
            .arrange(DOWN, buff=0.35, aligned_edge=LEFT).move_to(P3(4.6, 2.0))
        self.play(FadeIn(r1), FadeIn(b1), GrowArrow(a1), FadeIn(t1), run_time=0.9)
        self.ate(0.3)
        self.play(FadeIn(pe), FadeIn(pe_t), run_time=0.6)
        self.play(FadeIn(r2), FadeIn(b2), GrowArrow(a2), FadeIn(t2), run_time=0.9)
        self.ate(0.6)
        self.play(FadeIn(dados), run_time=0.7)
        self.ate(0.97)
        # C05-2 ----------------------------------------------------------------------------------------------
        self.an("C05-2")
        c = 3.0 * math.cos(PI / 4)
        cx_ = DashedLine(P3(-5.0, -1.9), P3(-5.0 + c, -1.9), color=DIM, stroke_width=3)
        cy_ = DashedLine(P3(-5.0 + c, -1.9), P3(-5.0 + c, -1.9 + c), color=DIM, stroke_width=3)
        vfx = Mc((r"v_{f,x}=v_{f,y}=21{,}2\ \mathrm{m/s}", VEL), size=40).move_to(P3(4.6, -0.2))
        vix = Mc((r"v_{i,x}=-20\ \mathrm{m/s},\ \ v_{i,y}=0", VEL), size=40).move_to(P3(4.6, -1.3))
        self.play(Create(cx_), Create(cy_), run_time=0.9)
        self.play(FadeIn(vfx), run_time=0.7)
        self.ate(0.6)
        self.play(FadeIn(vix), run_time=0.7)
        self.ate(0.97)
        # C05-3 ----------------------------------------------------------------------------------------------
        self.an("C05-3")
        self.play(FadeOut(dados), FadeOut(vfx), FadeOut(vix), run_time=0.4)
        jx = Mc((r"J_x", JC), "=", r"0{,}40\,(21{,}2+20)", "=", (r"16{,}5\ \mathrm{N\cdot s}", JC), size=40).move_to(P3(4.0, 0.6))
        jy = Mc((r"J_y", JC), "=", r"0{,}40\cdot 21{,}2", "=", (r"8{,}5\ \mathrm{N\cdot s}", JC), size=40).move_to(P3(4.0, -0.7))
        self.play(FadeIn(jx, shift=0.1 * UP), run_time=0.9)
        self.ate(0.55)
        self.play(FadeIn(jy, shift=0.1 * UP), run_time=0.9)
        self.ate(0.97)
        # C05-4 ----------------------------------------------------------------------------------------------
        self.an("C05-4")
        self.play(*[FadeOut(m) for m in (r1, r2, b1, a1, t1, b2, a2, t2, pe, pe_t, cx_, cy_, jx, jy)], run_time=0.5)
        s = 0.32
        o = P3(-3.4, -1.2)
        pi_v, pf_v = np.array([-8.0, 0, 0]) * s, np.array([8.49, 8.49, 0]) * s
        pi_a = arrow(o, o + pi_v, color=MAG, width=6)
        pf_a = arrow(o, o + pf_v, color=MAG, width=6)
        dp_a = arrow(o + pi_v, o + pf_v, color=MAG, width=9, tip=0.24)
        l1 = tex(r"\vec p_i", MAG, 38).next_to(pi_a, DOWN, buff=0.1).shift(LEFT * 0.4)
        l2 = tex(r"\vec p_f", MAG, 38).next_to(pf_a, UP, buff=0.1).shift(RIGHT * 0.5)
        l3 = tex(r"\Delta\vec p", MAG, 38).move_to(o + pi_v + (pf_v - pi_v) * 0.5 + P3(-0.7, 0.35))
        self.play(GrowArrow(pi_a), FadeIn(l1), run_time=0.7)
        self.play(GrowArrow(pf_a), FadeIn(l2), run_time=0.7)
        self.play(GrowArrow(dp_a), FadeIn(l3), run_time=0.9)
        fmed = arrow(o + pi_v + P3(0.7, -1.5), o + pi_v + (pf_v - pi_v) * 0.9 + P3(0.7, -1.5), color=FC, width=7, tip=0.22)
        fl = tex(r"\vec F_{\mathrm{m\acute{e}d}}", FC, 38).next_to(fmed, DOWN, buff=0.1).shift(RIGHT * 0.8)
        res = Mc((r"F_{\mathrm{m\acute{e}d}}", FC), "=", (r"\frac{\Delta p}{\Delta t}", MAG), size=M_MID).move_to(P3(4.5, 1.3))
        res2 = Mc((r"1{,}9\times10^{3}\ \mathrm{N}\ \text{a}\ 27^\circ", FC), size=44).move_to(P3(4.5, 0.0))
        self.ate(0.45)
        self.play(GrowArrow(fmed), FadeIn(fl), FadeIn(res), run_time=0.9)
        self.play(FadeIn(res2), run_time=0.7)
        self.ate(0.97)
        # C05-5 ----------------------------------------------------------------------------------------------
        self.an("C05-5")
        ang_dp = math.degrees(math.atan2(8.49, 16.49))
        arco1 = Arc(radius=0.9, start_angle=0, angle=math.radians(ang_dp), arc_center=o + pi_v, color=WHITE_, stroke_width=2)
        a27 = tex(r"27^\circ", WHITE_, 34).move_to(o + pi_v + P3(1.45, 0.3))
        hor = DashedLine(o + pi_v, o + pi_v + P3(2.2, 0), color=DIM, stroke_width=2)
        arco2 = Arc(radius=0.9, start_angle=0, angle=PI / 4, arc_center=o, color=WHITE_, stroke_width=2)
        a45 = tex(r"45^\circ", WHITE_, 34).move_to(o + P3(1.35, 0.4))
        hor2 = DashedLine(o, o + P3(2.2, 0), color=DIM, stroke_width=2)
        self.play(FadeIn(hor), Create(arco1), FadeIn(a27), run_time=0.9)
        self.play(FadeIn(hor2), Create(arco2), FadeIn(a45), run_time=0.9)
        n1 = Mc((r"\vec F_{\mathrm{m\acute{e}d}}\ \parallel\ \Delta\vec p", FC), size=44).move_to(P3(4.5, 1.3))
        n2 = Mc((r"\neq\ \vec v_f", VEL), size=44).move_to(P3(4.5, 0.0))
        self.play(FadeOut(res), FadeOut(res2), run_time=0.4)
        self.play(FadeIn(n1), run_time=0.7)
        self.ate(0.7)
        self.play(FadeIn(n2), run_time=0.7)
        self.ate(0.97)

    # ── C06 ─────────────────────────────────────────────────────────────────────────────────────────────────
    def c06(self):
        self.clear(rt=0.6)
        self.secao("EXERCÍCIO 3 · FORÇA QUE CRESCE COM O TEMPO", "SEARS · EXERC. 8.11")
        self.an("C06-1")
        G = Graf(-6.0, -3.0, 6.6, 5.3, 4.0, 8000, MathTex(r"F", font_size=40, color=FC))
        A = 500.0
        fun = lambda t: A * t * t
        curva = G.curva(fun, 0.0, 3.9, n=200)
        pto = Dot(G.pt(1.25, fun(1.25)), radius=0.09, color=WHITE_).set_z_index(9)
        lab = tex(r"(1{,}25\ \mathrm{s};\ 781{,}25\ \mathrm{N})", WHITE_, 32).next_to(pto, UP, buff=0.2).shift(LEFT * 1.3 + UP * 0.35)
        # foguete 2D (silhueta simples)
        corpo = RoundedRectangle(corner_radius=0.25, width=0.6, height=1.6).set_stroke(mix(STEEL, 0.5), 2).set_fill(STEEL, 1.0)
        nariz = Triangle().set_stroke(mix(STEEL, 0.5), 2).set_fill(GEO, 1.0).scale(0.3).next_to(corpo, UP, buff=-0.02)
        asa1 = Polygon(P3(-0.3, -0.8), P3(-0.62, -1.1), P3(-0.3, -0.35)).set_stroke(mix(STEEL, 0.5), 2).set_fill(STEEL, 1.0)
        asa2 = asa1.copy().flip(RIGHT)
        asa2.move_to(P3(0.46, -0.8), aligned_edge=ORIGIN)
        foguete = VGroup(corpo, nariz, asa1, asa2).move_to(P3(6.5, 2.0)).rotate(0)
        asa2.move_to(corpo.get_center() + P3(0.46, -0.52))
        asa1.move_to(corpo.get_center() + P3(-0.46, -0.52))
        chama = Polygon(P3(-0.15, 0), P3(0.15, 0), P3(0, -0.6)).set_stroke(WHITE_, 2).set_fill(WHITE_, 0.55) \
            .next_to(corpo, DOWN, buff=0.0)
        foguete.add(chama)
        msg = tex(r"m=2.150\ \mathrm{kg}", WHITE_, 40).next_to(foguete, LEFT, buff=0.5)
        feq = Mc((r"F", FC), "=", "A", (r"t^{2}", WHITE_), size=M_MID).move_to(P3(3.0, 0.5))
        self.play(FadeIn(G.eixos), FadeIn(foguete), FadeIn(msg), run_time=0.9)
        self.ate(0.25)
        self.play(Create(curva), run_time=2.0)
        self.play(FadeIn(feq, shift=0.1 * UP), run_time=0.6)
        self.ate(0.6)
        self.play(FadeIn(pto), FadeIn(lab), run_time=0.7)
        self.ate(0.97)
        # C06-2 ----------------------------------------------------------------------------------------------
        self.an("C06-2")
        aeq = Mc((r"A", WHITE_), "=", r"\frac{781{,}25}{1{,}25^{2}}", "=", r"500\ \mathrm{N/s^{2}}", size=44).move_to(P3(3.6, -0.7))
        self.play(FadeIn(aeq, shift=0.1 * UP), run_time=0.9)
        self.ate(0.97)
        # C06-3 ----------------------------------------------------------------------------------------------
        self.an("C06-3")
        self.play(FadeOut(lab), FadeOut(msg), run_time=0.4)
        t2l = tex(r"2{,}0", DIM, 32).next_to(G.pt(2.0, 0), DOWN, buff=0.12)
        t35 = tex(r"3{,}5", DIM, 32).next_to(G.pt(3.5, 0), DOWN, buff=0.12)
        self.play(FadeIn(t2l), FadeIn(t35), run_time=0.5)
        tt = ValueTracker(2.0)
        area = always_redraw(lambda: G.area(fun, 2.0, max(tt.get_value(), 2.001), n=100))
        self.add(area)
        self.play(tt.animate.set_value(3.5), run_time=3.0, rate_func=linear)
        area.clear_updaters()
        jeq = Mc((r"J", JC), "=", (r"\int_{2{,}0}^{3{,}5}500\,t^{2}\,dt", JC), size=40).move_to(P3(3.6, 1.0))
        jeq2 = Mc("=", r"\frac{500}{3}\,(3{,}5^{3}-2{,}0^{3})", size=40).next_to(jeq, DOWN, buff=0.3, aligned_edge=LEFT)
        self.play(FadeOut(feq), FadeOut(aeq), run_time=0.4)
        self.play(FadeIn(jeq, shift=0.1 * UP), run_time=0.8)
        self.ate(0.65)
        self.play(FadeIn(jeq2, shift=0.1 * UP), run_time=0.8)
        self.ate(0.97)
        # C06-4 ----------------------------------------------------------------------------------------------
        self.an("C06-4")
        j = area_num(fun, 2.0, 3.5)
        print(f"[QA] C06 J = {j:.2f} N·s (alvo 5812,5); F_med = {j / 1.5:.1f} N; Δv = {j / 2150:.3f} m/s")
        r = G.retangulo(2.0, 3.5, 3875.0)
        res = Mc((r"J\approx5{,}81\times10^{3}\ \mathrm{N\cdot s}", JC), size=40).move_to(P3(3.6, -0.7))
        dv = Mc((r"\Delta v=\frac{J}{m}=2{,}70\ \mathrm{m/s}", VEL), size=40).move_to(P3(3.6, -1.9))
        fm = Mc((r"F_{\mathrm{m\acute{e}d}}=3.875\ \mathrm{N}", FC), size=40).move_to(P3(3.6, -3.1))
        self.play(FadeOut(jeq), FadeOut(jeq2), run_time=0.4)
        self.play(FadeIn(res, shift=0.1 * UP), run_time=0.8)
        self.ate(0.3)
        self.play(FadeIn(dv, shift=0.1 * UP), run_time=0.8)
        self.ate(0.55)
        self.play(Create(r), FadeIn(fm, shift=0.1 * UP), run_time=1.2)
        self.ate(0.97)
