def _arr_lata_pesada(W=340, H=170):
    ys = (H - 0.5 - np.arange(H)) / H
    xs = -1.0 + 2.0 * (np.arange(W) + 0.5) / W
    S, Z = np.meshgrid(np.abs(xs), ys)
    r = np.clip(np.sqrt(S * S + Z * Z) / math.sqrt(2), 0.0, 1.0)
    t = np.power(r, 0.85)[..., None]
    return (hx(RAMP0) * (1.0 - t) + hx(CI) * t).round().astype(np.uint8)


