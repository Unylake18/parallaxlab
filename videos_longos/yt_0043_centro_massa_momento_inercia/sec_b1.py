"""yt_0043 · Lote PB1: B1-1 (sistema de pontos ao corpo), B1-2 (plano que equilibra, C1, GM1–GM2), B1-3 (simetria e contraexemplo, C2, GM3)."""
from k43 import *  # noqa: F401,F403

COL = 1020


class PB1(B43):
    ANTES = "CENTRO DE MASSA E MOMENTO DE INÉRCIA"

    def corpo(self):
        # ── B1-1 · do sistema de pontos ao corpo (alvos 03 e 04) ───────────────────────────────────────────
        self.an("B1-1")
        pal1 = self.palco("cmPontos", cam_alvo("b11a"), b1=0.0, b2=0.0, b3=0.0, cm=0.0)
        rx1 = self.rot3(pal1, "ex", r"\X", size=38, ancora="c")
        ry1 = self.rot3(pal1, "ey", r"\Y", size=38, ancora="c")
        rz1 = self.rot3(pal1, "ez", r"\Z", size=38, ancora="c")
        self.add(pal1.fundo, rx1, ry1, rz1)
        pronto(rx1)
        pronto(ry1)
        pronto(rz1)
        self.titulo("DO SISTEMA DE PONTOS AO CORPO")

        self.gat("três bolinhas")
        rm1 = self.rot3(pal1, "m1", "m_1=1", dx=22, dy=-26, size=30, ancora="l")
        rm2 = self.rot3(pal1, "m2", "m_2=3", dx=22, dy=-26, size=30, ancora="l")
        rm3 = self.rot3(pal1, "m3", "m_3=2", dx=22, dy=-26, size=30, ancora="l")
        self.play(*pal1.anim(rt=0.9, b1=1.0, b2=1.0, b3=1.0), FadeIn(rm1[0]), FadeIn(rm2[0]), FadeIn(rm3[0]))
        self.pena(rm1.f, rm2.f, rm3.f)

        self.gat("É uma média das posições")
        f1 = TC(r"\xb=\dfrac{\sum m_i\,\X_i}{\sum m_i}", COL, 260, 54)
        self.pena(f1)
        self.col("B1-1a", f1)

        self.gat("a mesma média, três vezes")
        f2 = TC(r"\yb=\dfrac{\sum m_i\,\Y_i}{\sum m_i}", COL, 440, 50)
        f3 = TC(r"\zb=\dfrac{\sum m_i\,\Z_i}{\sum m_i}", COL, 610, 50)
        l1 = leg("A MESMA MÉDIA, TRÊS VEZES", COL, 760, GEO, "left", 30)
        self.pena(f2)
        self.pena(f3)
        self.pena(l1)
        self.col("B1-1a", f2, f3, l1, chips=1)

        self.gat("o ponto de equilíbrio fica mais perto da mais pesada")
        qcm = pal1.pt("cm")
        cmm = cm_mark(qcm[0], qcm[1])
        sq1, lg1 = legq("#B9A6FF", "O CENTRO DE MASSA FICA MAIS PERTO DA MAIS PESADA", 120, 1020, 30)
        self.play(*pal1.anim(rt=0.4, cm=1.0), FadeIn(cmm), FadeIn(sq1))
        self.pena(lg1)
        self.marca("03_B1-1a", agora=True)

        self.gat("Num corpo de verdade")
        pal2 = self.palco("lataCel", cam_alvo("b11b"), cel=1.0, fios=1.0)
        rx2 = self.rot3(pal2, "ex", r"\X", size=38, ancora="c")
        ry2 = self.rot3(pal2, "ey", r"\Y", size=38, ancora="c")
        rz2 = self.rot3(pal2, "ez", r"\Z", size=38, ancora="c")
        rpx = self.rot3(pal2, "px", r"\X", dy=30, size=30, ancora="c")
        rpy = self.rot3(pal2, "py", r"\Y", dx=22, dy=20, size=30, ancora="l")
        pronto(rx2)
        pronto(ry2)
        pronto(rz2)
        pronto(rpx)
        pronto(rpy)
        cg1, cf1, cm1_ = chip(r"\xb=\dfrac{\sum m_i\X_i}{\sum m_i}", COL, 150, 28)
        # R12/R14: o 3D antigo sai e o novo (com os rótulos presos a ele) entra no MESMO play: nenhum quadro de palco vazio
        pal2.fundo.op.set_value(0.0)
        self.add(pal2.fundo)
        self.sai(pal1.fundo, rx1, ry1, rz1, rm1, rm2, rm3, cmm, sq1, lg1, f1, f2, f3, l1, rt=0.4,
                 extra=[pal2.fundo.op.animate.set_value(1.0), *[FadeIn(r_) for r_ in (rx2, ry2, rz2, rpx, rpy)]])
        self.chip_pena(cg1, cf1, cm1_)
        self.col("B1-1b", cg1, chips=1)

        self.gat("a massa do pedacinho é quase rô vezes delta V")
        rcel = self.rot3(pal2, "cel", r"\Delta m\approx\de\,\Delta V", dx=95, dy=0, size=30, ancora="l")
        g1 = TC(r"\Delta m_i\approx\de(P_i)\,\Delta V_i", COL, 270, 46)
        self.play(FadeIn(rcel[0]))
        self.pena(rcel.f, g1)
        self.col("B1-1b", g1, chips=1)

        self.gat("vira integral tripla")
        # I7: coluna renovada depois de Δm = ρ ΔV; o resultado que continua sendo usado vira chip no topo (voa da linha original)
        cgD, cfD, molD = chip(r"\Delta m\approx\de\,\Delta V", COL, 150, 28)
        self.chip_voo(cgD, cfD, molD, g1, extra=[FadeOut(cg1), FadeOut(g1)], rt=0.9, nota="chip Δm ≈ ρΔV voa de g1")
        self.remove(cg1, g1)
        self.col_zera("B1-1b")
        self.col("B1-1b", cgD, chips=1)
        g2 = TC(r"\sum \X_i\,\de(P_i)\,\Delta V_i\ \longrightarrow\ \iiint \X\,\de\,dV", COL, 380, 44)
        self.pena(g2)
        self.col("B1-1b", g2, chips=1)

        self.gat("a massa total")
        g3 = TC(r"M=\iiint \de\,dV", COL, 490, 46)
        self.pena(g3)
        self.col("B1-1b", g3, chips=1)

        self.gat("Dividindo pela massa")
        g4 = TC(r"\xb=\dfrac1M\iiint\X\,\de\,dV", COL, 630, 50)
        lg2 = leg("ȳ E z̄: O MESMO, COM y E COM z", COL, 720, GEO, "left", 28)
        self.pena(g4)
        self.pena(lg2)
        self.col("B1-1b", g4, lg2, chips=2)

        self.gat("têm nome")
        g5 = TC(r"\Mxy=\iiint\Z\,\de\,dV", COL, 820, 46)
        lg3 = leg("MOMENTO EM RELAÇÃO AO PLANO xy", COL, 900, GEO, "left", 28)
        lg4 = leg("OS OUTROS DOIS PLANOS: O MESMO, COM x E COM y", COL, 945, GEO, "left", 28)
        self.pena(g5)
        self.pena(lg3, lg4)
        self.col("B1-1b", g5, lg3, lg4, chips=3)
        self.marca("04_B1-1b")

        # ── B1-2 · o que o centro de massa garante (alvo 05, C1, GM1–GM2) ─────────────────────────────────
        self.an("B1-2")
        self.sai(pal2.fundo, rx2, ry2, rz2, rpx, rpy, rcel, cgD, g2, g3, g4, lg2, g5, lg3, lg4, rt=0.4)
        pal3 = self.palco("lataPlano", cam_alvo("b12"), plano=0.0, celA=0.0, celB=0.0, fios=0.0)
        rz3 = self.rot3(pal3, "ez", r"\Z", size=38, ancora="c")
        pronto(rz3)
        self.add(pal3.fundo, rz3)
        self.titulo("O QUE O CENTRO DE MASSA GARANTE", rt=0.35)

        self.gat("um plano deitado na altura z barra")
        rplano = self.rot3(pal3, "ponta", r"\Z=\zb", dx=34, dy=0, size=32, ancora="l")        # R2: o nome do plano, na ponta direita, fora do plano
        rplano.f.set_color(MEN)
        self.play(*pal3.anim(rt=0.7, plano=1.0), FadeIn(rplano[0]))
        self.pena(rplano.f)

        self.gat("a distância de cada pedaço até esse plano")
        rcA = self.rot3(pal3, "cA", "+", dx=26, dy=-50, size=34, ancora="l")
        rcB = self.rot3(pal3, "cB", r"-", dx=34, dy=6, size=34, ancora="l")
        rfA = self.rot3(pal3, "fA", r"\Z-\zb", dx=-10, dy=-2, size=28, ancora="l")
        self.play(*pal3.anim(rt=0.8, celA=1.0, celB=1.0, fios=1.0), FadeIn(rcA[0]), FadeIn(rcB[0]), FadeIn(rfA[0]))
        self.pena(rcA.f, rcB.f, rfA.f)

        self.gat("Soma tudo")
        self.degrau("C1.1", "iiint (z - zbar) rho dV")
        c11 = TC(r"\iiint(\Z-\zb)\,\de\,dV", COL, 200, 52)
        self.pena(c11)
        self.col("B1-2", c11)

        self.gat("separa em duas integrais")
        self.degrau("C1.2", "= iiint z rho dV - zbar iiint rho dV")
        c12 = L([("eq", "="), ("i1", r"\iiint\Z\,\de\,dV"), ("m", "-"), ("zb", r"\zb"), ("i2", r"\iiint\de\,dV")], COL, 330, 48)
        self.pena(c12)
        self.col("B1-2", c12)

        self.gat("a primeira é o momento")
        self.degrau("C1.3", "= M_xy - zbar M")
        c13 = L([("eq", "="), ("mxy", r"\Mxy"), ("m", "-"), ("zb", r"\zb"), ("M", "M")], COL, 450, 50)
        self.gm(1, c12, c13, [("eq", "eq"), ("i1", "mxy"), ("m", "m"), ("zb", "zb"), ("i2", "M")], rt=0.9, copia=True, nota="GM1: integrais -> M_xy - zbar M")
        self.col("B1-2", c13)

        self.gat("é exatamente M vezes z barra")
        self.degrau("C1.4", "= M zbar - zbar M = 0")
        c14 = L([("eq", "="), ("mzb", r"M\,\zb"), ("m", "-"), ("zb", r"\zb"), ("M", "M"), ("z0", "=0")], COL, 570, 52)
        self.gm(2, c13, c14, [("eq", "eq"), ("mxy", "mzb"), ("m", "m"), ("zb", "zb"), ("M", "M")], rt=0.9, copia=True, nota="GM2: M_xy - zbar M -> M zbar - zbar M = 0")
        self.col("B1-2", c14)

        self.gat("equilibra o que está abaixo")
        l_eq1 = leg("O QUE ESTÁ ACIMA DO PLANO", COL, 700, MEN, "left", 32)
        l_eq2 = leg("EQUILIBRA O QUE ESTÁ ABAIXO", COL, 745, MEN, "left", 32)
        self.pena(l_eq1, l_eq2)
        self.col("B1-2", l_eq1, l_eq2, chips=2)
        self.marca("05_B1-2")

        # ── B1-3 · simetria e contraexemplo (alvos 06 e 07, C2, GM3) ──────────────────────────────────────
        self.an("B1-3")
        self.sai(pal3.fundo, rz3, rplano, rcA, rcB, rfA, c11, c12, c13, c14, l_eq1, l_eq2, rt=0.35)
        pal4 = self.palco("lataSim", cam_alvo("b13a"), gemeos=0.0, fios=0.0)
        self.add(pal4.fundo)
        self.titulo("SIMETRIA", rt=0.3)

        self.gat("nem toda conta precisa ser feita")
        rcA4 = self.rot3(pal4, "cA", r"\X", dx=12, dy=0, size=34, ancora="l")
        rcB4 = self.rot3(pal4, "cB", r"-\X", dx=-24, dy=0, size=34, ancora="r")      # I4: sai de cima do eixo z, para a esquerda da célula
        sq4, lg4 = legq(LI, "GÊMEOS: MESMA MASSA, x COM SINAL TROCADO", 120, 1020, 30)
        self.play(*pal4.anim(rt=0.7, gemeos=1.0, fios=1.0), FadeIn(rcA4[0]), FadeIn(rcB4[0]), FadeIn(sq4))
        self.pena(rcA4.f, rcB4.f, lg4)

        self.gat("a densidade não depende do ângulo")
        self.degrau("C2.1", "rho = rho(s, z) (nao depende de theta)")
        s1 = mixl([("m", r"\de=\de(\S,\Z)"), ("t", "(NÃO DEPENDE DE θ)", GEO)], COL, 190, 46)
        self.pena(s1)
        self.col("B1-3a", s1)

        self.gat("x é s cosseno de téta")
        self.degrau("C2.2", "M_yz = int int (int_0^2pi cos theta dtheta) s^2 rho ds dz")
        s2 = L([("pre", r"\Myz=\int\!\!\int\Big(\int_0^{2\pi}"), ("cos", r"\cos\T\,\dT"), ("pos", r"\Big)\,\S^2\de\,\dS\,\dZ")], COL, 320, 44)
        self.escreve(s2, voos=[(rcA4.f, "cos")], rt_voo=0.9, nota="x da placa -> cos theta")
        self.col("B1-3a", s2)

        self.gat("a integral do cosseno numa volta inteira")
        self.degrau("C2.3", "int_0^2pi cos theta dtheta = [sen theta]_0^2pi = 0 - 0 = 0")
        s3 = TC(r"\int_0^{2\pi}\cos\T\,\dT=\Big[\sen\T\Big]_0^{2\pi}=0-0=0", COL, 460, 46)
        self.pena(s3)
        self.col("B1-3a", s3)

        self.gat("x barra é zero")
        self.degrau("C2.4", "=> xbar = 0; igual para y: ybar = 0")
        s4 = mixl([("m", r"\Rightarrow\ \xb=0"), ("t", "IGUAL PARA y:", GEO), ("m", r"\yb=0")], COL, 580, 46)
        self.pena(s4)
        self.col("B1-3a", s4)

        self.gat("o centro de massa está no eixo")
        ct4 = cartao(COL, 626, 840, 146)
        lc1 = leg("CORPO E DENSIDADE GIRAM JUNTOS", COL + 24, 700, MEN, "left", 32)
        lc2 = leg("⇒ CENTRO DE MASSA NO EIXO", COL + 24, 748, MEN, "left", 32)
        self.dentro(ct4._painel, lc1, lc2)
        self.pena(lc1, lc2, extra=[FadeIn(ct4)])
        self.col("B1-3a", ct4, chips=1)
        self.marca("06_B1-3a", agora=True)

        self.gat("E se a densidade fosse um mais x")
        # Corte limpo de lataSim para lataSim2 (sem sobreposição dos dois palcos)
        pal5 = self.palco("lataSim2", cam_alvo("b13b"), lado=1.0, disco=0.0)
        rcA4.clear_updaters()
        rcB4.clear_updaters()
        pal5.prende(rcA4, "cA", 12, 0, "l")
        pal5.prende(rcB4, "cB", -24, 0, "r")
        self.remove(pal4.fundo)
        self.add(pal5.fundo)
        self.sobe_sai(s1, s2, s3, s4, ct4, lc1, lc2, sq4, lg4, rt=0.35)
        self.titulo("SIMETRIA: OS DOIS PRECISAM GIRAR", rt=0.3)
        sq5, lg5 = legq("#E9FF9E", "ρ = 1 + x: O LADO DO x > 0 PESA MAIS", 120, 1020, 30)
        self.degrau("C2.5", "rho = 1 + x (cilindro R = 1, h = 1)")
        cg5, cf5, cm5_ = chipm([("m", r"\de=1+\X"), ("t", "CILINDRO", GEO), ("m", r"R=1,\ h=1")], COL, 150, 30)
        self.play(FadeIn(sq5), *pal5.anim(rt=0.6, disco=1.0), run_time=0.6)         # A2: o disco lima nasce no gatilho de ρ = 1 + x
        self.chip_pena(cg5, cf5, cm5_)
        self.pena(lg5)
        self.col("B1-3b", cg5, chips=1)

        self.gat("A massa continua pi")
        self.degrau("C2.6", "M = iiint (1 + x) dV = iiint dV + iiint x dV")
        u1 = TC(r"M=\iiint(1+\X)\,dV=\iiint dV+\iiint\X\,dV", COL, 280, 40)
        self.pena(u1)
        self.col("B1-3b", u1, chips=1)
        self.degrau("C2.6b", "= pi 1^2 1 + 0 = pi   (iiint x dV = 0 pela simetria)")
        u1b = mixl([("m", r"=\pi\cdot1^2\cdot1+0=\pi\quad(\iiint\X\,dV=0)"), ("t", "SIMETRIA", GEO)], COL + 20, 372, 38)
        self.pena(u1b)
        self.col("B1-3b", u1b, chips=1)

        self.gat("o x ao quadrado")
        self.degrau("C2.7", "M_yz = iiint x(1 + x) dV = iiint x dV + iiint x^2 dV")
        u2a = L([("pre", r"\Myz="), ("int", r"\iiint\X(1+\X)\,dV")], COL, 470, 40)
        u2b = L([("pre", r"\Myz=\iiint\X(1+\X)\,dV="), ("i1", r"\iiint\X\,dV+"), ("i2", r"\iiint\X^2\,dV")], COL, 470, 40)
        self.pena(u2a)
        self.gm(3, u2a, u2b, [("pre", "pre"), ("int", "i2")], rt=0.7, nota="GM3: iiint x(1+x)dV -> iiint x dV + iiint x^2 dV")
        self.col("B1-3b", u2b, chips=1)
        self.degrau("C2.7b", "x^2 = s^2 cos^2 theta")
        u2c = TC(r"\X^2=\S^2\cos^2\T", COL, 565, 40)
        self.pena(u2c)
        self.col("B1-3b", u2c, chips=1)
        self.degrau("C2.7c", "x^2 s = s^3 cos^2 theta (s lima: o fator)")
        u2d = TC(r"\X^2\cdot\Js=\S^3\cos^2\T", COL, 660, 40)
        self.pena(u2d)
        self.col("B1-3b", u2d, chips=1)

        # I7 + R5: a coluna renova; M = π, M_yz = 0 + ∭x² dV e x²·s = s³cos²θ viram chips no topo, voando das linhas originais
        cg6, cf6, cm6_ = chip(r"\X^2\cdot\Js=\S^3\cos^2\T", COL, 235, 26)
        xr = pxof(cg6.get_right())[0] + 16
        cgM, cfM, cmM = chip(r"M=\pi", xr, 235, 26)
        xr = pxof(cgM.get_right())[0] + 16
        cgY, cfY, cmY = chip(r"\Myz=0+\iiint\X^2\,dV", xr, 235, 26)
        self.chips_voo([(cg6, cf6, cm6_, u2d), (cgM, cfM, cmM, u1b), (cgY, cfY, cmY, u2b)],
                       extra=[FadeOut(x) for x in (u1, u1b, u2b, u2c, u2d)], rt=0.9, nota="chips x²·s, M=π, M_yz voam das linhas")
        self.remove(u1, u1b, u2a, u2b, u2c, u2d)
        self.col_zera("B1-3b")
        self.col("B1-3b", cg5, cg6, cgM, cgY, chips=4)

        self.degrau("C2.8", "iiint x^2 dV = int_0^2pi cos^2 theta dtheta * int_0^1 s^3 ds * int_0^1 dz")
        u3 = TC(r"\iiint\X^2dV=\int_0^{2\pi}\!\cos^2\T\,\dT\cdot\!\int_0^1\!\S^3\dS\cdot\!\int_0^1\!\dZ", COL, 335, 40)
        self.pena(u3)
        self.col("B1-3b", u3, chips=4)
        self.degrau("C2.8a", "int_0^2pi cos^2 theta dtheta = [theta/2 + sen 2theta/4]_0^2pi = (pi + 0) - (0 + 0) = pi")
        w1 = TC(r"\int_0^{2\pi}\cos^2\T\,\dT=\Big[\dfrac{\T}{2}+\dfrac{\sen2\T}{4}\Big]_0^{2\pi}=(\pi+0)-(0+0)=\pi", COL, 440, 34)
        self.pena(w1)
        self.col("B1-3b", w1, chips=4)
        self.degrau("C2.8b", "int_0^1 s^3 ds = [s^4/4]_0^1 = 1/4 - 0 = 1/4")
        w2 = TC(r"\int_0^1\S^3\,\dS=\Big[\dfrac{\S^4}{4}\Big]_0^1=\dfrac14-0=\dfrac14", COL, 535, 34)
        self.pena(w2)
        self.col("B1-3b", w2, chips=4)
        self.degrau("C2.8c", "int_0^1 dz = [z]_0^1 = 1 - 0 = 1")
        w3 = TC(r"\int_0^1\dZ=\Big[\Z\Big]_0^1=1-0=1", COL, 625, 34)
        self.pena(w3)
        self.col("B1-3b", w3, chips=4)
        self.degrau("C2.8d", "iiint x^2 dV = pi * 1/4 * 1 = pi/4")
        u4 = L([("lhs", r"\iiint\X^2dV=\pi\cdot\dfrac14\cdot1="), ("res", r"\dfrac{\pi}{4}")], COL, 725, 42)
        self.pena(u4)
        self.col("B1-3b", u4, chips=4)

        self.gat("um quarto para a direita")
        self.degrau("C2.9", "xbar = M_yz / M = (pi/4)/pi = 1/4   (pi/4 voa do resultado, pi voa do chip M)")
        u5 = L([("lhs", r"\xb=\dfrac{\Myz}{M}="), ("fr", r"\dfrac{\pi/4}{\pi}"), ("res", r"=\dfrac14")], COL, 845, 48)
        sm5, st5 = selo("A DENSIDADE QUEBROU A SIMETRIA", COL, 975, AL, 30)
        ix_fr = sel(u5, "fr")
        self.escreve(u5, voos=[(gl(u4, "res"), ix_fr[:3]), (VGroup(cfM[0][-1]), [ix_fr[4]])], rt_voo=0.9, nota="x̄: π/4 voa do resultado, π voa do chip M")
        self.pena(st5, extra=[Create(sm5)])
        self.col("B1-3b", u5, st5, chips=4)
        self.marca("07_B1-3b")

        self.sai_fim()
