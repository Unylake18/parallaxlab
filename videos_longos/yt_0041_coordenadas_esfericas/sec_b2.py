def mini(nome, X, Y, w=110):
    """Miniatura (recorte do PNG 3D do H2) num cartão opaco: canto superior esquerdo em (X, Y) px."""
    arq = MINI / f"mini_{nome}.png"
    if not arq.exists():
        return None
    from PIL import Image
    a = np.array(Image.open(arq).convert("RGBA"))
    h = w * a.shape[0] / a.shape[1]
    im = img_px(a, X, Y, w, h, z=6)
    return im


